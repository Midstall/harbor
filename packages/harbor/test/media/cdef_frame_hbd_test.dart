    unawaited(Simulator.run());
    await clk.nextPosedge;
    return (mod: mod, clk: clk, drv: drv);
  }

  Future<(List<List<int>>, List<List<int>>?, List<List<int>>?)> runHw(
    _Frame f,
    HarborCdefFrame mod,
    Logic clk,
    Map<String, Logic> drv,
    List<List<int>> py,
    List<List<int>>? pu,
    List<List<int>>? pv,
    List<List<int>> miSkip,
    List<int> unitIdx,
    int cdefDamping,
    List<int> yPri,
    List<int> ySec,
    List<int> uvPri,
    List<int> uvSec,
  ) async {
    drv['plane_y']!.inject(_packPlane(py, f.lumaW, f.lumaH, f.bd));
    if (f.numPlanes > 1) {
      drv['plane_u']!.inject(_packPlane(pu!, f.chW, f.chH, f.bd));
      drv['plane_v']!.inject(_packPlane(pv!, f.chW, f.chH, f.bd));
      drv['uv_pri']!.inject(_packTable(uvPri, f.numEntries));
      drv['uv_sec']!.inject(_packTable(uvSec, f.numEntries));
    }
    drv['skip']!.inject(_packSkip(miSkip, f.miRows, f.miCols));
    drv['cdef_idx']!.inject(_packIdx(unitIdx, f.idxW));
    drv['y_pri']!.inject(_packTable(yPri, f.numEntries));
    drv['y_sec']!.inject(_packTable(ySec, f.numEntries));
    drv['cdef_damping']!.inject(cdefDamping);
    await clk.nextPosedge;
    final oy = _unpackPlane(
      mod.output('out_y').value.toBigInt(),
      f.lumaW,
      f.lumaH,
      f.bd,
    );
    if (f.numPlanes == 1) return (oy, null, null);
    final ou = _unpackPlane(
      mod.output('out_u').value.toBigInt(),
      f.chW,
      f.chH,
      f.bd,
    );
    final ov = _unpackPlane(
      mod.output('out_v').value.toBigInt(),
      f.chW,
      f.chH,
      f.bd,
    );
    return (oy, ou, ov);
  }

  // Mid-range directional plane: base ~ 2^(bd-1), a directional step, and small
  // per-pixel noise. Values stay comfortably inside [0, 2^bd-1] so CDEF output
  // never leaves the pixel range.
  List<List<int>> mkPlane(
    Random rng,
    int w,
    int h,
    int bd, {
    bool flat = false,
  }) {
    final int mid = 1 << (bd - 1);
    final base = mid - 60 + rng.nextInt(30);
    final step = 40 + rng.nextInt(40);
    return [
      for (var r = 0; r < h; r++)
        [
          for (var c = 0; c < w; c++)
            (flat
                    ? base + rng.nextInt(7) - 3
                    : ((r + c) < (w + h) ~/ 2 ? base : base + step) +
                          rng.nextInt(13) -
                          6)
                .clamp(0, (1 << bd) - 1),
        ],
    ];
  }

  // Shared per-geometry runner: builds one HW instance and sweeps scenarios.
  Future<void> sweep(
    _Frame f,
    int seed,
    int iters,
    List<List<List<int>>> gYs,
    List<List<List<int>>> gUs,
    List<List<List<int>>> gVs,
  ) async {
    final b = await buildMod(f);
    final rng = Random(seed);
    for (var iter = 0; iter < iters; iter++) {
      final py = mkPlane(rng, f.lumaW, f.lumaH, f.bd, flat: iter % 5 == 0);
      final pu = f.numPlanes > 1 ? mkPlane(rng, f.chW, f.chH, f.bd) : null;
      final pv = f.numPlanes > 1 ? mkPlane(rng, f.chW, f.chH, f.bd) : null;

      // Skip mask: all-off (iter 0), all-on pass-through (iter 1), else random.
      final miSkip = [
        for (var r = 0; r < f.miRows; r++)
          [
            for (var c = 0; c < f.miCols; c++)
              iter == 0
                  ? 0
                  : iter == 1
                  ? 1
                  : (rng.nextInt(3) == 0 ? 1 : 0),
          ],
      ];

      // Both primary AND secondary strengths non-zero (>=1): clip path, and
      // small enough that level << coeffShift <= 240.
      final yPri = [for (var e = 0; e < f.numEntries; e++) 1 + rng.nextInt(6)];
      final ySec = [for (var e = 0; e < f.numEntries; e++) 1 + rng.nextInt(3)];
      final uvPri = [for (var e = 0; e < f.numEntries; e++) 1 + rng.nextInt(6)];
      final uvSec = [for (var e = 0; e < f.numEntries; e++) 1 + rng.nextInt(3)];
      final cdefDamping = 3 + rng.nextInt(4); // 3..6

      final idx = f.numEntries == 1 ? 0 : rng.nextInt(f.numEntries);
      final unitIdx = [for (var u = 0; u < f.numUnits; u++) idx];

      final gy = gYs[iter];
      final gu = f.numPlanes > 1 ? gUs[iter] : null;
      final gv = f.numPlanes > 1 ? gVs[iter] : null;
      final (oy, ou, ov) = await runHw(
        f,
        b.mod,
        b.clk,
        b.drv,
        py,
        pu,
        pv,
        miSkip,
        unitIdx,
        cdefDamping,
        yPri,
        ySec,
        uvPri,
        uvSec,
      );

      expect(
        oy,
        equals(gy),
        reason:
            'Y bd=${f.bd} iter=$iter idx=$idx damp=$cdefDamping '
            'yPri=$yPri ySec=$ySec',
      );
      if (f.numPlanes > 1) {
        expect(
          ou,
          equals(gu),
          reason:
              'U bd=${f.bd} iter=$iter idx=$idx '
              'uvPri=$uvPri uvSec=$uvSec',
        );
        expect(ov, equals(gv), reason: 'V bd=${f.bd} iter=$iter idx=$idx');
      }
    }
    await Simulator.endSimulation();
  }

  // Multi-block 4:2:0 (16x8 luma => two adjacent 8x8 luma blocks, so an interior
