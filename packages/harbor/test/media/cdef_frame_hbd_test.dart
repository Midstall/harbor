// High-bit-depth (10/12-bit) driver for HarborCdefFrame vs the SW `cdefFrame`
// oracle. Mirrors test/media/cdef_frame_test.dart, but:
//   * planes are packed/unpacked at `bd` bits per pixel (mask (1<<bd)-1),
//   * pixel content is mid-range (~2^(bd-1)) so CDEF output stays inside
//     [0, 2^bd-1] and the HW `& (2^bd-1)` store agrees with the SW `& 0xffff`
//     high-bit-depth store,
//   * both primary and secondary strengths are non-zero so the clipping path is
//     exercised (and the small strengths keep `level << coeffShift <= 240`),
//   * sw.cdefFrame is called with bitDepth: bd, exercising coeff_shift in the
//     direction search, the strength `<< coeff_shift`, the `+ coeff_shift`
//     damping and the `pri[coeff_shift]` primary-tap selection.

class _Frame {
  _Frame(
    this.lumaW,
    this.lumaH,
    this.subX,
    this.subY,
    this.numPlanes,
    this.cdefBits,
    this.bd,
  );
  final int lumaW, lumaH, subX, subY, numPlanes, cdefBits, bd;
  int get chW => numPlanes > 1 ? (lumaW + subX) >> subX : 0;
  int get chH => numPlanes > 1 ? (lumaH + subY) >> subY : 0;
  int get miRows => lumaH ~/ 4;
  int get miCols => lumaW ~/ 4;
  int get nvfb => (miRows + 15) ~/ 16;
  int get nhfb => (miCols + 15) ~/ 16;
  int get numUnits => nvfb * nhfb;
  int get numEntries => 1 << cdefBits;
  int get idxW => cdefBits == 0 ? 1 : cdefBits;
  int get pxMask => (1 << bd) - 1;
}

BigInt _packPlane(List<List<int>> plane, int w, int h, int bd) {
  final mask = BigInt.from((1 << bd) - 1);
  var v = BigInt.zero;
  for (var r = 0; r < h; r++) {
    for (var c = 0; c < w; c++) {
      v |= (BigInt.from(plane[r][c]) & mask) << ((r * w + c) * bd);
    }
  }
  return v;
}

List<List<int>> _unpackPlane(BigInt v, int w, int h, int bd) {
  final mask = BigInt.from((1 << bd) - 1);
  return [
    for (var r = 0; r < h; r++)
      [for (var c = 0; c < w; c++) ((v >> ((r * w + c) * bd)) & mask).toInt()],
  ];
}

BigInt _packSkip(List<List<int>> miSkip, int miRows, int miCols) {
  var v = BigInt.zero;
  for (var r = 0; r < miRows; r++) {
    for (var c = 0; c < miCols; c++) {
      if (miSkip[r][c] != 0) v |= BigInt.one << (r * miCols + c);
    }
  }
  return v;
}

BigInt _packTable(List<int> tab, int numEntries) {
  var v = BigInt.zero;
  for (var e = 0; e < numEntries; e++) {
    v |= BigInt.from(tab[e] & 0xFF) << (e * 8);
  }
  return v;
}

BigInt _packIdx(List<int> unitIdx, int idxW) {
  var v = BigInt.zero;
  for (var u = 0; u < unitIdx.length; u++) {
    v |= BigInt.from(unitIdx[u]) << (u * idxW);
  }
  return v;
}

