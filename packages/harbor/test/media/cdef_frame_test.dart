    for (final name in mod.inputs.keys) {
      final w = mod.input(name).width;
      final l = Logic(name: 'drv_$name', width: w);
      mod.input(name).srcConnection! <= l;
      drv[name] = l;
    }
    await mod.build();
    Simulator.setMaxSimTime(600000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    return (mod: mod, clk: clk, drv: drv);
  }

  // Injects one scenario and returns the HW-filtered planes.
  Future<(List<List<int>>, List<List<int>>?, List<List<int>>?)> _runHw(
    _Frame f,
    HarborCdefFrame mod,
    Logic clk,
    Map<String, Logic> drv,
    List<List<int>> py,
    List<List<int>>? pu,
    List<List<int>>? pv,
    List<List<int>> miSkip,
    List<int> unitIdx,
    int cdefDamping,
    List<int> yPri,
    List<int> ySec,
    List<int> uvPri,
    List<int> uvSec,
  ) async {
    drv['plane_y']!.inject(_packPlane(py, f.lumaW, f.lumaH));
    if (f.numPlanes > 1) {
      drv['plane_u']!.inject(_packPlane(pu!, f.chW, f.chH));
      drv['plane_v']!.inject(_packPlane(pv!, f.chW, f.chH));
      drv['uv_pri']!.inject(_packTable(uvPri, f.numEntries));
      drv['uv_sec']!.inject(_packTable(uvSec, f.numEntries));
    }
    drv['skip']!.inject(_packSkip(miSkip, f.miRows, f.miCols));
    drv['cdef_idx']!.inject(_packIdx(unitIdx, f.idxW));
    drv['y_pri']!.inject(_packTable(yPri, f.numEntries));
    drv['y_sec']!.inject(_packTable(ySec, f.numEntries));
    drv['cdef_damping']!.inject(cdefDamping);
    await clk.nextPosedge;
    final oy = _unpackPlane(
      mod.output('out_y').value.toBigInt(),
      f.lumaW,
      f.lumaH,
    );
    if (f.numPlanes == 1) return (oy, null, null);
    final ou = _unpackPlane(mod.output('out_u').value.toBigInt(), f.chW, f.chH);
    final ov = _unpackPlane(mod.output('out_v').value.toBigInt(), f.chW, f.chH);
    return (oy, ou, ov);
  }

  // Random directional plane so the direction search & variance vary.
  List<List<int>> _mkPlane(Random rng, int w, int h, {bool flat = false}) {
    final base = 60 + rng.nextInt(120);
    return [
      for (var r = 0; r < h; r++)
        [
          for (var c = 0; c < w; c++)
            flat
                ? (base + rng.nextInt(7) - 3).clamp(0, 255)
                : (((r + c) < (w + h) ~/ 2 ? base : base + 50) +
                          rng.nextInt(13) -
                          6) &
                      0xFF,
        ],
    ];
  }

  group('HarborCdefFrame 16x16 4:2:0, cdefBits=2 (Y+chroma, edge sentinel)', () {
    final f = _Frame(16, 16, 1, 1, 3, 2);

    test('bit-exact vs SW cdefFrame across idx/skip/strengths', () async {
      final b = await _buildMod(f);
      final rng = Random(0xC0FFEE);

      for (var iter = 0; iter < 24; iter++) {
        final py = _mkPlane(rng, f.lumaW, f.lumaH, flat: iter % 5 == 0);
        final pu = _mkPlane(rng, f.chW, f.chH);
        final pv = _mkPlane(rng, f.chW, f.chH);

        // Per-mi skip: random, but force all-off (iter 0) and all-on (iter 1).
        final miSkip = [
          for (var r = 0; r < f.miRows; r++)
            [
              for (var c = 0; c < f.miCols; c++)
                iter == 0
                    ? 0
                    : iter == 1
                    ? 1
                    : (rng.nextInt(3) == 0 ? 1 : 0),
            ],
        ];

        // Strength tables (numEntries=4). Include zeros to hit the disabled
        // primary/secondary and pass-through paths.
        final yPri = [for (var e = 0; e < f.numEntries; e++) rng.nextInt(16)];
        final ySec = [for (var e = 0; e < f.numEntries; e++) rng.nextInt(5)];
        final uvPri = [for (var e = 0; e < f.numEntries; e++) rng.nextInt(16)];
        final uvSec = [for (var e = 0; e < f.numEntries; e++) rng.nextInt(5)];
        if (iter == 2) {
          for (var e = 0; e < f.numEntries; e++) {
            yPri[e] = 0;
            ySec[e] = 0;
            uvPri[e] = 0;
            uvSec[e] = 0;
          }
        }
        final cdefDamping = 3 + rng.nextInt(4); // 3..6

        // One unit for a 16x16 frame, vary the selected index.
        final idx = rng.nextInt(f.numEntries);
        final unitIdx = [idx];

        final gy = _g1y[iter];
        final gu = _g1u[iter];
        final gv = _g1v[iter];
        final (oy, ou, ov) = await _runHw(
          f,
          b.mod,
          b.clk,
          b.drv,
          py,
          pu,
          pv,
          miSkip,
          unitIdx,
          cdefDamping,
          yPri,
          ySec,
          uvPri,
          uvSec,
        );

        expect(
          oy,
          equals(gy),
          reason:
              'Y iter=$iter idx=$idx damp=$cdefDamping '
              'yPri=$yPri ySec=$ySec skip=$miSkip',
        );
        expect(ou, equals(gu), reason: 'U iter=$iter idx=$idx');
        expect(ov, equals(gv), reason: 'V iter=$iter idx=$idx');
      }
      await Simulator.endSimulation();
    });
  });

