// Test driver for HarborCdefFrame vs the software `cdefFrame` oracle.
//
// HarborCdefFrame is a purely combinational full-frame CDEF pass, each built
// instance is expensive to elaborate, so we build ONE instance per geometry and
// amortise it over many injected scenarios (strength index, skip pattern,
// strengths incl. zeros, pixel content). Frames are intentionally tiny (16x16 /
// 8x8 luma) so every block also exercises the frame-edge CDEF_VERY_LARGE
// sentinel path (all blocks touch a frame boundary).

class _Frame {
  _Frame(
    this.lumaW,
    this.lumaH,
    this.subX,
    this.subY,
    this.numPlanes,
    this.cdefBits,
  );
  final int lumaW, lumaH, subX, subY, numPlanes, cdefBits;
  int get chW => numPlanes > 1 ? (lumaW + subX) >> subX : 0;
  int get chH => numPlanes > 1 ? (lumaH + subY) >> subY : 0;
  int get miRows => lumaH ~/ 4;
  int get miCols => lumaW ~/ 4;
  int get nvfb => (miRows + 15) ~/ 16;
  int get nhfb => (miCols + 15) ~/ 16;
  int get numUnits => nvfb * nhfb;
  int get numEntries => 1 << cdefBits;
  int get idxW => cdefBits == 0 ? 1 : cdefBits;
}

BigInt _packPlane(List<List<int>> plane, int w, int h) {
  var v = BigInt.zero;
  for (var r = 0; r < h; r++) {
    for (var c = 0; c < w; c++) {
      v |= BigInt.from(plane[r][c] & 0xFF) << ((r * w + c) * 8);
    }
  }
  return v;
}

List<List<int>> _unpackPlane(BigInt v, int w, int h) => [
  for (var r = 0; r < h; r++)
    [
      for (var c = 0; c < w; c++)
        ((v >> ((r * w + c) * 8)) & BigInt.from(0xFF)).toInt(),
    ],
];

BigInt _packSkip(List<List<int>> miSkip, int miRows, int miCols) {
  var v = BigInt.zero;
  for (var r = 0; r < miRows; r++) {
    for (var c = 0; c < miCols; c++) {
      if (miSkip[r][c] != 0) v |= BigInt.one << (r * miCols + c);
    }
  }
  return v;
}

BigInt _packTable(List<int> tab, int numEntries) {
  var v = BigInt.zero;
  for (var e = 0; e < numEntries; e++) {
    v |= BigInt.from(tab[e] & 0xFF) << (e * 8);
  }
  return v;
}

// Per-unit index list -> packed cdef_idx (unit `fbr*nhfb+fbc` at bit unit*idxW).
BigInt _packIdx(List<int> unitIdx, int idxW) {
  var v = BigInt.zero;
  for (var u = 0; u < unitIdx.length; u++) {
    v |= BigInt.from(unitIdx[u]) << (u * idxW);
  }
  return v;
}

