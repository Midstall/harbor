void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 16;

  group('HarborCflAlphaDecode', () {
    late HarborCflAlphaDecode t;
    late Logic clk, reset, start, bytes;

    Future<void> setUpDut() async {
      t = HarborCflAlphaDecode(maxBytes: maxBytes);
      clk = SimpleClockGenerator(10).clk;
      reset = Logic(name: 'reset');
      start = Logic(name: 'start');
      bytes = Logic(name: 'bytes', width: maxBytes * 8);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      Simulator.setMaxSimTime(20000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
    }

    BigInt packBytes(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    test('matches _readCflAlphas over random coded bytes', () async {
      await setUpDut();
      final rng = Random(0xCF1);
      // Track which js branches we cover so the sweep is meaningful.
      final seenSigns = <int>{};
      var sawSignUzero = false, sawSignVzero = false;
      var sawBothNonzero = false;

      for (var iter = 0; iter < 400; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        final want = (idx: _idx[iter], signs: _signs[iter]);
        final js = want.signs;
        final signU = (js + 1) ~/ 3, signV = (js + 1) - 3 * signU;
        seenSigns.add(js);
        if (signU == 0) sawSignUzero = true;
        if (signV == 0) sawSignVzero = true;
        if (signU != 0 && signV != 0) sawBothNonzero = true;

        bytes.inject(packBytes(b));
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 200) fail('timeout iter=$iter');
        }
        final gotIdx = t.output('cfl_alpha_idx').value.toInt();
        final gotSigns = t.output('cfl_signs').value.toInt();
        expect(gotSigns, want.signs, reason: 'cfl_signs iter=$iter (bytes=$b)');
        expect(gotIdx, want.idx, reason: 'cfl_alpha_idx iter=$iter (bytes=$b)');
        await clk.nextPosedge; // back to idle
      }

      // Branch coverage sanity: the sweep must exercise both zero and nonzero
      // signU/signV branches, otherwise it is not testing the conditional
      // 2nd/3rd decodes.
      expect(sawSignUzero, isTrue, reason: 'never hit signU==0');
      expect(sawSignVzero, isTrue, reason: 'never hit signV==0');
      expect(sawBothNonzero, isTrue, reason: 'never hit signU!=0 && signV!=0');
      expect(
        seenSigns.length,
        greaterThanOrEqualTo(5),
        reason: 'too few distinct js values: $seenSigns',
      );
      await Simulator.endSimulation();
    });
  });
}
