BigInt _pack8(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

BigInt _pack16(List<int> c) {
  var v = BigInt.zero;
  for (var i = 0; i < c.length; i++) {
    v |= BigInt.from(c[i] & 0xffff) << (i * 16);
  }
  return v;
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // The 4x4 / 8x8 intra ext-tx set inverse map -> TX_TYPE (no flips).
  const intraTxSet = [9, 0, 10, 11, 3, 1, 2];

  for (final bs in [4, 8]) {
    final n = bs * bs;
    test('HarborChromaReconBlock bs=$bs matches SW per-plane recon', () async {
      final dut = HarborChromaReconBlock(bs: bs);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final uvMode = Logic(name: 'uv_mode', width: 4);
      final useCfl = Logic(name: 'use_cfl');
      final haveAbove = Logic(name: 'have_above');
      final haveLeft = Logic(name: 'have_left');
      final above = Logic(name: 'above', width: bs * 8);
      final left = Logic(name: 'left', width: bs * 8);
      final aboveLeft = Logic(name: 'above_left', width: 8);
      final cflLumaAc = Logic(name: 'cfl_luma_ac', width: n * 8);
      final cflAlphaIdx = Logic(name: 'cfl_alpha_idx', width: 8);
      final cflSigns = Logic(name: 'cfl_signs', width: 3);
      final plane = Logic(name: 'plane');
      final txType = Logic(name: 'tx_type', width: 4);
      final coeffs = Logic(name: 'coeffs', width: n * 16);
      final skip = Logic(name: 'skip');
      final eobZero = Logic(name: 'eob_zero');

      dut.input('clk').srcConnection! <= clk;
      dut.input('reset').srcConnection! <= reset;
      dut.input('start').srcConnection! <= start;
      dut.input('uv_mode').srcConnection! <= uvMode;
      dut.input('use_cfl').srcConnection! <= useCfl;
      dut.input('have_above').srcConnection! <= haveAbove;
      dut.input('have_left').srcConnection! <= haveLeft;
      dut.input('above').srcConnection! <= above;
      dut.input('left').srcConnection! <= left;
      dut.input('above_left').srcConnection! <= aboveLeft;
      dut.input('cfl_luma_ac').srcConnection! <= cflLumaAc;
      dut.input('cfl_alpha_idx').srcConnection! <= cflAlphaIdx;
      dut.input('cfl_signs').srcConnection! <= cflSigns;
      dut.input('plane').srcConnection! <= plane;
      dut.input('tx_type').srcConnection! <= txType;
      dut.input('coeffs').srcConnection! <= coeffs;
      dut.input('skip').srcConnection! <= skip;
      dut.input('eob_zero').srcConnection! <= eobZero;

      await dut.build();
      reset.inject(1);
      start.inject(0);
      uvMode.inject(0);
      useCfl.inject(0);
      haveAbove.inject(0);
      haveLeft.inject(0);
      above.inject(0);
      left.inject(0);
      aboveLeft.inject(0);
      cflLumaAc.inject(0);
      cflAlphaIdx.inject(0);
      cflSigns.inject(0);
      plane.inject(0);
      txType.inject(0);
      coeffs.inject(0);
      skip.inject(0);
      eobZero.inject(0);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      final rng = Random(0xC4 + bs);
      for (var iter = 0; iter < 120; iter++) {
        final av = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
        final lf = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
        final cr = rng.nextInt(256);
        final luma = [for (var i = 0; i < n; i++) rng.nextInt(256)];
        final idx = rng.nextInt(256);
        final sg = rng.nextInt(8);
        final pl = rng.nextInt(2);
        final cfl = rng.nextInt(2) == 1;
        // uv_mode is randomized even when CfL is on: the SW ignores it for the
        // CfL base prediction (always DC), so this exercises the DC-base detail.
        final mode = rng.nextInt(13);
        final tt = intraTxSet[rng.nextInt(intraTxSet.length)];
        final haveA = rng.nextInt(2) == 1;
        final haveL = rng.nextInt(2) == 1;
        final doSkip = rng.nextInt(4) == 0;
        final eob0 = !doSkip && rng.nextInt(4) == 0;
        final coef = [for (var i = 0; i < n; i++) rng.nextInt(2048) - 1024];

        uvMode.inject(mode);
        useCfl.inject(cfl ? 1 : 0);
        haveAbove.inject(haveA ? 1 : 0);
        haveLeft.inject(haveL ? 1 : 0);
        above.inject(_pack8(av));
        left.inject(_pack8(lf));
        aboveLeft.inject(cr);
        cflLumaAc.inject(_pack8(luma));
        cflAlphaIdx.inject(idx);
        cflSigns.inject(sg);
        plane.inject(pl);
        txType.inject(tt);
        coeffs.inject(_pack16(coef));
        skip.inject(doSkip ? 1 : 0);
        eobZero.inject(eob0 ? 1 : 0);

        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);

        var guard = 0;
        while (dut.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > bs * 2 + 32) {
            fail('timeout bs=$bs iter=$iter');
          }
        }

        final gold = _gold[bs]![iter];

        final out = dut.output('recon').value;
        for (var k = 0; k < n; k++) {
          expect(
            out.getRange(k * 8, k * 8 + 8).toInt(),
            equals(gold[k]),
            reason:
                'bs=$bs iter=$iter k=$k mode=$mode cfl=$cfl pl=$pl '
                'tt=$tt skip=$doSkip eob0=$eob0 haveA=$haveA haveL=$haveL',
          );
        }
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    });
  }
}
