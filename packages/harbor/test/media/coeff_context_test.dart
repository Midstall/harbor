void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // (txSize, n coeffs, bhl, width)
  const sizes = [
    (0, 16, 2, 4), // TX_4X4
    (1, 64, 3, 8), // TX_8X8
    (2, 256, 4, 16), // TX_16X16
    (5, 32, 3, 4), // TX_4X8
    (6, 32, 2, 8), // TX_8X4
    (7, 128, 4, 8), // TX_8X16
    (8, 128, 3, 16), // TX_16X8
    (13, 64, 4, 4), // TX_4X16
    (14, 64, 2, 16), // TX_16X4
    (9, 512, 5, 16), // TX_16X32
    (15, 256, 5, 8), // TX_8X32
  ];

  for (final s in sizes) {
    final txSize = s.$1;
    final n = s.$2;
    final bhl = s.$3;
    final width = s.$4;
    final height = 1 << bhl;
    final bufLen = (height + 4) * (width + 4) + 16;
    final posW = (n - 1).bitLength;

    group('HarborCoeffContext txSize=$txSize', () {
      late HarborCoeffContext t;
      late Logic clk, levels, coeffIdx, scanIdx, txClass;

      Future<void> setUpDut() async {
        t = HarborCoeffContext(txSize: txSize);
        clk = SimpleClockGenerator(10).clk;
        levels = Logic(name: 'levels', width: bufLen * 8);
        coeffIdx = Logic(name: 'coeff_idx', width: posW);
        scanIdx = Logic(name: 'scan_idx', width: posW + 1);
        txClass = Logic(name: 'tx_class', width: 2);
        t.input('levels').srcConnection! <= levels;
        t.input('coeff_idx').srcConnection! <= coeffIdx;
        t.input('scan_idx').srcConnection! <= scanIdx;
        t.input('tx_class').srcConnection! <= txClass;
        await t.build();
        levels.inject(0);
        coeffIdx.inject(0);
        scanIdx.inject(0);
        txClass.inject(0);
        Simulator.setMaxSimTime(50000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
      }

      test('matches libaom get_*_ctx over random level maps', () async {
        await setUpDut();
        final rng = Random(0xC7 + txSize);
        for (var iter = 0; iter < 300; iter++) {
          // Build a software levels buffer (full TX_PAD_2D), random in the
          // first bufLen entries. The module sees those same entries.
          final lvlBytes = List<int>.filled(bufLen, 0);
          for (var i = 0; i < bufLen; i++) {
            // bias toward small magnitudes (realistic), occasional large.
            final v = rng.nextInt(10) == 0 ? rng.nextInt(256) : rng.nextInt(8);
            lvlBytes[i] = v;
          }
          var lvlPacked = BigInt.zero;
          for (var i = 0; i < bufLen; i++) {
            lvlPacked |= BigInt.from(lvlBytes[i]) << (i * 8);
          }
          final ci = rng.nextInt(n);
          final si = rng.nextInt(n);
          final tc = rng.nextInt(3);

          levels.inject(lvlPacked);
          coeffIdx.inject(ci);
          scanIdx.inject(si);
          txClass.inject(tc);
          await clk.nextPosedge;

          final base2d = t.output('base_ctx_2d').value.toInt();
          final baseGen = t.output('base_ctx_gen').value.toInt();
          final baseEob = t.output('base_eob_ctx').value.toInt();
          final br2d = t.output('br_ctx_2d').value.toInt();
          final brGen = t.output('br_ctx_gen').value.toInt();
          final brEob = t.output('br_ctx_eob').value.toInt();

          final g = _g[txSize]![iter];
          expect(base2d, g[0], reason: 'base2d ci=$ci');
          expect(baseGen, g[1], reason: 'baseGen ci=$ci tc=$tc');
          expect(baseEob, g[2], reason: 'baseEob si=$si');
          expect(br2d, g[3], reason: 'br2d ci=$ci');
          expect(brGen, g[4], reason: 'brGen ci=$ci tc=$tc');
          expect(brEob, g[5], reason: 'brEob ci=$ci');
        }
        await Simulator.endSimulation();
      });
    });
  }
}
