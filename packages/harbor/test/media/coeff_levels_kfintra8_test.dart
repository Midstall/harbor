void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 64;

  test(
    'HarborCoeffLevels kfIntra TX_8X8 luma keyframe matches libaom',
    timeout: const Timeout(Duration(minutes: 20)),
    () async {
      final t = HarborCoeffLevels(
        maxBytes: maxBytes,
        txSize: 1,
        readTxType: true,
        kfIntra: true,
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      final skipCtx = Logic(name: 'skip_ctx', width: 2);
      final aMode = Logic(name: 'above_ymode', width: 4);
      final lMode = Logic(name: 'left_ymode', width: 4);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      t.input('skip_ctx').srcConnection! <= skipCtx;
      t.input('above_ymode').srcConnection! <= aMode;
      t.input('left_ymode').srcConnection! <= lMode;
      await t.build();
      reset.inject(1);
      for (final s in [start, bytes, dcQ, acQ, skipCtx, aMode, lMode]) {
        s.inject(0);
      }
      Simulator.setMaxSimTime(120000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      int s16(BigInt v) {
        final raw = v.toInt() & 0xffff;
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      }

      final rng = Random(0x8E8E);
      var sawCoeffs = false;
      for (var iter = 0; iter < 30; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        rng.nextInt(256); // advance rng (dequant index)
        final sc0 = rng.nextInt(3);
        final am = rng.nextInt(13);
        final lm = rng.nextInt(13);
        final want = (
          eob: _eob[iter],
          yMode: _ymode[iter],
          angle: _angle[iter],
          blockSkip: _skip[iter],
          txType: _txtype[iter],
          coeffs: _coeffs[iter],
        );
        if (want.eob > 0) sawCoeffs = true;

        bytes.inject(packBytes(b));
        dcQ.inject(_dcv[iter]);
        acQ.inject(_acv[iter]);
        skipCtx.inject(sc0);
        aMode.inject(am);
        lMode.inject(lm);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 8000) fail('timeout iter=$iter');
        }
        expect(
          t.output('y_mode').value.toInt(),
          want.yMode,
          reason: 'ymode $iter',
        );
        expect(
          t.output('angle_delta').value.toInt(),
          want.angle,
          reason: 'angle $iter',
        );
        expect(
          t.output('block_skip').value.toInt(),
          want.blockSkip ? 1 : 0,
          reason: 'skip $iter',
        );
        if (want.eob > 0) {
          expect(
            t.output('tx_type').value.toInt(),
            want.txType,
            reason: 'tt $iter',
          );
        }
        expect(t.output('eob').value.toInt(), want.eob, reason: 'eob $iter');
        final cvv = t.output('coeffs').value.toBigInt();
        final gotCoeffs = [
          for (var p = 0; p < 64; p++)
            s16((cvv >> (p * 16)) & BigInt.from(0xffff)),
        ];
        expect(gotCoeffs, want.coeffs, reason: 'coeffs iter=$iter');
        await clk.nextPosedge;
      }
      expect(sawCoeffs, isTrue, reason: 'no coeffs seen');
      await Simulator.endSimulation();
    },
  );
}
