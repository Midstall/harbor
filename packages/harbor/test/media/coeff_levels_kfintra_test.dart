          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      int s16(BigInt v) {
        final raw = v.toInt() & 0xffff;
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      }

      final rng = Random(0xC0FE);
      var sawSkip = false, sawCoeffs = false;
      for (var iter = 0; iter < 200; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        rng.nextInt(256); // advance rng (dequant index)
        final sc0 = rng.nextInt(3);
        final am = rng.nextInt(13);
        final lm = rng.nextInt(13);
        final want = (
          eob: _eob[iter],
          yMode: _ymode[iter],
          blockSkip: _skip[iter],
          txType: _txtype[iter],
          coeffs: _coeffs[iter],
        );
        if (want.blockSkip) sawSkip = true;
        if (want.eob > 0) sawCoeffs = true;

        bytes.inject(packBytes(b));
        dcQ.inject(_dcv[iter]);
        acQ.inject(_acv[iter]);
        skipCtx.inject(sc0);
        aMode.inject(am);
        lMode.inject(lm);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 4000) fail('timeout iter=$iter');
        }
        final gotEob = t.output('eob').value.toInt();
        final gotYMode = t.output('y_mode').value.toInt();
        final gotSkip = t.output('block_skip').value.toInt();
        final gotType = t.output('tx_type').value.toInt();
        final cvv = t.output('coeffs').value.toBigInt();
        final gotCoeffs = [
          for (var p = 0; p < 16; p++)
            s16((cvv >> (p * 16)) & BigInt.from(0xffff)),
        ];
        expect(gotYMode, want.yMode, reason: 'y_mode iter=$iter');
        expect(
          gotSkip,
          want.blockSkip ? 1 : 0,
          reason: 'block_skip iter=$iter',
        );
        if (want.eob > 0) {
          expect(gotType, want.txType, reason: 'tx_type iter=$iter');
        }
        expect(gotEob, want.eob, reason: 'eob iter=$iter');
        expect(gotCoeffs, want.coeffs, reason: 'coeffs iter=$iter b=$b');
        await clk.nextPosedge;
      }
      expect(sawSkip, isTrue, reason: 'no block_skip seen');
      expect(sawCoeffs, isTrue, reason: 'no coeffs seen');
      await Simulator.endSimulation();
    },
  );
}
