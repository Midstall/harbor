void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const n = 32;

  Future<void> runSize(int txSize, int seed) async {
    final t = HarborCoeffLevels(maxBytes: maxBytes, txSize: txSize);
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    final dcQ = Logic(name: 'dc_q', width: 16);
    final acQ = Logic(name: 'ac_q', width: 16);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    t.input('dc_q').srcConnection! <= dcQ;
    t.input('ac_q').srcConnection! <= acQ;
    await t.build();
    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    dcQ.inject(0);
    acQ.inject(0);
    Simulator.setMaxSimTime(400000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    BigInt packBytes(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    int s16(BigInt v) {
      final raw = v.toInt() & 0xffff;
      return raw >= 0x8000 ? raw - 0x10000 : raw;
    }

    final rng = Random(seed);
    for (var iter = 0; iter < 120; iter++) {
      final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
      rng.nextInt(256); // advance rng (dequant index)
      final want = (eob: _eob[txSize]![iter], coeffs: _coeffs[txSize]![iter]);

      bytes.inject(packBytes(b));
      dcQ.inject(_dcv[txSize]![iter]);
      acQ.inject(_acv[txSize]![iter]);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 8000) fail('timeout txSize=$txSize iter=$iter');
      }
      final gotEob = t.output('eob').value.toInt();
      final cvv = t.output('coeffs').value.toBigInt();
      final gotCoeffs = [
        for (var p = 0; p < n; p++)
          s16((cvv >> (p * 16)) & BigInt.from(0xffff)),
      ];
      expect(gotEob, want.eob, reason: 'eob txSize=$txSize iter=$iter');
      expect(
        gotCoeffs,
        want.coeffs,
        reason: 'coeffs txSize=$txSize iter=$iter (bytes=$b)',
      );
      await clk.nextPosedge;
    }
    await Simulator.endSimulation();
  }

  test('HarborCoeffLevels TX_4X8 matches libaom read_coeffs_txb', () async {
    await runSize(5, 0x4848);
  });

  test('HarborCoeffLevels TX_8X4 matches libaom read_coeffs_txb', () async {
    await runSize(6, 0x8484);
  });
}
