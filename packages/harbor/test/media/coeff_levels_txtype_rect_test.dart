const _golden = {5: _golden5, 6: _golden6};

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const n = 32;

  Future<void> runSize(int txSize, int seed) async {
    final t = HarborCoeffLevels(
      maxBytes: maxBytes,
      txSize: txSize,
      readTxType: true,
    );
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    final dcQ = Logic(name: 'dc_q', width: 16);
    final acQ = Logic(name: 'ac_q', width: 16);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    t.input('dc_q').srcConnection! <= dcQ;
    t.input('ac_q').srcConnection! <= acQ;
    await t.build();
    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    dcQ.inject(0);
    acQ.inject(0);
    Simulator.setMaxSimTime(400000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    BigInt packBytes(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    int s16(BigInt v) {
      final raw = v.toInt() & 0xffff;
      return raw >= 0x8000 ? raw - 0x10000 : raw;
    }

    final gold = _golden[txSize]!;
    final rng = Random(seed);
    var sawHoriz = false, sawVert = false, nonZeroNon2d = 0;
    for (var iter = 0; iter < 120; iter++) {
      final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
      rng.nextInt(256); // advance rng past the q index
      final want = gold[iter];
      if (want.eob > 0 && want.txType == 11) sawHoriz = true;
      if (want.eob > 0 && want.txType == 10) sawVert = true;
      if (want.eob > 0 && (want.txType == 10 || want.txType == 11)) {
        nonZeroNon2d++;
      }

      bytes.inject(packBytes(b));
      dcQ.inject(want.dcv);
      acQ.inject(want.acv);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 8000) fail('timeout txSize=$txSize iter=$iter');
      }
      final gotEob = t.output('eob').value.toInt();
      final gotType = t.output('tx_type').value.toInt();
      final cvv = t.output('coeffs').value.toBigInt();
      final gotCoeffs = [
        for (var p = 0; p < n; p++)
          s16((cvv >> (p * 16)) & BigInt.from(0xffff)),
      ];
      if (gotEob > 0) {
        expect(
          gotType,
          want.txType,
          reason: 'tx_type txSize=$txSize iter=$iter',
        );
      }
      expect(gotEob, want.eob, reason: 'eob txSize=$txSize iter=$iter');
      expect(
        gotCoeffs,
        want.coeffs,
        reason: 'coeffs txSize=$txSize iter=$iter (bytes=$b)',
      );
      await clk.nextPosedge;
    }
    // The random stream must exercise the 1D (HORIZ/VERT) classes for coverage.
    expect(
      sawHoriz || sawVert,
      isTrue,
      reason: 'no 1D class seen txSize=$txSize',
    );
    expect(
      nonZeroNon2d,
      greaterThan(0),
      reason: 'no non-2D coeff block decoded txSize=$txSize',
    );
    // ignore: avoid_print
    print('txSize=$txSize non-2D coeff blocks: $nonZeroNon2d');
    await Simulator.endSimulation();
  }

  test('HarborCoeffLevels readTxType TX_4X8 matches libaom', () async {
    await runSize(5, 0x4848);
  });

  test('HarborCoeffLevels readTxType TX_8X4 matches libaom', () async {
    await runSize(6, 0x8484);
  });
}
