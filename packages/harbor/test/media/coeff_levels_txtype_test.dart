void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 32;

  test(
    'HarborCoeffLevels readTxType (TX_4X4 luma intra) matches libaom',
    () async {
      final t = HarborCoeffLevels(maxBytes: maxBytes, readTxType: true);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(50000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      int s16(BigInt v) {
        final raw = v.toInt() & 0xffff;
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      }

      final rng = Random(0x7A11);
      var sawHoriz = false, sawVert = false;
      for (var iter = 0; iter < 150; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        rng.nextInt(256); // advance rng past the q index
        final want = _golden[iter];
        if (want.txType == 11) sawHoriz = true;
        if (want.txType == 10) sawVert = true;

        bytes.inject(packBytes(b));
        dcQ.inject(want.dcv);
        acQ.inject(want.acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 4000) fail('timeout iter=$iter');
        }
        final gotEob = t.output('eob').value.toInt();
        final gotType = t.output('tx_type').value.toInt();
        final cvv = t.output('coeffs').value.toBigInt();
        final gotCoeffs = [
          for (var p = 0; p < 16; p++)
            s16((cvv >> (p * 16)) & BigInt.from(0xffff)),
        ];
        // tx_type only meaningful when not all-zero (eob > 0).
        if (gotEob > 0) {
          expect(gotType, want.txType, reason: 'tx_type iter=$iter');
        }
        expect(gotEob, want.eob, reason: 'eob iter=$iter');
        expect(gotCoeffs, want.coeffs, reason: 'coeffs iter=$iter b=$b');
        await clk.nextPosedge;
      }
      // Sanity: the random stream should exercise the 1D (HORIZ/VERT) classes.
      expect(sawHoriz || sawVert, isTrue, reason: 'no 1D class seen');
      await Simulator.endSimulation();
    },
  );
}
