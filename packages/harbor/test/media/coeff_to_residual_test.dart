void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const szName = {0: '4X4', 1: '8X8', 2: '16X16'};
  for (final (txSize, n, iters, maxBytes) in [
    (0, 16, 40, 32),
    (1, 64, 16, 48),
    (2, 256, 8, 96),
  ]) {
    test('coded bytes -> coeffs -> residual (TX_${szName[txSize]})', () async {
      final cl = HarborCoeffLevels(maxBytes: maxBytes, txSize: txSize);
      final tx = HarborInvTxfm(txSize: txSize, txType: 0); // DCT_DCT
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final clStart = Logic(name: 'cl_start');
      final txStart = Logic(name: 'tx_start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);

      cl.input('clk').srcConnection! <= clk;
      cl.input('reset').srcConnection! <= reset;
      cl.input('start').srcConnection! <= clStart;
      cl.input('bytes').srcConnection! <= bytes;
      cl.input('dc_q').srcConnection! <= dcQ;
      cl.input('ac_q').srcConnection! <= acQ;

      tx.input('clk').srcConnection! <= clk;
      tx.input('reset').srcConnection! <= reset;
      tx.input('start').srcConnection! <= txStart;
      tx.input('coeffs').srcConnection! <= cl.output('coeffs');

      await tx.build();

      reset.inject(1);
      clStart.inject(0);
      txStart.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      int s16(BigInt v) {
        final raw = v.toInt() & 0xffff;
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      }

      final gold = _residual[txSize]!;
      final rng = Random(0xC0FFEE + txSize);
      for (var iter = 0; iter < iters; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        rng.nextInt(256); // advance rng past the q index
        bytes.inject(packBytes(b));
        dcQ.inject(gold[iter].dcv);
        acQ.inject(gold[iter].acv);

        clStart.inject(1);
        await clk.nextPosedge;
        clStart.inject(0);
        var guard = 0;
        while (cl.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 40000) fail('coeff timeout iter=$iter');
        }

        txStart.inject(1);
        await clk.nextPosedge;
        txStart.inject(0);
        guard = 0;
        while (tx.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 256) fail('tx timeout iter=$iter');
        }
        final rvv = tx.output('residual').value.toBigInt();
        final residual = [
          for (var p = 0; p < n; p++)
            s16((rvv >> (p * 16)) & BigInt.from(0xffff)),
        ];

        expect(residual, gold[iter].res, reason: 'txSize=$txSize iter=$iter');

        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    });
  }
