// Helpers: pack Dart grids into the module's LSB-first row-major port words.

BigInt _packPlane(List<List<int>> pix, int w, int h) {
  var v = BigInt.zero;
  for (var y = 0; y < h; y++) {
    for (var x = 0; x < w; x++) {
      v |= BigInt.from(pix[y][x] & 0xFF) << ((y * w + x) * 8);
    }
  }
  return v;
}

BigInt _packMi(List<List<int>> g, int miRows, int miCols, int bits) {
  var v = BigInt.zero;
  for (var r = 0; r < miRows; r++) {
    for (var c = 0; c < miCols; c++) {
      v |= BigInt.from(g[r][c]) << ((r * miCols + c) * bits);
    }
  }
  return v;
}

List<List<int>> _fill(int r, int c, int val) =>
    List.generate(r, (_) => List.filled(c, val));

// Drive the HW module and compare Y/U/V against the SW deblockFrame oracle.

Future<void> runCase({
  required String label,
  required int width,
  required int height,
  required int numPlanes,
  required int subX,
  required int subY,
  required List<List<int>> miTxY,
  required List<List<int>> miTxUV,
  required List<List<int>> lvlYv,
  required List<List<int>> lvlYh,
  required List<List<int>> lvlU,
  required List<List<int>> lvlV,
  required List<List<int>> skip,
  required List<List<int>> isInter,
  required List<List<int>> blockW,
  required List<List<int>> blockH,
  required int sharpness,
  required int iters,
  required int seed,
  required List<_Gold> gold,
  bool expectChange = true,
}) async {
  final miRows = height ~/ 4;
  final miCols = width ~/ 4;
  final cw = width >> subX;
  final ch = height >> subY;

  final dut = HarborDeblockFrame(
    width: width,
    height: height,
    numPlanes: numPlanes,
    subX: subX,
    subY: subY,
  );

  // External drivers for every input port.
  final drivers = <String, Logic>{};
  Logic drive(String port) {
    final w = dut.input(port).width;
    final sig = Logic(name: 'drv_$port', width: w);
    dut.input(port).srcConnection! <= sig;
    drivers[port] = sig;
    return sig;
  }

  for (final p in [
    'frame',
    'sharpness',
    'mi_tx_y',
    'mi_tx_uv',
    'mi_level_yv',
    'mi_level_yh',
    'mi_level_u',
    'mi_level_v',
    'mi_skip',
    'mi_is_inter',
    'mi_block_w',
    'mi_block_h',
  ]) {
    drive(p);
  }
  if (numPlanes == 3) {
    drive('frame_u');
    drive('frame_v');
  }

  final clk = SimpleClockGenerator(10).clk;
  await dut.build();
  Simulator.setMaxSimTime(200000000);
  unawaited(Simulator.run());

  // Static metadata (constant across iterations).
  drivers['sharpness']!.put(sharpness);
  drivers['mi_tx_y']!.put(_packMi(miTxY, miRows, miCols, 5));
  drivers['mi_tx_uv']!.put(_packMi(miTxUV, miRows, miCols, 5));
  drivers['mi_level_yv']!.put(_packMi(lvlYv, miRows, miCols, 6));
  drivers['mi_level_yh']!.put(_packMi(lvlYh, miRows, miCols, 6));
  drivers['mi_level_u']!.put(_packMi(lvlU, miRows, miCols, 6));
  drivers['mi_level_v']!.put(_packMi(lvlV, miRows, miCols, 6));
  drivers['mi_skip']!.put(_packMi(skip, miRows, miCols, 1));
  drivers['mi_is_inter']!.put(_packMi(isInter, miRows, miCols, 1));
  drivers['mi_block_w']!.put(_packMi(blockW, miRows, miCols, 8));
  drivers['mi_block_h']!.put(_packMi(blockH, miRows, miCols, 8));

  final rng = Random(seed);
  var totalChanged = 0;

  List<List<int>> randPlane(int w, int h, int mode) {
    final p = List.generate(h, (_) => List<int>.filled(w, 0));
    for (var y = 0; y < h; y++) {
      for (var x = 0; x < w; x++) {
        if (mode == 0) {
          p[y][x] = rng.nextInt(256);
        } else if (mode == 1) {
          final plateau = 100 + 6 * ((x ~/ 8) + (y ~/ 8));
          p[y][x] = (plateau + rng.nextInt(3) - 1).clamp(0, 255);
        } else {
          p[y][x] = (60 + (x + y) + rng.nextInt(3) - 1).clamp(0, 255);
        }
      }
    }
    return p;
  }

  for (var iter = 0; iter < iters; iter++) {
    final mode = iter % 3;
    final py = randPlane(width, height, mode);
    final pu = numPlanes == 3 ? randPlane(cw, ch, mode) : <List<int>>[];
    final pv = numPlanes == 3 ? randPlane(cw, ch, mode) : <List<int>>[];

    drivers['frame']!.put(_packPlane(py, width, height));
    if (numPlanes == 3) {
      drivers['frame_u']!.put(_packPlane(pu, cw, ch));
      drivers['frame_v']!.put(_packPlane(pv, cw, ch));
    }
    await clk.nextPosedge;

    // Golden: the captured deblocked planes for this iteration.
    List<List<int>> unflat(List<int> flat, int w, int h) =>
        List.generate(h, (y) => flat.sublist(y * w, y * w + w));
    final g = gold[iter];
    final gy = unflat(g.y, width, height);
    final gu = numPlanes == 3 ? unflat(g.u, cw, ch) : <List<int>>[];
    final gv = numPlanes == 3 ? unflat(g.v, cw, ch) : <List<int>>[];

    // HW read-back.
    void checkPlane(
      String outPort,
      List<List<int>> gold,
      List<List<int>> src,
      int w,
      int h,
    ) {
      final val = dut.output(outPort).value;
      final got = List.generate(h, (y) => List<int>.filled(w, 0));
      for (var y = 0; y < h; y++) {
        for (var x = 0; x < w; x++) {
          got[y][x] = val
              .getRange((y * w + x) * 8, (y * w + x) * 8 + 8)
              .toInt();
        }
      }
      for (var y = 0; y < h; y++) {
        expect(
          got[y],
          equals(gold[y]),
          reason: '$label $outPort iter=$iter row=$y\nin =${src[y]}',
        );
        for (var x = 0; x < w; x++) {
          if (gold[y][x] != src[y][x]) totalChanged++;
        }
      }
    }

    checkPlane('out', gy, py, width, height);
    if (numPlanes == 3) {
      checkPlane('out_u', gu, pu, cw, ch);
      checkPlane('out_v', gv, pv, cw, ch);
    }
  }

  if (expectChange) {
    expect(
      totalChanged,
      greaterThan(0),
      reason: '$label never modified any pixel',
    );
  } else {
    expect(
      totalChanged,
      equals(0),
      reason: '$label expected identity but pixels changed',
    );
  }
  await Simulator.endSimulation();
}

