// End-to-end bit-exactness of the Harbor AV1 FILM GRAIN hardware against the
// conformant SW film-grain oracle (itself bit-exact vs libaom
// aomdec 3.12.1). Film grain is applied to the DISPLAY copy of a frame after all
// other decoding. The SW oracle's shown-frame output INCLUDES grain, so the HW
// grain stage is verified in isolation by feeding it the SW pre-grain recon plus
// the parsed grain params and diffing the grain-applied output.
//
// Two stages:
//  1. HarborFilmGrainSynth  - the AR autoregressive template synthesis
//     (luma + Cb + Cr, incl. the luma->chroma cross term) vs
//     synthesizeGrainTemplates.
//  2. HarborFilmGrainApply  - the per-pixel apply (block pseudo-random offsets,
//     the 2px grain-block OVERLAP blend, piecewise-linear scaling LUT, chroma
//     luma-average scaling index, video-range clip) vs addFilmGrain.
//
// The embedded OBU is a REAL aomenc 3.12.1 --film-grain-test=2 stream, 64x64
// 4:2:0 8-bit, whose shown frame carries active film-grain params:
//   seed=45231 ar_coeff_lag=3 ar_coeff_shift=7 scaling_shift=11
//   num_y=2 num_cb=2 num_cr=2 overlap=1 clip=0  (luma cross term present).
// aomenc --obu --cpu-used=4 --end-usage=q --cq-level=32 --limit=2 --passes=1
//   --film-grain-test=2 -o fgs_2.obu in64.y4m

const int _grainW = HarborFilmGrainSynth.grainW; // 16
const int _pxW = HarborFilmGrainApply.pxW; // 16

BigInt _packSigned(List<int> vals, int wbits) {
  var p = BigInt.zero;
  for (var i = 0; i < vals.length; i++) {
    p |= BigInt.from(vals[i]).toUnsigned(wbits) << (i * wbits);
  }
  return p;
}

int _sext(int v, int bits) {
  final s = 1 << (bits - 1);
  return (v & (s - 1)) - (v & s);
}

void main() {
  const ssx = _ssx, ssy = _ssy;
  const bd = _bitDepth;

  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'film grain SYNTHESIS: HarborFilmGrainSynth luma+Cb+Cr templates '
    'bit-exact vs SW synthesizeGrainTemplates',
    timeout: const Timeout(Duration(minutes: 60)),
    () async {
      final genCb = _numCbPoints != 0 || _chromaScalingFromLuma;
      final genCr = _numCrPoints != 0 || _chromaScalingFromLuma;

      final dut = HarborFilmGrainSynth(
        ssx: ssx,
        ssy: ssy,
        bd: bd,
        arCoeffLag: _arCoeffLag,
        genCb: genCb,
        genCr: genCr,
        chromaFromLuma: _chromaScalingFromLuma,
        lumaCross: _numYPoints > 0,
      );

      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic()..put(1);
      final start = Logic()..put(0);
      final seed = Logic(width: 16)..put(_randomSeed & 0xffff);
      final arShift = Logic(width: 4)..put(_arCoeffShift);
      final gss = Logic(width: 4)..put(_grainScaleShift);
      final arY = Logic(width: 24 * 8)
        ..put(_packSigned([for (var i = 0; i < 24; i++) _arCoeffsY[i]], 8));
      final arCb = Logic(width: 25 * 8)
        ..put(_packSigned([for (var i = 0; i < 25; i++) _arCoeffsCb[i]], 8));
      final arCr = Logic(width: 25 * 8)
        ..put(_packSigned([for (var i = 0; i < 25; i++) _arCoeffsCr[i]], 8));
      dut.input('clk').srcConnection! <= clk;
      dut.input('reset').srcConnection! <= reset;
      dut.input('start').srcConnection! <= start;
      dut.input('seed').srcConnection! <= seed;
      dut.input('ar_coeff_shift').srcConnection! <= arShift;
      dut.input('grain_scale_shift').srcConnection! <= gss;
      dut.input('ar_coeffs_y').srcConnection! <= arY;
      dut.input('ar_coeffs_cb').srcConnection! <= arCb;
      dut.input('ar_coeffs_cr').srcConnection! <= arCr;
      await dut.build();

      Simulator.setMaxSimTime(200000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      await clk.nextPosedge;
      reset.put(0);
      start.put(1);
      var cyc = 0;
      while (dut.output('done').value.toInt() == 0) {
        await clk.nextPosedge;
        expect(++cyc, lessThan(40000), reason: 'synthesis did not finish');
      }

      // position c of a plane of size n lives in slot (n-1-c).
      List<int> unpack(LogicValue v, int n) => [
        for (var c = 0; c < n; c++)
          _sext(
            v
                .getRange(
                  (n - 1 - c) * _grainW,
                  (n - 1 - c) * _grainW + _grainW,
                )
                .toInt(),
            _grainW,
          ),
      ];
      expect(
        unpack(dut.output('luma').value, dut.nLuma),
        equals(_tmplLuma),
        reason: 'luma grain template',
      );
      if (genCb) {
        expect(
          unpack(dut.output('cb').value, dut.nChroma),
          equals(_tmplCb),
          reason: 'Cb grain template',
        );
      }
      if (genCr) {
        expect(
          unpack(dut.output('cr').value, dut.nChroma),
          equals(_tmplCr),
          reason: 'Cr grain template',
        );
      }
      await Simulator.endSimulation();
    },
  );

  test(
    'film grain APPLY: HarborFilmGrainApply grain-applied Y+Cb+Cr display '
    'output bit-exact vs SW addFilmGrain (overlap + chroma)',
    timeout: const Timeout(Duration(minutes: 90)),
    () async {
      const w = _w, h = _h;
      final cw = (w + ssx) >> ssx, ch = (h + ssy) >> ssy;
      var cbMult = _cbMult - 128, cbLumaMult = _cbLumaMult - 128;
      var cbOffset = (_cbOffset << (bd - 8)) - (1 << bd);
      var crMult = _crMult - 128, crLumaMult = _crLumaMult - 128;
      var crOffset = (_crOffset << (bd - 8)) - (1 << bd);
      if (_chromaScalingFromLuma) {
        cbMult = 0;
        cbLumaMult = 64;
        cbOffset = 0;
        crMult = 0;
        crLumaMult = 64;
        crOffset = 0;
      }
      final genCb = _numCbPoints > 0 || _chromaScalingFromLuma;
      final genCr = _numCrPoints > 0 || _chromaScalingFromLuma;

      final dut = HarborFilmGrainApply(
        w: w,
        h: h,
        ssx: ssx,
        ssy: ssy,
        bd: bd,
        overlap: _overlapFlag,
        genCb: genCb,
        genCr: genCr,
        chromaFromLuma: _chromaScalingFromLuma,
        clipRestricted: _clipToRestrictedRange,
      );

      Logic uc(int wid, int v) =>
          Logic(width: wid)..put(BigInt.from(v).toUnsigned(wid));

      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic()..put(1);
      final start = Logic()..put(0);
      final conns = <String, Logic>{
        'clk': clk,
        'reset': reset,
        'start': start,
        'seed': uc(16, _randomSeed & 0xffff),
        'scaling_shift': uc(4, _scalingShift),
        'cb_luma_mult': uc(16, cbLumaMult),
        'cb_mult': uc(16, cbMult),
        'cb_offset': uc(32, cbOffset),
        'cr_luma_mult': uc(16, crLumaMult),
        'cr_mult': uc(16, crMult),
        'cr_offset': uc(32, crOffset),
        'lut_y': Logic(width: 256 * 16)..put(_packSigned(_lutY, 16)),
        'lut_cb': Logic(width: 256 * 16)..put(_packSigned(_lutCb, 16)),
        'lut_cr': Logic(width: 256 * 16)..put(_packSigned(_lutCr, 16)),
        'tmpl_y': Logic(width: _tmplLuma.length * 16)
          ..put(_packSigned(_tmplLuma, 16)),
        'tmpl_cb': Logic(width: _tmplCb.length * 16)
          ..put(_packSigned(_tmplCb, 16)),
        'tmpl_cr': Logic(width: _tmplCr.length * 16)
          ..put(_packSigned(_tmplCr, 16)),
        'recon_y': Logic(width: w * h * 16)..put(_packSigned(_preY, 16)),
        'recon_cb': Logic(width: cw * ch * 16)..put(_packSigned(_preU, 16)),
        'recon_cr': Logic(width: cw * ch * 16)..put(_packSigned(_preV, 16)),
      };
      conns.forEach((n, l) => dut.input(n).srcConnection! <= l);
      await dut.build();

      Simulator.setMaxSimTime(400000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      await clk.nextPosedge;
      reset.put(0);
      start.put(1);
      var cyc = 0;
      while (dut.output('done').value.toInt() == 0) {
        await clk.nextPosedge;
        expect(++cyc, lessThan(20000), reason: 'apply did not finish');
      }

      List<int> unpack(LogicValue v, int n) => [
        for (var c = 0; c < n; c++)
          v.getRange((n - 1 - c) * _pxW, (n - 1 - c) * _pxW + _pxW).toInt(),
      ];
      expect(
        unpack(dut.output('out_y').value, w * h),
        equals(_postY),
        reason: 'grain-applied luma',
      );
      expect(
        unpack(dut.output('out_cb').value, cw * ch),
        equals(_postU),
        reason: 'grain-applied Cb',
      );
      expect(
        unpack(dut.output('out_cr').value, cw * ch),
        equals(_postV),
        reason: 'grain-applied Cr',
      );
      await Simulator.endSimulation();
    },
  );
}

