      conn('reset', reset);
      conn('start', start);
      conn('bytes', bytes);
      conn('allow_hp', allowHp);
      conn('force_integer_mv', forceInt);
      conn('tx_mode_select', txModeSel);
      conn('skip_mode_present', skipModePresent);
