      const maxBytes = 32;

      const ms = HarborInterFrameWalk.maxSyms;
      const nctx = HarborInterFrameWalk.numCtx;
      BigInt packCdfs() {
        var v = BigInt.zero;
        for (var cc = 0; cc < nctx; cc++) {
          final icdf = _cdfs[cc];
          for (var s = 0; s < ms; s++) {
            final val = s < icdf.length ? icdf[s] : 0;
            v |= BigInt.from(val & 0xFFFF) << ((cc * ms + s) * 16);
          }
        }
        return v;
      }

      BigInt packNsyms() {
        var v = BigInt.zero;
        for (var cc = 0; cc < nctx; cc++) {
          v |= BigInt.from(_nsyms[cc] & 0x1F) << (cc * 5);
        }
        return v;
      }

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xFF) << (i * 8);
        }
        return v;
      }

      final tw = HarborInterFrameWalk(maxBytes: maxBytes);
      final clk = SimpleClockGenerator(10).clk;
