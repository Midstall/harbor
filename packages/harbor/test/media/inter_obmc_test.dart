      final wY = preY[0].length, hY = preY.length;
      final wC = preU[0].length, hC = preU.length;

      final reconY = [for (var y = 0; y < hY; y++) List<int>.filled(wY, 0)];
      final reconU = [for (var y = 0; y < hC; y++) List<int>.filled(wC, 0)];
      final reconV = [for (var y = 0; y < hC; y++) List<int>.filled(wC, 0)];
      List<List<int>> reconPlane(int p) =>
          p == 0 ? reconY : (p == 1 ? reconU : reconV);
      List<List<int>> refPlane(int p) =>
          p == 0 ? _refY : (p == 1 ? _refU : _refV);

      // --- Pre-scan every sub-pel MC (w,h) and every OBMC blend (pbw,pbh) size
      // from the captured geometry, so one HarborInterConvolve / HarborMaskBlend
      // is built per distinct size. ---
      final convSizes = <int>{}; // w*1000+h
      final blendSizes = <int>{}; // pbw*1000+pbh
      for (final op in _mcOps) {
        if (op[7] != 0 || op[8] != 0) convSizes.add(op[3] * 1000 + op[4]);
      }
      for (final s in _obmcStrips) {
        blendSizes.add(s[3] * 1000 + s[4]);
        if (s[7] != 0 || s[8] != 0) convSizes.add(s[3] * 1000 + s[4]);
      }

      final clk = SimpleClockGenerator(10).clk;
      final convs = <int, HarborInterConvolve>{};
      final convPatch = <int, Logic>{};
      final convFx = <int, Logic>{};
      final convFy = <int, Logic>{};
      for (final key in convSizes) {
        final w = key ~/ 1000, h = key % 1000;
        final conv = HarborInterConvolve(width: w, height: h);
        final patch = Logic(
          name: 'patch_${w}x$h',
          width: (w + 7) * (h + 7) * 8,
        );
        final fx = Logic(name: 'fx_${w}x$h', width: 4);
        final fy = Logic(name: 'fy_${w}x$h', width: 4);
        conv.input('patch').srcConnection! <= patch;
        conv.input('frac_x').srcConnection! <= fx;
        conv.input('frac_y').srcConnection! <= fy;
        convs[key] = conv;
        convPatch[key] = patch;
        convFx[key] = fx;
        convFy[key] = fy;
      }
      final blends = <int, HarborMaskBlend>{};
      final blendA = <int, Logic>{};
      final blendB = <int, Logic>{};
      final blendM = <int, Logic>{};
      for (final key in blendSizes) {
        final w = key ~/ 1000, h = key % 1000;
        final mb = HarborMaskBlend(width: w, height: h);
        final a = Logic(name: 'a_${w}x$h', width: w * h * 8);
        final b = Logic(name: 'b_${w}x$h', width: w * h * 8);
        final m = Logic(name: 'm_${w}x$h', width: w * h * 7);
        mb.input('a').srcConnection! <= a;
        mb.input('b').srcConnection! <= b;
        mb.input('mask').srcConnection! <= m;
        blends[key] = mb;
        blendA[key] = a;
        blendB[key] = b;
        blendM[key] = m;
      }
      for (final conv in convs.values) {
        await conv.build();
      }
      for (final mb in blends.values) {
        await mb.build();
      }

      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;

      // Fetch a `w x h` MC region (integer copy or sub-pel convolve) from `ref`.
      Future<List<List<int>>> mcRegion(
        List<List<int>> ref,
        int w,
        int h,
        int x0,
        int y0,
        int subX,
        int subY,
      ) async {
        final out = [for (var i = 0; i < h; i++) List<int>.filled(w, 0)];
        if (subX == 0 && subY == 0) {
          for (var y = 0; y < h; y++) {
            for (var x = 0; x < w; x++) {
              out[y][x] = refAt(ref, y0 + y, x0 + x);
            }
          }
          return out;
        }
        final key = w * 1000 + h;
        final conv = convs[key]!;
        final pw = w + 7, ph = h + 7;
        var v = BigInt.zero;
        for (var pr = 0; pr < ph; pr++) {
          for (var pc = 0; pc < pw; pc++) {
            final s = refAt(ref, y0 + pr - 3, x0 + pc - 3);
            v |= BigInt.from(s & 0xFF) << ((pr * pw + pc) * 8);
          }
        }
        convPatch[key]!.inject(v);
        convFx[key]!.inject(subX);
        convFy[key]!.inject(subY);
        await clk.nextPosedge;
        final pred = conv.output('pred').value;
        for (var y = 0; y < h; y++) {
          for (var x = 0; x < w; x++) {
            out[y][x] = pred
                .getRange((y * w + x) * 8, (y * w + x) * 8 + 8)
                .toInt();
          }
        }
        return out;
      }

      // --- 1) Motion compensation for every captured op (all skip -> no residual).
      for (final op in _mcOps) {
        final p = op[0], ox = op[1], oy = op[2], w = op[3], h = op[4];
        final x0 = op[5], y0 = op[6], subX = op[7], subY = op[8];
        final ref = refPlane(p), plane = reconPlane(p);
        final px = await mcRegion(ref, w, h, x0, y0, subX, subY);
        for (var y = 0; y < h; y++) {
          for (var x = 0; x < w; x++) {
            plane[oy + y][ox + x] = px[y][x];
          }
        }
      }

      // --- 2) OBMC: blend the top/left edges of each OBMC block with the
      // neighbour-MV strip predictions (captured geometry, applied in SW order).
      for (final s in _obmcStrips) {
        final plane = s[0],
            planeX = s[1],
            planeY = s[2],
            pbw = s[3],
            pbh = s[4];
        final x0 = s[5], y0 = s[6], subX = s[7], subY = s[8];
        final above = s[9] == 1;
        final ref = refPlane(plane), pl = reconPlane(plane);
        final strip = await mcRegion(ref, pbw, pbh, x0, y0, subX, subY);
        final key = pbw * 1000 + pbh;
        final mb = blends[key]!;
        final mask = HarborMaskBlend.obmcMask(pbw, pbh, above: above);
        var av = BigInt.zero, bv = BigInt.zero, mv = BigInt.zero;
        for (var i = 0; i < pbh; i++) {
          for (var j = 0; j < pbw; j++) {
            final idx = i * pbw + j;
            av |= BigInt.from(pl[planeY + i][planeX + j] & 0xFF) << (idx * 8);
            bv |= BigInt.from(strip[i][j] & 0xFF) << (idx * 8);
            mv |= BigInt.from(mask[idx] & 0x7F) << (idx * 7);
          }
        }
        blendA[key]!.inject(av);
        blendB[key]!.inject(bv);
        blendM[key]!.inject(mv);
        await clk.nextPosedge;
        final outv = mb.output('out').value;
        for (var i = 0; i < pbh; i++) {
          for (var j = 0; j < pbw; j++) {
            final idx = i * pbw + j;
            pl[planeY + i][planeX + j] = outv
                .getRange(idx * 8, idx * 8 + 8)
                .toInt();
          }
        }
      }

      // --- 3) Verify full frame vs SW pre-filter.
      var diffY = 0, diffU = 0, diffV = 0;
      for (var y = 0; y < hY; y++) {
        for (var x = 0; x < wY; x++) {
          if (reconY[y][x] != preY[y][x]) diffY++;
        }
      }
      for (var y = 0; y < hC; y++) {
        for (var x = 0; x < wC; x++) {
          if (reconU[y][x] != preU[y][x]) diffU++;
          if (reconV[y][x] != preV[y][x]) diffV++;
        }
      }
      expect(diffY, equals(0), reason: 'luma Y OBMC recon bit-exact');
      expect(diffU, equals(0), reason: 'chroma U OBMC recon bit-exact');
      expect(diffV, equals(0), reason: 'chroma V OBMC recon bit-exact');

      await Simulator.endSimulation();
    },
  );
}
