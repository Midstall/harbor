/// Reference sample with libaom edge replication.
int refAt(List<List<int>> p, int y, int x) {
  final h = p.length, w = p[0].length;
  final yy = y < 0 ? 0 : (y >= h ? h - 1 : y);
  final xx = x < 0 ? 0 : (x >= w ? w - 1 : x);
  return p[yy][xx];
}

BigInt packBytes(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xFF) << (i * 8);
  }
  return v;
}

BigInt packCdfs(List<List<int>> cdfs) {
  var v = BigInt.zero;
  for (var c = 0; c < _nCtx; c++) {
    final icdf = cdfs[c];
    for (var s = 0; s < _ms; s++) {
      final val = s < icdf.length ? icdf[s] : 0;
      v |= BigInt.from(val & 0xFFFF) << ((c * _ms + s) * 16);
    }
  }
  return v;
}

BigInt packNsyms(List<int> nsyms) {
  var v = BigInt.zero;
  for (var c = 0; c < _nCtx; c++) {
    v |= BigInt.from(nsyms[c] & 0x1F) << (c * 5);
  }
  return v;
}

int sgn16(int v) => v >= 0x8000 ? v - 0x10000 : v;

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'inter residual coeff decode + od_ec stays in sync to block end',
    () async {
      const maxBytes = 40;

      final t = HarborInterModeWalk(maxBytes: maxBytes, decodeResidual: true);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final allowHp = Logic(name: 'allow_hp');
      final forceInt = Logic(name: 'force_int');
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      final cdfIn = Logic(name: 'cdf_in', width: _nCtx * _ms * 16);
      final nsymsIn = Logic(name: 'nsyms_in', width: _nCtx * 5);

      void conn(String p, Logic s) => t.input(p).srcConnection! <= s;
      conn('clk', clk);
      conn('reset', reset);
      conn('start', start);
      conn('bytes', bytes);
      conn('allow_hp', allowHp);
      conn('force_integer_mv', forceInt);
      conn('dc_q', dcQ);
      conn('ac_q', acQ);
      conn('cdf_in', cdfIn);
      conn('nsyms_in', nsymsIn);
      await t.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(packBytes(_window));
      allowHp.inject(_allowHp);
      forceInt.inject(_forceInt);
      // chroma-U dequant steps (dc_q / ac_q from the frame's plane-1 dequant).
      dcQ.inject(_dcQ);
      acQ.inject(_acQ);
      cdfIn.inject(packCdfs(_cdfs));
      nsymsIn.inject(packNsyms(_nsyms));

      Simulator.setMaxSimTime(20000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 4000) fail('inter recon decode timeout');
      }

      int o(String n) => t.output(n).value.toInt();
      expect(sgn16(o('mv_row')), equals(_mvR));
      expect(sgn16(o('mv_col')), equals(_mvC));
      expect(o('y_all_zero'), equals(1), reason: 'luma Y all_zero');
      expect(o('u_all_zero'), equals(0), reason: 'chroma U has a coeff');
      expect(o('v_all_zero'), equals(1), reason: 'chroma V all_zero');
      expect(o('u_eob'), equals(1), reason: 'U eob = 1 (DC only)');
      expect(o('u_dc_level'), equals(2), reason: 'U DC level = 2');
      expect(o('u_dc_sign'), equals(1), reason: 'U DC sign negative');
      expect(sgn16(o('u_dc_coeff')), equals(_goldUDc), reason: 'U DC dequant');
      expect(
        o('rng'),
        equals(_goldEndRng),
        reason: 'od_ec rng sync at inter block END (post residual)',
      );
      expect(
        o('sym_count'),
        equals(24),
        reason: 'partition + 17 mode + 6 residual symbols',
      );

      await Simulator.endSimulation();
    },
  );

  test('inter block reconstruction bit-exact vs SW.preFilter (Y + U + V)', () async {
    const preY = _preY, preU = _preU, preV = _preV;
    // Decoded (verified in the entropy test) motion + residual for the block.
    const mvR = _mvR; // -16 (1/8-pel luma)
    const mvC = _mvC; // -24
    const uDc = _goldUDc; // -74 dequantized DC

    // Luma: integer MV -> a direct edge-clamped copy of the ref.
    // mvq = mv << 1 (1/16-pel). base = mvq >> 4. frac = mvq & 15 = 0 (integer).
    final lY0 = (mvR << 1) >> 4, lX0 = (mvC << 1) >> 4; // -2, -3
    final reconY = [
      for (var y = 0; y < 64; y++)
        [for (var x = 0; x < 64; x++) refAt(_refY, lY0 + y, lX0 + x)],
    ];
    expect(reconY, equals(preY), reason: 'luma integer-MV recon');

    // Chroma (4:2:0): mvq = mv << 0. base + half-pel horizontal.
    // x0 = mvq >> 4 = -2, subX = mvq & 15 = 8. y0 = -1, subY = 0.
    const cW = 32, cH = 32, subX = 8, subY = 0;
    final cX0 = mvC >> 4, cY0 = mvR >> 4; // -2, -1
    const pw = cW + 7, ph = cH + 7;

    // Build the HW sub-pel convolve core (bit-exact vs the SW reference horiz).
    final conv = HarborInterConvolve(width: cW, height: cH);
    final clk = SimpleClockGenerator(10).clk;
    final patch = Logic(name: 'patch', width: pw * ph * 8);
    final fracX = Logic(name: 'frac_x', width: 4);
    final fracY = Logic(name: 'frac_y', width: 4);
    conv.input('patch').srcConnection! <= patch;
    conv.input('frac_x').srcConnection! <= fracX;
    conv.input('frac_y').srcConnection! <= fracY;

    // U DC residual via the real HW inverse transform (TX_32X32, DCT_DCT).
    final itx = HarborInvTxfm(txSize: 3, txType: 0);
    final itxReset = Logic(name: 'itx_reset');
    final itxStart = Logic(name: 'itx_start');
    final itxCoeffs = Logic(name: 'itx_coeffs', width: 32 * 32 * 16);
    itx.input('clk').srcConnection! <= clk;
    itx.input('reset').srcConnection! <= itxReset;
    itx.input('start').srcConnection! <= itxStart;
    itx.input('coeffs').srcConnection! <= itxCoeffs;
    await conv.build();
    await itx.build();

    // Edge-replicated reference patch (row-major, LSB-first, phase-0 at (3,3)).
    BigInt packPatch(List<List<int>> ref) {
      var v = BigInt.zero;
      for (var pr = 0; pr < ph; pr++) {
        for (var pc = 0; pc < pw; pc++) {
          final s = refAt(ref, cY0 + pr - 3, cX0 + pc - 3);
          v |= BigInt.from(s & 0xFF) << ((pr * pw + pc) * 8);
        }
      }
      return v;
    }

    fracX.inject(subX);
    fracY.inject(subY);
    itxReset.inject(1);
    itxStart.inject(0);
    // DC-only 32x32 coeff buffer (row-major, signed 16b), DC = uDc.
    final coeffV = BigInt.from(uDc & 0xFFFF);
    itxCoeffs.inject(coeffV);

    Simulator.setMaxSimTime(200000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    itxReset.inject(0);

    // Predict U, then V, off the combinational convolve.
    patch.inject(packPatch(_refU));
    await clk.nextPosedge;
    final predU = List<int>.generate(
      cW * cH,
      (i) => conv.output('pred').value.getRange(i * 8, i * 8 + 8).toInt(),
    );
    patch.inject(packPatch(_refV));
    await clk.nextPosedge;
    final predV = List<int>.generate(
      cW * cH,
      (i) => conv.output('pred').value.getRange(i * 8, i * 8 + 8).toInt(),
    );

    // Inverse-transform the U DC residual.
    await clk.nextPosedge;
    itxStart.inject(1);
    await clk.nextPosedge;
    itxStart.inject(0);
    var guard = 0;
    while (itx.output('done').value.toInt() != 1) {
      await clk.nextPosedge;
      if (++guard > 20000) fail('inv txfm timeout');
    }
    int sres(int v) => v >= 0x8000 ? v - 0x10000 : v;
    final resid = List<int>.generate(
      cW * cH,
      (i) => sres(
        itx.output('residual').value.getRange(i * 16, i * 16 + 16).toInt(),
      ),
    );

    int clip8(int v) => v < 0 ? 0 : (v > 255 ? 255 : v);
    final reconU = [
      for (var y = 0; y < cH; y++)
        [
          for (var x = 0; x < cW; x++)
            clip8(predU[y * cW + x] + resid[y * cW + x]),
        ],
    ];
    final reconV = [
      for (var y = 0; y < cH; y++)
        [for (var x = 0; x < cW; x++) predV[y * cW + x]],
    ];

    expect(reconU, equals(preU), reason: 'chroma U half-pel MC + DC residual');
    expect(reconV, equals(preV), reason: 'chroma V half-pel MC');

    await Simulator.endSimulation();
  });
}
