        var v = BigInt.zero;
        for (var cc = 0; cc < nctx; cc++) {
          v |= BigInt.from(_t3Nsyms[cc] & 0x1F) << (cc * 5);
        }
        return v;
      }

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xFF) << (i * 8);
        }
        return v;
      }

      final t = HarborInterFrameWalk(maxBytes: maxBytes, enableTmvp: true);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final sigs = <String, Logic>{
        'bytes': Logic(width: maxBytes * 8),
        'allow_hp': Logic(),
        'force_integer_mv': Logic(),
        'tx_mode_select': Logic(),
        'skip_mode_present': Logic(),
        'ref_mode_select': Logic(),
        'skip_ref0': Logic(width: 3),
        'skip_ref1': Logic(width: 3),
        'sign_bias': Logic(width: 8),
        'enable_masked_compound': Logic(),
        'mm_switchable': Logic(),
        'allow_warped_motion': Logic(),
        'enable_interintra': Logic(),
        'cdf_in': Logic(width: nctx * msW * 16),
        'nsyms_in': Logic(width: nctx * 5),
        'use_ref_frame_mvs': Logic(),
        'tpl_valid': Logic(width: 64),
        'tpl_mvrow': Logic(width: 64 * 16),
        'tpl_mvcol': Logic(width: 64 * 16),
        'tpl_refoff': Logic(width: 64 * 6),
        'cur_off': Logic(width: 7 * 8),
      };
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      sigs.forEach((p, s) => t.input(p).srcConnection! <= s);
      await t.build();

      reset.inject(1);
      start.inject(0);
      sigs['bytes']!.inject(packBytes(_t3Window));
      sigs['allow_hp']!.inject(_t3AllowHp ? 1 : 0);
      sigs['force_integer_mv']!.inject(_t3ForceInt);
      sigs['tx_mode_select']!.inject(_t3TxSel ? 1 : 0);
      sigs['skip_mode_present']!.inject(0);
      sigs['ref_mode_select']!.inject(0);
      sigs['skip_ref0']!.inject(1);
      sigs['skip_ref1']!.inject(7);
      sigs['sign_bias']!.inject(_t3SignBias);
      sigs['enable_masked_compound']!.inject(1);
      sigs['mm_switchable']!.inject(_t3MmSw ? 1 : 0);
      sigs['allow_warped_motion']!.inject(_t3AllowWarp ? 1 : 0);
      sigs['enable_interintra']!.inject(0);
      sigs['cdf_in']!.inject(packCdfs());
      sigs['nsyms_in']!.inject(packNsyms());
      sigs['use_ref_frame_mvs']!.inject(1);
      sigs['tpl_valid']!.inject(_t3TplValidV);
      sigs['tpl_mvrow']!.inject(_t3TplRowV);
      sigs['tpl_mvcol']!.inject(_t3TplColV);
      sigs['tpl_refoff']!.inject(_t3TplOffV);
      sigs['cur_off']!.inject(_t3CurOff);

      Simulator.setMaxSimTime(400000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);

      int sgn16(int v) => v >= 0x8000 ? v - 0x10000 : v;
      final hwRng = <int>[];
      final hwBlocks = <List<int>>[];
      var guard = 0;
      while (true) {
        final doneV = t.output('done').value;
        if (doneV.isValid && doneV.toInt() == 1) break;
        if (!doneV.isValid) fail('done went X after ${hwRng.length} symbols');
        await clk.nextPosedge;
        final sv = t.output('sym_valid').value;
        if (sv.isValid && sv.toInt() == 1) {
          final rv = t.output('rng').value;
          hwRng.add(rv.isValid ? rv.toInt() : -1);
        }
        final bv = t.output('block_valid').value;
        if (bv.isValid && bv.toInt() == 1) {
          hwBlocks.add([
            t.output('blk_r').value.toInt(),
            t.output('blk_c').value.toInt(),
            t.output('blk_bs').value.toInt(),
            t.output('blk_mode').value.toInt(),
            t.output('blk_ref0').value.toInt(),
            sgn16(t.output('blk_mvrow').value.toInt()),
            sgn16(t.output('blk_mvcol').value.toInt()),
            t.output('blk_modectx').value.toInt(),
            t.output('blk_count').value.toInt(),
          ]);
        }
        if (++guard > 200000) fail('inter frame decode timeout');
      }

      var firstDiff = -1;
      final nCmp = hwRng.length < _t3Rng.length ? hwRng.length : _t3Rng.length;
      for (var i = 0; i < nCmp; i++) {
        if (hwRng[i] != _t3Rng[i]) {
          firstDiff = i;
          break;
        }
      }
      if (firstDiff >= 0) {
        // ignore: avoid_print
        print(
          'FIRST DIVERGENCE at symbol $firstDiff: HW rng=${hwRng[firstDiff]} '
          'SW rngAfter=${_t3Rng[firstDiff]}',
        );
      }
      // ignore: avoid_print
      print(
        'HW ${hwRng.length} symbols; SW ${_t3Rng.length}. In sync through '
        '${firstDiff < 0 ? nCmp - 1 : firstDiff - 1}.',
      );

      final sw0 = _t3Blocks;
      // Per-block diff (position/mode/ref/MV/mode_context/count).
      for (var i = 0; i < sw0.length && i < hwBlocks.length; i++) {
        final gg = sw0[i];
        final bb = hwBlocks[i];
        if (bb[0] != gg[0] ||
            bb[1] != gg[1] ||
            bb[3] != gg[5] ||
            bb[4] != gg[4] ||
            bb[5] != gg[7] ||
            bb[6] != gg[8] ||
            bb[7] != gg[9] ||
            bb[8] != gg[10]) {
          // ignore: avoid_print
          print(
            'block $i HW r=${bb[0]} c=${bb[1]} mode=${bb[3]} ref=${bb[4]} '
            'mv=(${bb[5]},${bb[6]}) mctx=${bb[7]} cnt=${bb[8]} | SW r=${gg[0]} '
            'c=${gg[1]} mode=${gg[5]} ref=${gg[4]} mv=(${gg[7]},${gg[8]}) '
            'mctx=${gg[9]} cnt=${gg[10]}',
          );
          break;
        }
      }

      expect(firstDiff, equals(-1), reason: 'every od_ec symbol matches SW');
      expect(
        hwRng.length,
        equals(_t3ExpSyms),
        reason: 'HW decodes all symbols',
      );
      expect(
        hwRng.last,
        equals(_t3ExpRng),
        reason: 'frame-end rng == ${_t3ExpRng}',
      );
      expect(hwBlocks.length, equals(sw0.length), reason: 'all blocks decoded');
      for (var i = 0; i < sw0.length; i++) {
        final gg = sw0[i];
        final bb = hwBlocks[i];
        expect(
          [bb[0], bb[1], bb[2]],
          equals([gg[0], gg[1], gg[2]]),
          reason: 'block $i position/size',
        );
        expect(bb[3], equals(gg[5]), reason: 'block $i inter_mode');
        expect(bb[4], equals(gg[4]), reason: 'block $i ref0');
        expect([bb[5], bb[6]], equals([gg[7], gg[8]]), reason: 'block $i MV');
        expect(bb[7], equals(gg[9]), reason: 'block $i mode_context');
        expect(bb[8], equals(gg[10]), reason: 'block $i refMvCount');
      }
      await Simulator.endSimulation();
    },
  );
}
