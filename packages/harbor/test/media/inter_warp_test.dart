// signed helper matching Dart-native int64 semantics for the warp setup
int _asr(int v, int n) => v >> n; // Dart >> is arithmetic

int refAt(List<List<int>> p, int y, int x) {
  final h = p.length, w = p[0].length;
  final yy = y < 0 ? 0 : (y >= h ? h - 1 : y);
  final xx = x < 0 ? 0 : (x >= w ? w - 1 : x);
  return p[yy][xx];
}

/// Decode a warpCapture record into named fields (see the SW reference decoder).
class _WarpRec {
  final int r, c, bSize, ref0, mvR0, mvC0, np, valid;
  final List<int> mat; // 6
  final int alpha, beta, gamma, delta;
  final List<int> pts1, pts2; // 2*np each
  _WarpRec(List<int> w)
    : r = w[0],
      c = w[1],
      bSize = w[2],
      ref0 = w[3],
      mvR0 = w[4],
      mvC0 = w[5],
      np = w[6],
      valid = w[7],
      mat = w.sublist(8, 14),
      alpha = w[14],
      beta = w[15],
      gamma = w[16],
      delta = w[17],
      pts1 = w.sublist(18, 18 + 2 * w[6]),
      pts2 = w.sublist(18 + 2 * w[6], 18 + 4 * w[6]);
}

