      final convSizes = <int>{};
      for (var p = 0; p < _numPlanes; p++) {
        final sx = p == 0 ? 0 : ssx, sy = p == 0 ? 0 : ssy;
        final mvqR = _simple[3] << (1 - sy), mvqC = _simple[4] << (1 - sx);
        if ((mvqC & 15) != 0 || (mvqR & 15) != 0) {
          final pbw = (_simpleMiW * 4) >> sx;
          final pbh = (_simpleMiH * 4) >> sy;
          convSizes.add(pbw * 1000 + pbh);
        }
      }
      final convs = <int, HarborInterConvolve>{};
      final convPatch = <int, Logic>{};
      final convFx = <int, Logic>{};
      final convFy = <int, Logic>{};
      for (final key in convSizes) {
        final w = key ~/ 1000, h = key % 1000;
        final conv = HarborInterConvolve(width: w, height: h);
        final patch = Logic(name: 'cp_${w}x$h', width: (w + 7) * (h + 7) * 8);
        final fx = Logic(name: 'cfx_${w}x$h', width: 4);
        final fy = Logic(name: 'cfy_${w}x$h', width: 4);
        conv.input('patch').srcConnection! <= patch;
        conv.input('frac_x').srcConnection! <= fx;
        conv.input('frac_y').srcConnection! <= fy;
        convs[key] = conv;
        convPatch[key] = patch;
        convFx[key] = fx;
        convFy[key] = fy;
      }

      final clk = SimpleClockGenerator(10).clk;
      await est.build();
      await wa.build();
      for (final conv in convs.values) {
        await conv.build();
      }
      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;

      // Estimate the warp model in HW for one block, returns mat[6]+abgd+valid.
      Future<Map<String, dynamic>> estimate(_WarpRec w, int bw, int bh) async {
        BigInt packCoords(List<int> pts) {
          var v = BigInt.zero;
          for (var i = 0; i < 2 * w.np; i++) {
            v |= BigInt.from(pts[i] & ((1 << coordW) - 1)) << (i * coordW);
          }
          return v;
        }

        npL.inject(w.np);
        pts1L.inject(packCoords(w.pts1));
        pts2L.inject(packCoords(w.pts2));
        bwL.inject(bw);
        bhL.inject(bh);
        mvxL.inject(w.mvC0 & 0xFFFF);
        mvyL.inject(w.mvR0 & 0xFFFF);
        miRowL.inject(w.r);
        miColL.inject(w.c);
        await clk.nextPosedge;
        int sMat(int i) {
          final v = est.output('mat$i').value.toInt();
          return v >= (1 << 31) ? v - (1 << 32) : v;
        }

        int s16(String p) {
          final v = est.output(p).value.toInt();
          return v >= (1 << 15) ? v - (1 << 16) : v;
        }

        return {
          'valid': est.output('valid').value.toInt(),
          'mat': [for (var i = 0; i < 6; i++) sMat(i)],
          'alpha': s16('alpha'),
          'beta': s16('beta'),
          'gamma': s16('gamma'),
          'delta': s16('delta'),
        };
      }

      // Warp one plane block via HarborWarpAffine per 8x8 (SW warpAffine geometry).
      Future<void> warpBlock(
        List<int> mat,
        int alpha,
        int beta,
        int gamma,
        int delta,
        List<List<int>> ref,
        List<List<int>> plane,
        int pCol,
        int pRow,
        int pW,
        int pH,
        int subX,
        int subY,
      ) async {
        for (var i = pRow; i < pRow + pH; i += 8) {
          for (var j = pCol; j < pCol + pW; j += 8) {
            final srcX = (j + 4) << subX;
            final srcY = (i + 4) << subY;
            final dstX = mat[2] * srcX + mat[3] * srcY + mat[0];
            final dstY = mat[4] * srcX + mat[5] * srcY + mat[1];
            final x4 = _asr(dstX, subX);
            final y4 = _asr(dstY, subY);
            final ix4 = _asr(x4, 16);
            var sx4 = x4 & 0xFFFF;
            final iy4 = _asr(y4, 16);
            var sy4 = y4 & 0xFFFF;
            sx4 += alpha * -4 + beta * -4;
            sy4 += gamma * -4 + delta * -4;
            sx4 &= ~63;
            sy4 &= ~63;
            // 15x15 edge-clamped patch around (iy4,ix4).
            var pv = BigInt.zero;
            for (var pr = 0; pr < 15; pr++) {
              for (var pc = 0; pc < 15; pc++) {
                final s = refAt(ref, iy4 - 7 + pr, ix4 - 7 + pc);
                pv |= BigInt.from(s & 0xFF) << ((pr * 15 + pc) * 8);
              }
            }
            patchL.inject(pv);
            sx4L.inject(sx4 & 0xFFFFF);
            sy4L.inject(sy4 & 0xFFFFF);
            alL.inject(alpha & 0xFFFF);
            beL.inject(beta & 0xFFFF);
            gaL.inject(gamma & 0xFFFF);
            deL.inject(delta & 0xFFFF);
            await clk.nextPosedge;
            final pred = wa.output('pred').value;
            for (var oy = 0; oy < 8; oy++) {
              for (var ox = 0; ox < 8; ox++) {
                plane[i + oy][j + ox] = pred
                    .getRange((oy * 8 + ox) * 8, (oy * 8 + ox) * 8 + 8)
                    .toInt();
              }
            }
          }
        }
      }

      for (var p = 0; p < _numPlanes; p++) {
        final sx = p == 0 ? 0 : ssx, sy = p == 0 ? 0 : ssy;
        final ref = refPlane(p), plane = reconPlane(p);
        final ox = (_simple[1] * 4) >> sx, oy = (_simple[0] * 4) >> sy;
        final pbw = (_simpleMiW * 4) >> sx;
        final pbh = (_simpleMiH * 4) >> sy;
        final mvqR = _simple[3] << (1 - sy), mvqC = _simple[4] << (1 - sx);
        final x0 = (ox * 16 + mvqC) >> 4, subX = mvqC & 15;
        final y0 = (oy * 16 + mvqR) >> 4, subY = mvqR & 15;
        if (subX == 0 && subY == 0) {
          for (var y = 0; y < pbh; y++) {
            for (var x = 0; x < pbw; x++) {
              plane[oy + y][ox + x] = refAt(ref, y0 + y, x0 + x);
            }
          }
        } else {
          final key = pbw * 1000 + pbh;
          final conv = convs[key]!;
          final pw = pbw + 7, ph = pbh + 7;
          var v = BigInt.zero;
          for (var pr = 0; pr < ph; pr++) {
            for (var pc = 0; pc < pw; pc++) {
              final s = refAt(ref, y0 + pr - 3, x0 + pc - 3);
              v |= BigInt.from(s & 0xFF) << ((pr * pw + pc) * 8);
            }
          }
          convPatch[key]!.inject(v);
          convFx[key]!.inject(subX);
          convFy[key]!.inject(subY);
          await clk.nextPosedge;
          final pred = conv.output('pred').value;
          for (var y = 0; y < pbh; y++) {
            for (var x = 0; x < pbw; x++) {
              plane[oy + y][ox + x] = pred
                  .getRange((y * pbw + x) * 8, (y * pbw + x) * 8 + 8)
                  .toInt();
            }
          }
        }
      }

      for (var wi = 0; wi < recs.length; wi++) {
        final w = recs[wi];
        final m = await estimate(w, _recBw[wi], _recBh[wi]);
        // The HW model must match SW (asserted here too, so recon uses HW model).
        expect(
          m['valid'],
          equals(w.valid),
          reason: 'recon blk r=${w.r} c=${w.c} valid',
        );
        expect(
          m['mat'],
          equals(w.mat),
          reason: 'recon blk r=${w.r} c=${w.c} mat',
        );
        final mat = m['mat'] as List<int>;
        final alpha = m['alpha'] as int, beta = m['beta'] as int;
        final gamma = m['gamma'] as int, delta = m['delta'] as int;
        final miW = _recMiW[wi], miH = _recMiH[wi];
        for (var p = 0; p < _numPlanes; p++) {
          final sx = p == 0 ? 0 : ssx, sy = p == 0 ? 0 : ssy;
          final ref = refPlane(p), plane = reconPlane(p);
          final ox = (w.c * 4) >> sx, oy = (w.r * 4) >> sy;
          var pbw = (miW * 4) >> sx;
          var pbh = (miH * 4) >> sy;
          if (ox + pbw > planeW(p)) pbw = planeW(p) - ox;
          if (oy + pbh > planeH(p)) pbh = planeH(p) - oy;
          // Warp requires the plane block >= 8x8, else translation. Here 32x32
          // luma / 16x16 chroma both qualify.
          final planeBw = (miW * 4) >> sx;
          final planeBh = (miH * 4) >> sy;
          expect(planeBw >= 8 && planeBh >= 8, isTrue);
          await warpBlock(
            mat,
            alpha,
            beta,
            gamma,
            delta,
            ref,
            plane,
            ox,
            oy,
            pbw,
            pbh,
            sx,
            sy,
          );
        }
      }

      var diffY = 0, diffU = 0, diffV = 0;
      for (var y = 0; y < hY; y++) {
        for (var x = 0; x < wY; x++) {
          if (reconY[y][x] != preY[y][x]) diffY++;
        }
      }
      for (var y = 0; y < hC; y++) {
        for (var x = 0; x < wC; x++) {
          if (reconU[y][x] != preU[y][x]) diffU++;
          if (reconV[y][x] != preV[y][x]) diffV++;
        }
      }
      expect(diffY, equals(0), reason: 'luma Y warp recon bit-exact');
      expect(diffU, equals(0), reason: 'chroma U warp recon bit-exact');
      expect(diffV, equals(0), reason: 'chroma V warp recon bit-exact');

      await Simulator.endSimulation();
    },
  );
}
