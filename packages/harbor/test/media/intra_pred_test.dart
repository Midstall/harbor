// Golden predictors captured from the reference libaom predictIntraRaw
// (non-directional modes), embedded below. See end of file.
void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // AV1 non-directional modes: DC, V, H, SMOOTH, SMOOTH_V, SMOOTH_H, PAETH.
  const modes = [0, 1, 2, 9, 10, 11, 12];

  for (final bs in [4, 8, 16]) {
    group('HarborIntraPred bs=$bs', () {
      late HarborIntraPred t;
      late Logic clk, mode, above, left, aboveLeft;

      Future<void> setUpDut() async {
        t = HarborIntraPred(bs: bs);
        clk = SimpleClockGenerator(10).clk;
        mode = Logic(name: 'mode', width: 4);
        above = Logic(name: 'above', width: bs * 8);
        left = Logic(name: 'left', width: bs * 8);
        aboveLeft = Logic(name: 'above_left', width: 8);
        t.input('mode').srcConnection! <= mode;
        t.input('above').srcConnection! <= above;
        t.input('left').srcConnection! <= left;
        t.input('above_left').srcConnection! <= aboveLeft;
        await t.build();
        mode.inject(0);
        above.inject(0);
        left.inject(0);
        aboveLeft.inject(0);
        Simulator.setMaxSimTime(20000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
      }

      BigInt pack(List<int> v) {
        var x = BigInt.zero;
        for (var i = 0; i < v.length; i++) {
          x |= BigInt.from(v[i] & 0xff) << (i * 8);
        }
        return x;
      }

      test('matches libaom predictIntraRaw (non-directional)', () async {
        await setUpDut();
        final golden = bs == 4
            ? _goldenPred4
            : (bs == 8 ? _goldenPred8 : _goldenPred16);
        var gi = 0;
        final rng = Random(0x1D7A + bs);
        for (final m in modes) {
          for (var iter = 0; iter < 8; iter++) {
            final av = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
            final lf = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
            final corner = rng.nextInt(256);

            mode.inject(m);
            above.inject(pack(av));
            left.inject(pack(lf));
            aboveLeft.inject(corner);
            await clk.nextPosedge;

            final want = golden.sublist(gi * bs * bs, (gi + 1) * bs * bs);
            gi++;
            final pv = t.output('pred').value.toBigInt();
            final got = [
              for (var i = 0; i < bs * bs; i++)
                ((pv >> (i * 8)) & BigInt.from(0xff)).toInt(),
            ];
            expect(got, equals(want), reason: 'mode=$m bs=$bs iter=$iter');
          }
        }
        await Simulator.endSimulation();
      });
    });
  }
}

