@Tags(['slow'])
library;

import 'dart:async';
import 'dart:math';

import 'package:harbor/src/media/intra_recon_block_seq.dart';
import 'package:rohd/rohd.dart';
import 'package:test/test.dart';

// Sequential single-block intra recon (predict + inverse transform + clip, row
// by row) vs a Dart golden. bs=8/16 use runtime tx_type, bs=32 is DCTONLY
// (fixed DCT). Proves the row-sequential recon core reconstructs bit-exact and
// (crucially) BUILDS fast at bs=32 where the flat recon walk could not.
void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // (bs, txSize, [tx_types to exercise])
  // 64x64 (txSize 4) is supported by the module but its ROHD build is very
  // heavy (4096-flop block + O(bs^2) residual-row mux + the 64x64 transform +
  // bs=64 predictor) and exceeds a practical timeout, deferred as a build
  // optimization (the architecture is proven at 4/8/16/32).
  final cases = [
    (8, 1, [0, 1, 9, 10]),
    (16, 2, [0, 1]),
    (32, 3, [0]),
  ];

  for (final cs in cases) {
    final bs = cs.$1, txSize = cs.$2, txTypes = cs.$3;
    final rtt = txSize <= 2;
    test(
      'HarborIntraReconBlockSeq bs=$bs recon matches golden',
      timeout: const Timeout(Duration(minutes: 20)),
      () async {
        final t = HarborIntraReconBlockSeq(bs: bs);
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final mode = Logic(name: 'mode', width: 4);
        final haveA = Logic(name: 'have_above');
        final haveL = Logic(name: 'have_left');
        final above = Logic(name: 'above', width: bs * 8);
        final left = Logic(name: 'left', width: bs * 8);
        final corner = Logic(name: 'above_left', width: 8);
        final coeffs = Logic(name: 'coeffs', width: bs * bs * 16);
        final txType = rtt ? Logic(name: 'tx_type', width: 4) : null;
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('mode').srcConnection! <= mode;
        t.input('have_above').srcConnection! <= haveA;
        t.input('have_left').srcConnection! <= haveL;
        t.input('above').srcConnection! <= above;
        t.input('left').srcConnection! <= left;
        t.input('above_left').srcConnection! <= corner;
        t.input('coeffs').srcConnection! <= coeffs;
        if (rtt) t.input('tx_type').srcConnection! <= txType!;
        await t.build();
        reset.inject(1);
        start.inject(0);
        mode.inject(0);
        haveA.inject(0);
        haveL.inject(0);
        above.inject(0);
        left.inject(0);
        corner.inject(0);
        coeffs.inject(0);
        if (rtt) txType!.inject(0);
        Simulator.setMaxSimTime(200000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        BigInt packB(List<int> b) {
          var v = BigInt.zero;
          for (var i = 0; i < b.length; i++) {
            v |= BigInt.from(b[i] & 0xff) << (i * 8);
          }
          return v;
        }

        BigInt packCoeffs(List<int> co) {
          var v = BigInt.zero;
          for (var i = 0; i < co.length; i++) {
            v |= BigInt.from(co[i] & 0xffff) << (i * 16);
          }
          return v;
        }

        var gi = 0;
        final rng = Random(0x5EC + bs);
        for (final ym in [0, 1, 6, 9, 12]) {
          for (final tt in txTypes) {
            final co = List<int>.filled(bs * bs, 0);
            // AV1 64x64 keeps coeffs only in the top-left 32x32 region.
            final cr32 = bs > 32 ? 32 : bs;
            for (var i = 0; i < bs; i++) {
              final r = rng.nextInt(cr32), c = rng.nextInt(cr32);
              co[r * bs + c] = rng.nextInt(1024) - 512;
            }
            final av0 = rng.nextInt(2), lv0 = rng.nextInt(2);
            final av = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
            final lf = [for (var i = 0; i < bs; i++) rng.nextInt(256)];
            final cr = rng.nextInt(256);

            mode.inject(ym);
            haveA.inject(av0);
            haveL.inject(lv0);
            above.inject(packB(av));
            left.inject(packB(lf));
            corner.inject(cr);
            coeffs.inject(packCoeffs(co));
            if (rtt) txType!.inject(tt);
            start.inject(1);
            await clk.nextPosedge;
            start.inject(0);
            var guard = 0;
            while (t.output('done').value.toInt() != 1) {
              await clk.nextPosedge;
              if (++guard > 5000) fail('timeout bs=$bs ym=$ym tt=$tt');
            }
            final bv = t.output('block').value.toBigInt();
            final got = [
              for (var p = 0; p < bs * bs; p++)
                ((bv >> (p * 8)) & BigInt.from(0xff)).toInt(),
            ];

            // Golden captured from reference predictIntraRaw + inverseTransform.
            final want = _goldenBlockSeq['$bs']![gi];
            gi++;
            expect(
              got,
              equals(want),
              reason: 'bs=$bs ym=$ym tt=$tt av0=$av0 lv0=$lv0',
            );
            await clk.nextPosedge;
          }
        }
        await Simulator.endSimulation();
      },
    );
  }
}

