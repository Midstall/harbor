// Validates the maxLog2:3 generalization of HarborIntraReconWalk: a single
// 32x32 leaf (log2size 3) at the plane origin, coeffs fed directly, checked vs
// a Dart golden (intra predict with no neighbours + inverse TX_32X32 + clip).
// This is the cheap de-risk for the new 32x32 predictor/transform lane before
// the slow full mode-walk -> recon chain.
void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'HarborIntraReconWalk(maxLog2:3): single 32x32 leaf pixels',
    timeout: const Timeout(Duration(minutes: 15)),
    () async {
      const sbSize = 32, maxLeaves = 1, side = 32, nPix = sbSize * sbSize;
      final t = HarborIntraReconWalk(
        sbSize: sbSize,
        maxLeaves: maxLeaves,
        maxLog2: 3,
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final leafCount = Logic(
        name: 'leaf_count',
        width: t.input('leaf_count').width,
      );
      final positions = Logic(
        name: 'positions',
        width: t.input('positions').width,
      );
      final log2sizes = Logic(
        name: 'log2sizes',
        width: t.input('log2sizes').width,
      );
      final yModes = Logic(name: 'y_modes', width: t.input('y_modes').width);
      final txTypes = Logic(name: 'tx_types', width: t.input('tx_types').width);
      final coeffs = Logic(name: 'coeffs', width: t.input('coeffs').width);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('leaf_count').srcConnection! <= leafCount;
      t.input('positions').srcConnection! <= positions;
      t.input('log2sizes').srcConnection! <= log2sizes;
      t.input('y_modes').srcConnection! <= yModes;
      t.input('tx_types').srcConnection! <= txTypes;
      t.input('coeffs').srcConnection! <= coeffs;
      await t.build();

      reset.inject(1);
      start.inject(0);
      leafCount.inject(0);
      positions.inject(0);
      log2sizes.inject(0);
      yModes.inject(0);
      txTypes.inject(0);
      coeffs.inject(0);
      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      var gi = 0;
      final rng = Random(0x320320);
      // a few directional + non-directional modes, tx_type is DCT_DCT (32x32).
      for (final ym in [0, 1, 6, 9, 12]) {
        // sparse-ish signed coeffs so the residual is meaningful but bounded.
        final co = List<int>.filled(side * side, 0);
        for (var i = 0; i < 40; i++) {
          final pos = rng.nextInt(side * side);
          co[pos] = rng.nextInt(2048) - 1024;
        }
        BigInt packCoeffs() {
          var v = BigInt.zero;
          for (var i = 0; i < side * side; i++) {
            v |= BigInt.from(co[i] & 0xffff) << (i * 16);
          }
          return v;
        }

        leafCount.inject(1);
        positions.inject(0); // MI (0,0)
        log2sizes.inject(3); // 32x32
        yModes.inject(ym);
        txTypes.inject(0); // DCT_DCT
        coeffs.inject(packCoeffs());
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 5000) fail('timeout ym=$ym');
        }
        final fv = t.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < nPix; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];

        // golden: no neighbours (origin leaf), predict + inverse TX_32X32 + clip.
        // Captured from the reference predictIntraRaw + inverseTransform.
        final want = _goldenWalk32.sublist(gi * nPix, (gi + 1) * nPix);
        gi++;
        expect(got, equals(want), reason: 'ym=$ym');
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    },
  );
}

