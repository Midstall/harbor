@Tags(['slow'])
library;

import 'dart:async';
import 'dart:math';

import 'package:harbor/src/media/intra_recon_walk_seq.dart';
import 'package:rohd/rohd.dart';
import 'package:test/test.dart';

// HarborIntraReconWalkSeq (row-sequential recon) vs a Dart golden. Covers a
// single 16x16 leaf, four 8x8 leaves (cross-leaf neighbours), and a single
// 32x32 leaf (the size the flat recon walk could not build). The golden mirrors
// the origin-pinned per-leaf recon: construct neighbours from the frame so far,
// predict + inverse transform + clip, write the block into the frame. Goldens
// captured from that reference are embedded at the end of the file.

class _Leaf {
  final int miR, miC, log2, mode, txType;
  final List<int> coeffs; // side*side signed, row-major
  _Leaf(this.miR, this.miC, this.log2, this.mode, this.txType, this.coeffs);
  int get side => 4 << log2;
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // (label, sbSize, maxLeaves, leaves-builder)
  final configs = <(String, int, int, List<_Leaf> Function(Random))>[
    ('one 16x16', 16, 1, (rng) => [_Leaf(0, 0, 2, 6, 0, _rc(rng, 16))]),
    (
      'four 8x8',
      16,
      4,
      (rng) => [
        for (final p in const [
          [0, 0],
          [0, 2],
          [2, 0],
          [2, 2],
        ])
          _Leaf(p[0], p[1], 1, rng.nextInt(13), 0, _rc(rng, 8)),
      ],
    ),
    ('one 32x32', 32, 1, (rng) => [_Leaf(0, 0, 3, 9, 0, _rc(rng, 32))]),
    (
      'four 32x32',
      64,
      4,
      (rng) => [
        for (final p in const [
          [0, 0],
          [0, 8],
          [8, 0],
          [8, 8],
        ])
          _Leaf(p[0], p[1], 3, rng.nextInt(13), 0, _rc(rng, 32)),
      ],
    ),
  ];

  for (final cfg in configs) {
    final label = cfg.$1, sbSize = cfg.$2, maxLeaves = cfg.$3, build = cfg.$4;
    test(
      'HarborIntraReconWalkSeq $label matches golden',
      timeout: const Timeout(Duration(minutes: 20)),
      () async {
        // cap at 3 (32x32 max leaf): the 64x64 leaf recon build is too heavy.
        final maxLog2 = ((sbSize ~/ 4).bitLength - 1).clamp(1, 3);
        final maxSide = 4 << maxLog2;
        final coeffN = maxSide * maxSide;
        final miBits = (sbSize ~/ 4).bitLength;
        final t = HarborIntraReconWalkSeq(
          sbSize: sbSize,
          maxLeaves: maxLeaves,
          maxLog2: maxLog2,
        );
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final leafCount = Logic(
          name: 'leaf_count',
          width: t.input('leaf_count').width,
        );
        final positions = Logic(
          name: 'positions',
          width: t.input('positions').width,
        );
        final log2sizes = Logic(
          name: 'log2sizes',
          width: t.input('log2sizes').width,
        );
        final yModes = Logic(name: 'y_modes', width: t.input('y_modes').width);
        final txTypes = Logic(
          name: 'tx_types',
          width: t.input('tx_types').width,
        );
        final coeffs = Logic(name: 'coeffs', width: t.input('coeffs').width);
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('leaf_count').srcConnection! <= leafCount;
        t.input('positions').srcConnection! <= positions;
        t.input('log2sizes').srcConnection! <= log2sizes;
        t.input('y_modes').srcConnection! <= yModes;
        t.input('tx_types').srcConnection! <= txTypes;
        t.input('coeffs').srcConnection! <= coeffs;
        await t.build();
        reset.inject(1);
        for (final s in [start]) {
          s.inject(0);
        }
        leafCount.inject(0);
        positions.inject(0);
        log2sizes.inject(0);
        yModes.inject(0);
        txTypes.inject(0);
        coeffs.inject(0);
        Simulator.setMaxSimTime(400000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        final rng = Random(0xABC + sbSize + maxLeaves);
        for (var iter = 0; iter < 3; iter++) {
          final leaves = build(rng);
          // pack leaf arrays.
          var posV = BigInt.zero, l2V = BigInt.zero, ymV = BigInt.zero;
          var ttV = BigInt.zero, coV = BigInt.zero;
          for (var l = 0; l < leaves.length; l++) {
            final lf = leaves[l];
            posV |=
                BigInt.from(lf.miR | (lf.miC << miBits)) << (l * 2 * miBits);
            l2V |= BigInt.from(lf.log2) << (l * 2);
            ymV |= BigInt.from(lf.mode) << (l * 4);
            ttV |= BigInt.from(lf.txType) << (l * 4);
            for (var i = 0; i < lf.side * lf.side; i++) {
              coV |=
                  BigInt.from(lf.coeffs[i] & 0xffff) << ((l * coeffN + i) * 16);
            }
          }
          leafCount.inject(leaves.length);
          positions.inject(posV);
          log2sizes.inject(l2V);
          yModes.inject(ymV);
          txTypes.inject(ttV);
          coeffs.inject(coV);
          start.inject(1);
          await clk.nextPosedge;
          start.inject(0);
          var guard = 0;
          while (t.output('done').value.toInt() != 1) {
            await clk.nextPosedge;
            if (++guard > 40000) fail('timeout $label iter=$iter');
          }
          final fv = t.output('frame').value.toBigInt();
          final got = [
            for (var p = 0; p < sbSize * sbSize; p++)
              ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
          ];
          final want = _goldenWalkSeq[label]![iter];
          expect(got, equals(want), reason: '$label iter=$iter');
          await clk.nextPosedge;
          await clk.nextPosedge;
        }
        await Simulator.endSimulation();
      },
    );
  }
}

List<int> _rc(Random rng, int side) {
  final co = List<int>.filled(side * side, 0);
  for (var i = 0; i < side; i++) {
    co[rng.nextInt(side * side)] = rng.nextInt(1024) - 512;
  }
  return co;
}

