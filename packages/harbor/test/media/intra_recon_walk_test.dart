// Generalized recon walk over a list of VARIABLE SQUARE intra leaves (4x4 /
// 8x8 / 16x16) tiling a square superblock plane, reconstructed in decode/raster
// order with cross-leaf neighbour propagation through the frame RAM, vs a
// self-contained software golden (a generalization of keyframe_recon_grid).
//
// Intra ext-tx set only (no FLIPADST): valid for the runtime predictor /
// transform at all three sizes.
const _intraSet = [9, 0, 10, 11, 3, 1, 2];

// One leaf in the layout: mi (row, col) in 4x4 units, log2 size (0/1/2), and
// (filled by the test) mode / tx_type / coeffs sized to the leaf.
class _Leaf {
  final int miR;
  final int miC;
  final int log2;
  _Leaf(this.miR, this.miC, this.log2);
  int get side => 4 << log2;
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // all 4x4: 16 leaves over a 16x16 SB, decode (raster) order.
  runWalkTest(
    'all-4x4 16x16',
    16,
    [
      for (var r = 0; r < 4; r++)
        for (var c = 0; c < 4; c++) _Leaf(r, c, 0),
    ],
    iters: 6,
    seed: 0x4444,
  );

  // all 8x8: 4 leaves over a 16x16 SB, raster order of the 2x2 8x8 grid.
  runWalkTest(
    'all-8x8 16x16',
    16,
    [
      for (var r = 0; r < 2; r++)
        for (var c = 0; c < 2; c++) _Leaf(r * 2, c * 2, 1),
    ],
    iters: 6,
    seed: 0x8888,
  );

  // single 16x16 leaf.
  runWalkTest('single 16x16', 16, [_Leaf(0, 0, 2)], iters: 8, seed: 0x1616);

  // mixed 4x4 / 8x8: top-left quadrant split into 4x4, the other three 8x8.
  // Decode order: the four 4x4 of the TL quadrant, then the three 8x8.
  runWalkTest(
    'mixed 4x4/8x8 16x16',
    16,
    [
      _Leaf(0, 0, 0), _Leaf(0, 1, 0), _Leaf(1, 0, 0), _Leaf(1, 1, 0), // TL 4x4
      _Leaf(0, 2, 1), // TR 8x8
      _Leaf(2, 0, 1), // BL 8x8
      _Leaf(2, 2, 1), // BR 8x8
    ],
    iters: 6,
    seed: 0x5a5a,
  );
}

void runWalkTest(
  String label,
  int sbSize,
  List<_Leaf> layout, {
  required int iters,
  required int seed,
}) {
  final mw = sbSize ~/ 4; // mi units per side
  final maxLeaves = 16;
  final cntW = (maxLeaves + 1).bitLength;
  final miBits = mw.bitLength; // bits to hold a mi coordinate (0..mw)

  test('HarborIntraReconWalk $label', () async {
    final t = HarborIntraReconWalk(sbSize: sbSize, maxLeaves: maxLeaves);
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final leafCount = Logic(name: 'leaf_count', width: cntW);
    final positions = Logic(name: 'positions', width: maxLeaves * 2 * miBits);
    final log2sizes = Logic(name: 'log2sizes', width: maxLeaves * 2);
    final yModes = Logic(name: 'y_modes', width: maxLeaves * 4);
    final txTypes = Logic(name: 'tx_types', width: maxLeaves * 4);
    final coeffs = Logic(name: 'coeffs', width: maxLeaves * 256 * 16);

    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('leaf_count').srcConnection! <= leafCount;
    t.input('positions').srcConnection! <= positions;
    t.input('log2sizes').srcConnection! <= log2sizes;
    t.input('y_modes').srcConnection! <= yModes;
    t.input('tx_types').srcConnection! <= txTypes;
    t.input('coeffs').srcConnection! <= coeffs;
    await t.build();

    reset.inject(1);
    start.inject(0);
    leafCount.inject(0);
    positions.inject(0);
    log2sizes.inject(0);
    yModes.inject(0);
    txTypes.inject(0);
    coeffs.inject(0);
    Simulator.setMaxSimTime(200000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    final rng = Random(seed);
    final nLeaf = layout.length;
    final f = sbSize;

    for (var iter = 0; iter < iters; iter++) {
      // per-leaf random mode / tx_type / coeffs (sized to the leaf).
      final ym = [for (var l = 0; l < nLeaf; l++) rng.nextInt(13)];
      final tt = [for (var l = 0; l < nLeaf; l++) _intraSet[rng.nextInt(7)]];
      final co = [
        for (var l = 0; l < nLeaf; l++)
          [
            for (var i = 0; i < layout[l].side * layout[l].side; i++)
              rng.nextInt(4096) - 2048,
          ],
      ];

      // golden: raster recon over the leaf list into an f x f frame, captured
      // from the reference predictIntraRaw + inverseTransform.
      final frame = _goldenWalk[label]![iter];

      // pack inputs.
      var posV = BigInt.zero;
      var l2V = BigInt.zero;
      var ymV = BigInt.zero;
      var ttV = BigInt.zero;
      var coV = BigInt.zero;
      for (var l = 0; l < nLeaf; l++) {
        final lf = layout[l];
        // position: miR at low miBits, miC at high miBits.
        final pos = lf.miR | (lf.miC << miBits);
        posV |= BigInt.from(pos) << (l * 2 * miBits);
        l2V |= BigInt.from(lf.log2) << (l * 2);
        ymV |= BigInt.from(ym[l]) << (l * 4);
        ttV |= BigInt.from(tt[l]) << (l * 4);
        for (var i = 0; i < co[l].length; i++) {
          coV |= BigInt.from(co[l][i] & 0xffff) << (l * 256 * 16 + i * 16);
        }
      }

      leafCount.inject(nLeaf);
      positions.inject(posV);
      log2sizes.inject(l2V);
      yModes.inject(ymV);
      txTypes.inject(ttV);
      coeffs.inject(coV);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 2000) fail('timeout iter=$iter');
      }
      final fv = t.output('frame').value.toBigInt();
      final got = [
        for (var p = 0; p < f * f; p++)
          ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
      ];
      expect(got, equals(frame), reason: 'iter=$iter ym=$ym tt=$tt');
      await clk.nextPosedge;
    }
    await Simulator.endSimulation();
  });
}

