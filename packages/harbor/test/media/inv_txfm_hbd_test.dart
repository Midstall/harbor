// Goldens captured from the bit-exact software decoder's inverse transform are
// embedded at the end (keyed by '${bd}_${txSize}_$txType', one per block).
// Small sizes only (fast builds). Validates the 10/12-bit stage-range and
// clamp-width threading. cores are already proven at 8-bit across all sizes.
const _wide = {0: 4, 1: 8, 5: 4, 6: 8};
const _high = {0: 4, 1: 8, 5: 8, 6: 4};
const _names = {0: 'TX_4X4', 1: 'TX_8X8', 5: 'TX_4X8', 6: 'TX_8X4'};

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  BigInt pack(List<int> c, int w) {
    var v = BigInt.zero;
    for (var i = 0; i < c.length; i++) {
      v |= BigInt.from(c[i]).toUnsigned(w) << (i * w);
    }
    return v;
  }

  List<int> unpack(BigInt v, int n, int w) {
    final mask = (BigInt.one << w) - BigInt.one;
    final half = BigInt.one << (w - 1);
    final full = BigInt.one << w;
    return [
      for (var i = 0; i < n; i++)
        (() {
          final raw = (v >> (i * w)) & mask;
          return (raw >= half ? raw - full : raw).toInt();
        })(),
    ];
  }

  for (final bd in [10, 12]) {
    for (final txSize in _wide.keys) {
      final txw = _wide[txSize]!;
      final txh = _high[txSize]!;
      final n = txw * txh;
      final outW = bd + 8;

      for (var txType = 0; txType < 16; txType++) {
        final key = '${bd}_${txSize}_$txType';
        if (!_goldenHbdInv.containsKey(key)) continue;

        test('HarborInvTxfm bd=$bd ${_names[txSize]} txType=$txType', () async {
          final t = HarborInvTxfm(txSize: txSize, txType: txType, bitDepth: bd);
          final clk = SimpleClockGenerator(10).clk;
          final reset = Logic(name: 'reset');
          final start = Logic(name: 'start');
          final coeffs = Logic(name: 'coeffs', width: n * outW);
          t.input('clk').srcConnection! <= clk;
          t.input('reset').srcConnection! <= reset;
          t.input('start').srcConnection! <= start;
          t.input('coeffs').srcConnection! <= coeffs;
          await t.build();
          reset.inject(1);
          start.inject(0);
          coeffs.inject(0);
          Simulator.setMaxSimTime(50000000);
          unawaited(Simulator.run());
          await clk.nextPosedge;
          reset.inject(0);
          await clk.nextPosedge;

          final rng = Random(0xB0 + bd * 19 + txSize * 16 + txType);
          // High-bit-depth coefficients span a wider range.
          final blocks = <List<int>>[
            [400, ...List.filled(n - 1, 0)],
            [for (var i = 0; i < n; i++) (i % 4 == 0) ? (i * 11 - 60) : 0],
            [for (var i = 0; i < n; i++) rng.nextInt(8192) - 4096],
            [for (var i = 0; i < n; i++) rng.nextInt(1 << 15) - (1 << 14)],
          ];

          for (var bi = 0; bi < blocks.length; bi++) {
            final b = blocks[bi];
            coeffs.inject(pack(b, outW));
            start.inject(1);
            await clk.nextPosedge;
            start.inject(0);
            var guard = 0;
            while (t.output('done').value.toInt() != 1) {
              await clk.nextPosedge;
              if (++guard > txw + txh + 16) fail('timeout');
            }
            final got = unpack(t.output('residual').value.toBigInt(), n, outW);
            final want = _goldenHbdInv[key]![bi];
            expect(
              got,
              equals(want),
              reason: 'bd=$bd ${_names[txSize]} txType=$txType',
            );
            await clk.nextPosedge;
          }
          await Simulator.endSimulation();
        });
      }
    }
  }
}

