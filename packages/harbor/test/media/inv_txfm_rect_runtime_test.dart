// Goldens captured from the bit-exact software decoder's inverse transform are
// embedded at the end (keyed by '${txSize}_$txType', one residual per block).
// Verify HarborInvTxfm with runtimeTxType for the RECTANGULAR intra transform
// sizes (both dims <= 16). Recon selects the tx_type per leaf at runtime, so the
// rect inverse transform must accept a runtime tx_type just like the square
// TX_4X4/8X8/16X16 path already does. The intra rect ext-tx sets are entirely
// non-FLIPADST: DTT4_IDTX_1DDCT for max dim 8 (adds V_DCT=10 / H_DCT=11) and
// DTT4_IDTX for max dim 16. This drives every applicable intra type and diffs
// the residual against sw.inverseTransform (which is bit-exact vs libaom).

