const _names = {
  5: 'TX_4X8',
  6: 'TX_8X4',
  7: 'TX_8X16',
  8: 'TX_16X8',
  13: 'TX_4X16',
  14: 'TX_16X4',
};

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  BigInt pack(List<int> c) {
    var v = BigInt.zero;
    for (var i = 0; i < c.length; i++) {
      v |= BigInt.from(c[i] & 0xFFFF) << (i * 16);
    }
    return v;
  }

  List<int> unpack(BigInt v, int n) => [
    for (var i = 0; i < n; i++)
      (() {
        final raw = ((v >> (i * 16)) & BigInt.from(0xFFFF)).toInt();
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      })(),
  ];

  // Intra rect ext-tx types. Max dim 8 -> DTT4_IDTX_1DDCT (adds V_DCT/H_DCT),
  // max dim 16 -> DTT4_IDTX. All non-FLIPADST.
  List<int> intraTypes(int txSize) {
    final maxDim = _wide[txSize] > _high[txSize]
        ? _wide[txSize]
        : _high[txSize];
    return maxDim <= 8 ? const [0, 1, 2, 3, 9, 10, 11] : const [0, 1, 2, 3, 9];
  }

  for (final txSize in _names.keys) {
    final txw = _wide[txSize];
    final txh = _high[txSize];
    final n = txw * txh;

    for (final txType in intraTypes(txSize)) {
      final key = '${txSize}_$txType';
      test('HarborInvTxfm ${_names[txSize]} runtime txType=$txType', () async {
        final t = HarborInvTxfm(txSize: txSize, txType: 0, runtimeTxType: true);
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final coeffs = Logic(name: 'coeffs', width: n * 16);
        final ttype = Logic(name: 'tx_type', width: 4);
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('coeffs').srcConnection! <= coeffs;
        t.input('tx_type').srcConnection! <= ttype;
        await t.build();
        reset.inject(1);
        start.inject(0);
        coeffs.inject(0);
        ttype.inject(txType);
        Simulator.setMaxSimTime(500000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        final rng = Random(0x5A1 + txSize * 16 + txType);
        final blocks = <(String, List<int>)>[
          ('dc only', [200, ...List.filled(n - 1, 0)]),
          (
            'sparse',
            [for (var i = 0; i < n; i++) (i % 5 == 0) ? (i * 3 - 30) : 0],
          ),
          ('ramp', [for (var i = 0; i < n; i++) (i * 7 - n * 3)]),
          ('random a', [for (var i = 0; i < n; i++) rng.nextInt(1024) - 512]),
          ('random b', [for (var i = 0; i < n; i++) rng.nextInt(2048) - 1024]),
        ];

        for (var bi = 0; bi < blocks.length; bi++) {
          final b = blocks[bi];
          coeffs.inject(pack(b.$2));
          ttype.inject(txType);
          start.inject(1);
          await clk.nextPosedge;
          start.inject(0);
          var guard = 0;
          while (t.output('done').value.toInt() != 1) {
            await clk.nextPosedge;
            if (++guard > txw + txh + 16) {
              fail('timeout: ${_names[txSize]} $txType ${b.$1}');
            }
          }
          final got = unpack(t.output('residual').value.toBigInt(), n);
          final want = _goldenRectRt[key]![bi];
          expect(
            got,
            equals(want),
            reason: '${_names[txSize]} runtime txType=$txType ${b.$1}',
          );
          await clk.nextPosedge;
        }
        await Simulator.endSimulation();
      });
    }
  }
}

