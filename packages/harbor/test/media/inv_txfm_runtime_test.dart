// Goldens captured from the bit-exact software decoder's inverse transform are
// embedded at the end (keyed by '${txSize}_$tt', one residual per block).
// The 4x4 / 8x8 intra ext-tx set (DTT4_IDTX_1DDCT), inverse map -> TX_TYPE.
// All seven use DCT/ADST/IDTX 1D cores with NO flips, so a runtime-typed
// transform can mux them without runtime buffer flipping.
const _intraSet = [9, 0, 10, 11, 3, 1, 2];
const _names = ['TX_4X4', 'TX_8X8'];

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  BigInt pack(List<int> c) {
    var v = BigInt.zero;
    for (var i = 0; i < c.length; i++) {
      v |= BigInt.from(c[i] & 0xFFFF) << (i * 16);
    }
    return v;
  }

  List<int> unpack(BigInt v, int n) => [
    for (var i = 0; i < n; i++)
      (() {
        final raw = ((v >> (i * 16)) & BigInt.from(0xFFFF)).toInt();
        return raw >= 0x8000 ? raw - 0x10000 : raw;
      })(),
  ];

  for (var txSize = 0; txSize < 2; txSize++) {
    final dim = txSize == 0 ? 4 : 8;
    final n = dim * dim;

    test(
      'HarborInvTxfm runtimeTxType ${_names[txSize]} (all 7 intra types)',
      () async {
        final t = HarborInvTxfm(txSize: txSize, txType: 0, runtimeTxType: true);
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final coeffs = Logic(name: 'coeffs', width: n * 16);
        final txType = Logic(name: 'tx_type', width: 4);
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('coeffs').srcConnection! <= coeffs;
        t.input('tx_type').srcConnection! <= txType;
        await t.build();
        reset.inject(1);
        start.inject(0);
        coeffs.inject(0);
        txType.inject(0);
        Simulator.setMaxSimTime(500000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        final rng = Random(0xD17 + txSize);
        for (final tt in _intraSet) {
          final blocks = <List<int>>[
            [200, ...List.filled(n - 1, 0)],
            [for (var i = 0; i < n; i++) (i % 5 == 0) ? (i * 3 - 30) : 0],
            [for (var i = 0; i < n; i++) rng.nextInt(1024) - 512],
            [for (var i = 0; i < n; i++) rng.nextInt(2048) - 1024],
          ];
          for (var bi = 0; bi < blocks.length; bi++) {
            final b = blocks[bi];
            coeffs.inject(pack(b));
            txType.inject(tt);
            start.inject(1);
            await clk.nextPosedge;
            start.inject(0);
            var guard = 0;
            while (t.output('done').value.toInt() != 1) {
              await clk.nextPosedge;
              if (++guard > dim * 2 + 16) {
                fail('timeout ${_names[txSize]} txType=$tt');
              }
            }
            final got = unpack(t.output('residual').value.toBigInt(), n);
            final want = _goldenRt['${txSize}_$tt']![bi];
            expect(
              got,
              equals(want),
              reason: '${_names[txSize]} txType=$tt b=$b',
            );
            await clk.nextPosedge;
          }
        }
        await Simulator.endSimulation();
      },
    );
  }
}

