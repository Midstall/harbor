// Phase-2 gate: 12-bit MONOCHROME intra keyframe decode + luma recon bit-exact
// vs the conformant software decoder. Drives the REAL Harbor HW engine
// (HarborKeyframeModeWalk + HarborIntraReconWalkSeq) at bitDepth: 12 with a REAL
// aomenc 3.12.1 12-bit keyframe OBU and diffs the HW reconstruction against
// SW.preFilterY (the pre-in-loop-filter reconstruction, == recon for this
// filterless encode). Mirrors keyframe_10bit_recon_test exactly, only the bit
// depth (and the 12-bit dc/ac qlookup + the 12-bit inverse-transform stage-range
// / intermediate-clamp bumps + wider coeff / pixel datapaths) is different.
//
// Stream: aomenc --obu --allintra --monochrome --bit-depth=12 --cq-level=4
//   --enable-tx64=0 --enable-rect-tx=0 --enable-rect-partitions=0
//   --enable-ab-partitions=0 --enable-1to4-partitions=0 --min-partition-size=16
//   --max-partition-size=16 --enable-filter-intra=0 --enable-palette=0
//   --enable-intrabc=0 --enable-angle-delta=0 --enable-intra-edge-filter=0
//   --enable-diagonal-intra=0 --use-intra-dct-only=1 --enable-cdef=0
//   --enable-restoration=0     (source: a smooth (40+r+c)*16 12-bit luma ramp)
// -> a 64x64 SB uniformly split into sixteen 16x16 TX_16X16 leaves, modes in
// {DC,V,H,SMOOTH,PAETH}, DCT_DCT, base_qindex 16 (qband 0). bd=12 dc_q=166
// ac_q=183, TX_MODE_LARGEST.
//
// The tile bytes, dc_q/ac_q, qband, tx_mode, per-leaf luma modes and the
// SW.preFilterY golden are captured from the conformant software decoder
// and embedded as consts at the end of this file.

const _bd = 12;

// DFS/Z-order leaf index -> (miRow, miCol) for a 64x64 SB uniformly split into
// sixteen 16x16 leaves.
List<int> _leafMi(int leaf) {
  final q = leaf >> 2, s = leaf & 3;
  return [(q >> 1) * 8 + (s >> 1) * 4, (q & 1) * 8 + (s & 1) * 4];
}

BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'ingest: 12-bit 64x64 monochrome keyframe -> tile bytes + dc_q/ac_q',
    () {
      expect(_mono, isTrue);
      expect([_frameW, _frameH], equals([64, 64]));
      expect(_qband, equals(0));
      expect(_dcQ, equals(166), reason: '12-bit dc qlookup at qindex 16');
      expect(_acQ, equals(183), reason: '12-bit ac qlookup at qindex 16');
      expect(_bd, equals(12));
      expect(_swY.length, equals(64));
      // uniform 16x16 partition: 16 leaves, all intra, non-directional modes.
      for (var l = 0; l < 16; l++) {
        expect(_leafModes[l], lessThanOrEqualTo(12));
      }
    },
  );

  test(
    '12-bit monochrome keyframe: HW luma recon == SW.preFilterY (bit-exact)',
    timeout: const Timeout(Duration(minutes: 90)),
    () async {
      final swY = _swY; // [64][64], 12-bit samples

      const maxBytes = 192;
      const sbSize = 64;
      const maxLeaves = 16;
      const cw = _bd + 8; // dequant-coeff element width (18)

      // --- HW mode-walk: real tile bytes -> per-leaf luma modes/tx/coeffs -------
      final walk = HarborKeyframeModeWalk(
        rootBsize: 12,
        maxBytes: maxBytes,
        coeffPrefix: true,
        txLeaf: true,
        maxTxN: 256, // TX_16X16 leaves
        chroma: false, // monochrome
        maxLeafOut: maxLeaves,
        qband: _qband,
        txModeSelect: _txMode == 2, // TX_MODE_LARGEST here
        bitDepth: _bd,
        name: 'walk',
      );
      final wClk = SimpleClockGenerator(10).clk;
      final wReset = Logic(name: 'wreset');
      final wStart = Logic(name: 'wstart');
      final wBytes = Logic(name: 'wbytes', width: maxBytes * 8);
      final wDcQ = Logic(name: 'wdcq', width: 16);
      final wAcQ = Logic(name: 'wacq', width: 16);
      walk.input('clk').srcConnection! <= wClk;
      walk.input('reset').srcConnection! <= wReset;
      walk.input('start').srcConnection! <= wStart;
      walk.input('bytes').srcConnection! <= wBytes;
      walk.input('dc_q').srcConnection! <= wDcQ;
      walk.input('ac_q').srcConnection! <= wAcQ;
      await walk.build();

      wReset.inject(1);
      wStart.inject(0);
      wBytes.inject(_pack(_tileBytes));
      wDcQ.inject(_dcQ);
      wAcQ.inject(_acQ);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await wClk.nextPosedge;
      wReset.inject(0);
      await wClk.nextPosedge;
      wStart.inject(1);
      await wClk.nextPosedge;
      wStart.inject(0);
      var guard = 0;
      while (walk.output('done').value.toInt() != 1) {
        await wClk.nextPosedge;
        if (++guard > 500000) fail('mode-walk decode timeout');
      }

      final leafCount = walk.output('leaf_count').value.toInt();
      final ym = walk.output('leaf_ymodes').value.toBigInt();
      final l2 = walk.output('leaf_log2size').value.toBigInt();
      final tt = walk.output('leaf_txtypes').value.toBigInt();
      final cf = walk.output('leaf_coeffs').value.toBigInt();
      expect(
        leafCount,
        equals(16),
        reason: 'uniform-16x16 64x64 SB must produce 16 leaves',
      );
      for (var l = 0; l < 16; l++) {
        final hw = ((ym >> (l * 4)) & BigInt.from(0xf)).toInt();
        expect(hw, equals(_leafModes[l]), reason: 'leaf $l y_mode desync');
      }

      await Simulator.endSimulation();
      await Simulator.reset();

      // --- HW luma recon: per-leaf arrays -> 64x64 10-bit luma plane -----------
      final recon = HarborIntraReconWalkSeq(
        sbSize: sbSize,
        maxLeaves: maxLeaves,
        maxLog2: 2,
        bitDepth: _bd,
        name: 'recon',
      );
      const miBits = 5;
      const coeffN = 256; // 16x16
      final rClk = SimpleClockGenerator(10).clk;
      final rReset = Logic(name: 'rreset');
      final rStart = Logic(name: 'rstart');
      final rLeafCount = Logic(
        name: 'rleafcount',
        width: recon.input('leaf_count').width,
      );
      final rPositions = Logic(
        name: 'rpositions',
        width: maxLeaves * 2 * miBits,
      );
      final rLog2 = Logic(name: 'rlog2', width: maxLeaves * 2);
      final rYModes = Logic(name: 'rymodes', width: maxLeaves * 4);
      final rTxTypes = Logic(name: 'rtxtypes', width: maxLeaves * 4);
      final rCoeffs = Logic(name: 'rcoeffs', width: maxLeaves * coeffN * cw);
      recon.input('clk').srcConnection! <= rClk;
      recon.input('reset').srcConnection! <= rReset;
      recon.input('start').srcConnection! <= rStart;
      recon.input('leaf_count').srcConnection! <= rLeafCount;
      recon.input('positions').srcConnection! <= rPositions;
      recon.input('log2sizes').srcConnection! <= rLog2;
      recon.input('y_modes').srcConnection! <= rYModes;
      recon.input('tx_types').srcConnection! <= rTxTypes;
      recon.input('coeffs').srcConnection! <= rCoeffs;
      await recon.build();

      var positions = BigInt.zero, log2v = BigInt.zero, txv = BigInt.zero;
      for (var l = 0; l < 16; l++) {
        final p = _leafMi(l);
        positions |= BigInt.from(p[0] | (p[1] << miBits)) << (l * 2 * miBits);
        final walkLog2 = ((l2 >> (l * 3)) & BigInt.from(0x7)).toInt();
        log2v |= BigInt.from(walkLog2 - 2) << (l * 2);
        txv |= ((tt >> (l * 4)) & BigInt.from(0xf)) << (l * 4);
      }

      rReset.inject(1);
      rStart.inject(0);
      rLeafCount.inject(16);
      rPositions.inject(positions);
      rLog2.inject(log2v);
      rYModes.inject(ym);
      rTxTypes.inject(txv);
      rCoeffs.inject(cf);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await rClk.nextPosedge;
      rReset.inject(0);
      await rClk.nextPosedge;
      rStart.inject(1);
      await rClk.nextPosedge;
      rStart.inject(0);
      guard = 0;
      while (recon.output('done').value.toInt() != 1) {
        await rClk.nextPosedge;
        if (++guard > 2000000) fail('recon timeout');
      }
      final frame = recon.output('frame').value.toBigInt();
      final mask = BigInt.from((1 << _bd) - 1);
      int px(int r, int c) =>
          ((frame >> ((r * sbSize + c) * _bd)) & mask).toInt();

      var firstDiff = '';
      var diffs = 0;
      for (var r = 0; r < 64; r++) {
        for (var c = 0; c < 64; c++) {
          if (px(r, c) != swY[r][c]) {
            diffs++;
            firstDiff = firstDiff.isEmpty
                ? 'first diff @($r,$c): HW=${px(r, c)} SW=${swY[r][c]}'
                : firstDiff;
          }
        }
      }
      expect(
        diffs,
        equals(0),
        reason: '$diffs/4096 luma pixels differ; $firstDiff',
      );
      await Simulator.endSimulation();
    },
  );
}

