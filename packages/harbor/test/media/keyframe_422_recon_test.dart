// Phase-2 gate: 4:2:2 (HALF-width, FULL-height chroma) intra keyframe decode +
// FULL Y+U+V reconstruction, bit-exact vs the conformant SW decoder. Drives the
// REAL Harbor HW engine (HarborKeyframeModeWalk at ssx=1,ssy=0: per-leaf TX_8X16
// chroma + the 16x16 luma tx_size depth-1 split, HarborIntraReconWalkSeq for luma
// with depth-1 leaves expanded to four 8x8 sub-leaves, HarborIntraPredRect(8,16)
// + HarborInvTxfm(TX_8X16) for the rect chroma recon) with a REAL aomenc 3.12.1
// 4:2:2 keyframe OBU, diffing HW recon against SW.preFilterY/U/V.

const _intraModeToTxType = [0, 1, 2, 0, 3, 1, 2, 2, 1, 3, 1, 2, 3];

List<int> _leafMi(int leaf) {
  final q = leaf >> 2, s = leaf & 3;
  return [(q >> 1) * 8 + (s >> 1) * 4, (q & 1) * 8 + (s & 1) * 4];
}

BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

class _Walk {
  final int leafCount;
  final BigInt ym, log2, lumaTx, lumaCoeffs, uvm, uc, vc, txDepth;
  _Walk(
    this.leafCount,
    this.ym,
    this.log2,
    this.lumaTx,
    this.lumaCoeffs,
    this.uvm,
    this.uc,
    this.vc,
    this.txDepth,
  );
}

Future<_Walk> _walk(int bd, int maxBytes) async {
  const maxLeaves = 16;
  final walk = HarborKeyframeModeWalk(
    rootBsize: 12,
    maxBytes: maxBytes,
    coeffPrefix: true,
    txLeaf: true,
    maxTxN: 256,
    chroma: true,
    chromaLeaf16: true,
    ssx: 1, // 4:2:2: half-width chroma
    ssy: 0,
    maxLeafOut: maxLeaves,
    qband: _qband8,
    txModeSelect: _txMode8 == 2,
    bitDepth: bd,
    name: 'walk',
  );
  final clk = SimpleClockGenerator(10).clk;
  final reset = Logic(name: 'wreset');
  final start = Logic(name: 'wstart');
  final bytes = Logic(name: 'wbytes', width: maxBytes * 8);
  final dcQ = Logic(name: 'wdcq', width: 16);
  final acQ = Logic(name: 'wacq', width: 16);
  walk.input('clk').srcConnection! <= clk;
  walk.input('reset').srcConnection! <= reset;
  walk.input('start').srcConnection! <= start;
  walk.input('bytes').srcConnection! <= bytes;
  walk.input('dc_q').srcConnection! <= dcQ;
  walk.input('ac_q').srcConnection! <= acQ;
  await walk.build();
  reset.inject(1);
  start.inject(0);
  bytes.inject(_pack(_tileBytes8));
  dcQ.inject(_dcQ8);
  acQ.inject(_acQ8);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await clk.nextPosedge;
  reset.inject(0);
  await clk.nextPosedge;
  start.inject(1);
  await clk.nextPosedge;
  start.inject(0);
  var guard = 0;
  while (walk.output('done').value.toInt() != 1) {
    await clk.nextPosedge;
    if (++guard > 500000) fail('walk timeout');
  }
  final w = _Walk(
    walk.output('leaf_count').value.toInt(),
    walk.output('leaf_ymodes').value.toBigInt(),
    walk.output('leaf_log2size').value.toBigInt(),
    walk.output('leaf_luma_txtypes').value.toBigInt(),
    walk.output('leaf_coeffs').value.toBigInt(),
    walk.output('leaf_uv_modes').value.toBigInt(),
    walk.output('leaf_u_coeffs_arr').value.toBigInt(),
    walk.output('leaf_v_coeffs_arr').value.toBigInt(),
    walk.output('leaf_tx_depth').value.toBigInt(),
  );
  await Simulator.endSimulation();
  await Simulator.reset();
  return w;
}

Future<void> _runBd(int bd) async {
  const sbSize = 64, maxLeaves = 16, miBits = 5, coeffN = 256, chromaN = 128;
  final cw = bd + 8;
  const maxBytes = 2048;
  expect(_tileBytes8.length, lessThan(maxBytes));
  final swY = _swY8, swU = _swU8, swV = _swV8;

  final w = await _walk(bd, maxBytes);
  expect(w.leafCount, equals(maxLeaves));

  final cmask = (BigInt.one << cw) - BigInt.one;
  BigInt lc(int leaf, int idx) =>
      (w.lumaCoeffs >> ((leaf * coeffN + idx) * cw)) & cmask;
  final ePos = <int>[];
  final eLog2 = <int>[], eYm = <int>[], eTx = <int>[];
  final eCoeffs = <BigInt>[];
  for (var l = 0; l < maxLeaves; l++) {
    final p = _leafMi(l);
    final depth = ((w.txDepth >> (l * 2)) & BigInt.from(3)).toInt();
    final ym = ((w.ym >> (l * 4)) & BigInt.from(0xf)).toInt();
    final tx = ((w.lumaTx >> (l * 4)) & BigInt.from(0xf)).toInt();
    if (depth == 0) {
      ePos.add(p[0] | (p[1] << miBits));
      eLog2.add(2);
      eYm.add(ym);
      eTx.add(tx);
      var cv = BigInt.zero;
      for (var i = 0; i < coeffN; i++) {
        cv |= lc(l, i) << (i * cw);
      }
      eCoeffs.add(cv);
    } else {
      for (var sb = 0; sb < 4; sb++) {
        final qr = sb >> 1, qc = sb & 1;
        ePos.add((p[0] + qr * 2) | ((p[1] + qc * 2) << miBits));
        eLog2.add(1);
        eYm.add(ym);
        eTx.add(tx);
        var cv = BigInt.zero;
        for (var i8 = 0; i8 < 64; i8++) {
          final idx256 = (qr * 8 + (i8 ~/ 8)) * 16 + qc * 8 + (i8 % 8);
          cv |= lc(l, idx256) << (i8 * cw);
        }
        eCoeffs.add(cv);
      }
    }
  }
  final nRecon = ePos.length;

  final recon = HarborIntraReconWalkSeq(
    sbSize: sbSize,
    maxLeaves: nRecon,
    maxLog2: 2,
    bitDepth: bd,
    name: 'recon',
  );
  final rClk = SimpleClockGenerator(10).clk;
  final rReset = Logic(name: 'rreset');
  final rStart = Logic(name: 'rstart');
  final rLeafCount = Logic(name: 'rlc', width: recon.input('leaf_count').width);
  final rPositions = Logic(name: 'rpos', width: nRecon * 2 * miBits);
  final rLog2 = Logic(name: 'rlog2', width: nRecon * 2);
  final rYModes = Logic(name: 'rym', width: nRecon * 4);
  final rTxTypes = Logic(name: 'rtx', width: nRecon * 4);
  final rCoeffs = Logic(name: 'rco', width: nRecon * coeffN * cw);
  recon.input('clk').srcConnection! <= rClk;
  recon.input('reset').srcConnection! <= rReset;
  recon.input('start').srcConnection! <= rStart;
  recon.input('leaf_count').srcConnection! <= rLeafCount;
  recon.input('positions').srcConnection! <= rPositions;
  recon.input('log2sizes').srcConnection! <= rLog2;
  recon.input('y_modes').srcConnection! <= rYModes;
  recon.input('tx_types').srcConnection! <= rTxTypes;
  recon.input('coeffs').srcConnection! <= rCoeffs;
  await recon.build();

  var positions = BigInt.zero, log2v = BigInt.zero, txv = BigInt.zero;
  var ymv = BigInt.zero, coeffsv = BigInt.zero;
  for (var l = 0; l < nRecon; l++) {
    positions |= BigInt.from(ePos[l]) << (l * 2 * miBits);
    log2v |= BigInt.from(eLog2[l]) << (l * 2);
    ymv |= BigInt.from(eYm[l]) << (l * 4);
    txv |= BigInt.from(eTx[l]) << (l * 4);
    coeffsv |= eCoeffs[l] << (l * coeffN * cw);
  }
  rReset.inject(1);
  rStart.inject(0);
  rLeafCount.inject(nRecon);
  rPositions.inject(positions);
  rLog2.inject(log2v);
  rYModes.inject(ymv);
  rTxTypes.inject(txv);
  rCoeffs.inject(coeffsv);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await rClk.nextPosedge;
  rReset.inject(0);
  await rClk.nextPosedge;
  rStart.inject(1);
  await rClk.nextPosedge;
  rStart.inject(0);
  var guard = 0;
  while (recon.output('done').value.toInt() != 1) {
    await rClk.nextPosedge;
    if (++guard > 2000000) fail('luma recon timeout');
  }
  final frame = recon.output('frame').value.toBigInt();
  final ymask = BigInt.from((1 << bd) - 1);
  int ypx(int r, int c) => ((frame >> ((r * sbSize + c) * bd)) & ymask).toInt();
  var yDiffs = 0;
  var yFirst = '';
  for (var r = 0; r < 64; r++) {
    for (var c = 0; c < 64; c++) {
      if (ypx(r, c) != swY[r][c]) {
        yDiffs++;
        yFirst = yFirst.isEmpty
            ? 'Y($r,$c) HW=${ypx(r, c)} SW=${swY[r][c]}'
            : yFirst;
      }
    }
  }
  await Simulator.endSimulation();
  await Simulator.reset();
  expect(yDiffs, equals(0), reason: 'bd=$bd $yDiffs/4096 luma differ; $yFirst');

  // chroma plane 32 wide x 64 tall, block (br,bc) at (br*16, bc*8).
  final leafOf = List.generate(4, (_) => List<int>.filled(4, 0));
  for (var l = 0; l < maxLeaves; l++) {
    final p = _leafMi(l);
    leafOf[p[0] ~/ 4][p[1] ~/ 4] = l;
  }

  final pred = HarborIntraPredRect(bw: 8, bh: 16, name: 'cpred');
  final itx = HarborInvTxfm(
    txSize: 7,
    txType: 0,
    runtimeTxType: true,
    bitDepth: bd,
    name: 'citx',
  );
  final iClk = SimpleClockGenerator(10).clk;
  final iReset = Logic(name: 'ireset');
  final iStart = Logic(name: 'istart');
  final iCoeffs = Logic(name: 'icoef', width: 8 * 16 * cw);
  final iTxType = Logic(name: 'itxt', width: 4);
  final pMode = Logic(name: 'pmode', width: 4);
  final pHaveA = Logic(name: 'pha');
  final pHaveL = Logic(name: 'phl');
  final pAbove = Logic(name: 'pab', width: 8 * 8);
  final pLeft = Logic(name: 'plf', width: 16 * 8);
  final pAL = Logic(name: 'pal', width: 8);
  itx.input('clk').srcConnection! <= iClk;
  itx.input('reset').srcConnection! <= iReset;
  itx.input('start').srcConnection! <= iStart;
  itx.input('coeffs').srcConnection! <= iCoeffs;
  itx.input('tx_type').srcConnection! <= iTxType;
  pred.input('mode').srcConnection! <= pMode;
  pred.input('have_above').srcConnection! <= pHaveA;
  pred.input('have_left').srcConnection! <= pHaveL;
  pred.input('above').srcConnection! <= pAbove;
  pred.input('left').srcConnection! <= pLeft;
  pred.input('above_left').srcConnection! <= pAL;
  await itx.build();
  await pred.build();

  final rsignW = cw; // residual element width bd+8
  final rmask = (BigInt.one << rsignW) - BigInt.one;

  Future<List<List<int>>> reconChroma(
    int planeNum,
    BigInt coeffArr,
    List<List<int>> sw,
  ) async {
    final plane = List.generate(64, (_) => List<int>.filled(32, 0));
    iReset.inject(1);
    iStart.inject(0);
    for (final l in [
      iCoeffs,
      iTxType,
      pMode,
      pHaveA,
      pHaveL,
      pAbove,
      pLeft,
      pAL,
    ]) {
      l.inject(0);
    }
    Simulator.setMaxSimTime(2000000000);
    unawaited(Simulator.run());
    await iClk.nextPosedge;
    iReset.inject(0);
    await iClk.nextPosedge;
    for (var br = 0; br < 4; br++) {
      for (var bc = 0; bc < 4; bc++) {
        final l = leafOf[br][bc];
        final y0 = br * 16, x0 = bc * 8;
        final haveA = br > 0, haveL = bc > 0;
        final uvMode = ((w.uvm >> (l * 4)) & BigInt.from(0xf)).toInt();
        expect(uvMode, lessThan(13), reason: 'unexpected CfL leaf');
        final txType = _intraModeToTxType[uvMode];
        // coeffs: leaf l's 128 (8x16 row-major).
        var coeffs = BigInt.zero;
        for (var i = 0; i < chromaN; i++) {
          final v = (coeffArr >> ((l * chromaN + i) * cw)) & cmask;
          coeffs |= v << (i * cw);
        }
        var above = BigInt.zero;
        for (var i = 0; i < 8; i++) {
          final px = haveA ? plane[y0 - 1][x0 + i] : 0;
          above |= BigInt.from(px & 0xff) << (i * 8);
        }
        var left = BigInt.zero;
        for (var i = 0; i < 16; i++) {
          final px = haveL ? plane[y0 + i][x0 - 1] : 0;
          left |= BigInt.from(px & 0xff) << (i * 8);
        }
        final al = (haveA && haveL) ? plane[y0 - 1][x0 - 1] : 0;
        pMode.inject(uvMode);
        pHaveA.inject(haveA ? 1 : 0);
        pHaveL.inject(haveL ? 1 : 0);
        pAbove.inject(above);
        pLeft.inject(left);
        pAL.inject(al);
        iTxType.inject(txType);
        iCoeffs.inject(coeffs);
        iStart.inject(1);
        await iClk.nextPosedge;
        iStart.inject(0);
        var g = 0;
        while (itx.output('done').value.toInt() != 1) {
          await iClk.nextPosedge;
          if (++g > 4000) fail('chroma itx timeout');
        }
        final predBlk = pred.output('pred').value.toBigInt();
        final resBlk = itx.output('residual').value.toBigInt();
        final pmax = (1 << bd) - 1;
        for (var r = 0; r < 16; r++) {
          for (var c = 0; c < 8; c++) {
            final pv = ((predBlk >> ((r * 8 + c) * 8)) & BigInt.from(0xff))
                .toInt();
            var rv = ((resBlk >> ((r * 8 + c) * rsignW)) & rmask).toInt();
            if (rv >= (1 << (rsignW - 1))) rv -= (1 << rsignW);
            var v = pv + rv;
            if (v < 0) v = 0;
            if (v > pmax) v = pmax;
            plane[y0 + r][x0 + c] = v;
          }
        }
        await iClk.nextPosedge;
      }
    }
    await Simulator.endSimulation();
    await Simulator.reset();
    return plane;
  }

  final hwU = await reconChroma(0, w.uc, swU);
  final hwV = await reconChroma(1, w.vc, swV);

  var diffs = 0;
  var first = '';
  for (var r = 0; r < 64; r++) {
    for (var c = 0; c < 32; c++) {
      if (hwU[r][c] != swU[r][c]) {
        diffs++;
        first = first.isEmpty
            ? 'U($r,$c) HW=${hwU[r][c]} SW=${swU[r][c]}'
            : first;
      }
      if (hwV[r][c] != swV[r][c]) {
        diffs++;
        first = first.isEmpty
            ? 'V($r,$c) HW=${hwV[r][c]} SW=${swV[r][c]}'
            : first;
      }
    }
  }
  expect(diffs, equals(0), reason: 'bd=$bd $diffs/4096 chroma differ; $first');
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    '8-bit 4:2:2 keyframe: HW Y+U+V recon == SW.preFilter (bit-exact)',
    timeout: const Timeout(Duration(minutes: 90)),
    () async {
      await _runBd(8);
    },
  );
}

