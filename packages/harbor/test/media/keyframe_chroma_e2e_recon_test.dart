      final rAL = Logic(name: 'ral', width: 8);
      final rAc = Logic(name: 'rac', width: 64 * cflAcBits);
      final rIdx = Logic(name: 'rix', width: 8);
      final rSg = Logic(name: 'rsg', width: 3);
      final rPlane = Logic(name: 'rpl');
      final rTx = Logic(name: 'rtx', width: 4);
      final rCoeffs = Logic(name: 'rco', width: 64 * 16);
      final rSkip = Logic(name: 'rsk');
      final rEobZero = Logic(name: 'rez');
      recon.input('clk').srcConnection! <= rClk;
      recon.input('reset').srcConnection! <= rReset;
      recon.input('start').srcConnection! <= rStart;
      recon.input('uv_mode').srcConnection! <= rUvMode;
      recon.input('use_cfl').srcConnection! <= rUseCfl;
      recon.input('have_above').srcConnection! <= rHaveA;
      recon.input('have_left').srcConnection! <= rHaveL;
      recon.input('above').srcConnection! <= rAbove;
      recon.input('left').srcConnection! <= rLeft;
      recon.input('above_left').srcConnection! <= rAL;
      recon.input('cfl_luma_ac').srcConnection! <= rAc;
      recon.input('cfl_alpha_idx').srcConnection! <= rIdx;
      recon.input('cfl_signs').srcConnection! <= rSg;
      recon.input('plane').srcConnection! <= rPlane;
      recon.input('tx_type').srcConnection! <= rTx;
      recon.input('coeffs').srcConnection! <= rCoeffs;
      recon.input('skip').srcConnection! <= rSkip;
      recon.input('eob_zero').srcConnection! <= rEobZero;
      await recon.build();

      rReset.inject(1);
      rStart.inject(0);
      for (final l in [
        rUvMode,
        rUseCfl,
        rHaveA,
        rHaveL,
        rAbove,
        rLeft,
        rAL,
        rAc,
        rIdx,
        rSg,
        rPlane,
        rTx,
        rCoeffs,
        rSkip,
        rEobZero,
      ]) {
        l.inject(0);
      }
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await rClk.nextPosedge;
      rReset.inject(0);
      await rClk.nextPosedge;

      BigInt pack8(List<int> px) {
        var v = BigInt.zero;
        for (var i = 0; i < px.length; i++) {
          v |= BigInt.from(px[i] & 0xff) << (i * 8);
        }
        return v;
      }

      // Reconstruct one plane (0=U, 1=V) into a 32x32 buffer.
      Future<List<List<int>>> reconPlane(int planeNum, BigInt coeffArr) async {
        final plane = List.generate(32, (_) => List<int>.filled(32, 0));
        for (var br = 0; br < 4; br++) {
          for (var bc = 0; bc < 4; bc++) {
            final l = leafOf[br][bc];
            final r0 = br * 8, c0 = bc * 8;
            final haveA = br > 0, haveL = bc > 0;
            final above = [
              for (var i = 0; i < 8; i++) haveA ? plane[r0 - 1][c0 + i] : 0,
            ];
            final left = [
              for (var i = 0; i < 8; i++) haveL ? plane[r0 + i][c0 - 1] : 0,
            ];
            final al = (haveA && haveL) ? plane[r0 - 1][c0 - 1] : 0;
            final uvMode = ((uvm >> (l * 4)) & BigInt.from(0xf)).toInt();
            var coeffs = BigInt.zero;
            for (var i = 0; i < 64; i++) {
              final cf =
                  (coeffArr >> ((l * 64 + i) * 16)) & BigInt.from(0xffff);
              coeffs |= cf << (i * 16);
            }
            rUvMode.inject(uvMode); // DC (0) for this stream
            rUseCfl.inject(0);
            rHaveA.inject(haveA ? 1 : 0);
            rHaveL.inject(haveL ? 1 : 0);
            rAbove.inject(pack8(above));
            rLeft.inject(pack8(left));
            rAL.inject(al);
            rAc.inject(0);
            rIdx.inject(0);
            rSg.inject(0);
            rPlane.inject(planeNum);
            rTx.inject(0); // DCT_DCT for DC chroma
            rCoeffs.inject(coeffs);
            rSkip.inject(0);
            rEobZero.inject(0);
            rStart.inject(1);
            await rClk.nextPosedge;
            rStart.inject(0);
            var g = 0;
            while (recon.output('done').value.toInt() != 1) {
              await rClk.nextPosedge;
              if (++g > 200) fail('recon timeout');
            }
            final out = recon.output('recon').value.toBigInt();
            for (var r = 0; r < 8; r++) {
              for (var c = 0; c < 8; c++) {
                plane[r0 + r][c0 + c] =
                    ((out >> ((r * 8 + c) * 8)) & BigInt.from(0xff)).toInt();
              }
            }
            await rClk.nextPosedge;
          }
        }
        return plane;
      }

      final hwU = await reconPlane(0, uc);
      final hwV = await reconPlane(1, vc);
      await Simulator.endSimulation();

      var diffs = 0;
      var first = '';
      for (var r = 0; r < 32; r++) {
        for (var c = 0; c < 32; c++) {
          if (hwU[r][c] != swU[r][c]) {
            diffs++;
            first = first.isEmpty
                ? 'U($r,$c) HW=${hwU[r][c]} SW=${swU[r][c]}'
                : first;
          }
          if (hwV[r][c] != swV[r][c]) {
            diffs++;
            first = first.isEmpty
                ? 'V($r,$c) HW=${hwV[r][c]} SW=${swV[r][c]}'
                : first;
          }
        }
      }
      expect(
        diffs,
        equals(0),
        reason: '$diffs/2048 chroma pixels differ; $first',
      );
    },
  );
}
