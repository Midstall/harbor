  });

  const maxBytes = 320;
  const q = 0, dcv = 200, acv = 220;

  test(
    'HarborKeyframeModeWalk chroma 16x16 NONE leaf (TX_8X8 chroma) matches libaom',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      final t = HarborKeyframeModeWalk(
        rootBsize: 6,
        maxTxN: 256,
        coeffPrefix: true,
        txLeaf: true,
        chroma: true,
        qband: q,
        maxBytes: maxBytes,
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();

      final streams = _streams;
      expect(streams.length, greaterThan(0), reason: 'no qualifying streams');

      reset.inject(1);
      start.inject(0);
      dcQ.inject(dcv);
      acQ.inject(acv);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      for (var s = 0; s < streams.length; s++) {
        final b = streams[s];
        var bv = BigInt.zero;
        for (var i = 0; i < maxBytes; i++) {
          bv |= BigInt.from(b[i]) << (i * 8);
        }
        bytes.inject(bv);
        // pulse start.
        reset.inject(1);
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var iter = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++iter > 200000) fail('CASE $s: did not reach done');
        }
        expect(
          t.output('leaf_uv_mode').value.toInt(),
          _wantUvModes[s],
          reason: 'CASE $s leaf_uv_mode',
        );
        final uc = _unpack(t.output('leaf_u_coeffs').value.toBigInt(), 64, 16);
        expect(uc, _wantU[s], reason: 'CASE $s leaf_u_coeffs');
        final vc = _unpack(t.output('leaf_v_coeffs').value.toBigInt(), 64, 16);
        expect(vc, _wantV[s], reason: 'CASE $s leaf_v_coeffs');
        final lc = _unpack(t.output('leaf_coeffs').value.toBigInt(), 256, 16);
        expect(lc, _wantLuma[s], reason: 'CASE $s leaf_coeffs (luma)');
        // ignore: avoid_print
        print('CASE $s matched (iter=$iter)');
      }
      await Simulator.endSimulation();
    },
  );
}
