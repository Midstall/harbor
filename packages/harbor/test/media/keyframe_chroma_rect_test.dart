    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    dcQ.inject(0);
    acQ.inject(0);
    Simulator.setMaxSimTime(400000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    BigInt packBytes(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    List<int> unpackS(BigInt v, int n, int off) => [
      for (var i = 0; i < n; i++)
        (() {
          final raw = ((v >> ((off + i) * 16)) & BigInt.from(0xffff)).toInt();
          return raw >= 0x8000 ? raw - 0x10000 : raw;
        })(),
    ];

    const dcv = _dcv, acv = _acv;
    expect(streams.isNotEmpty, isTrue, reason: 'no $label streams found');
    for (var iter = 0; iter < streams.length; iter++) {
      final b = streams[iter];
      bytes.inject(packBytes(b));
      dcQ.inject(dcv);
      acQ.inject(acv);
      start.inject(1);
      await clk.nextPosedge;
