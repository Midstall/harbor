      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 20000) fail('timeout $label iter=$iter');
      }
      expect(
        t.output('leaf_count').value.toInt(),
        2,
        reason: '$label leaf_count iter=$iter',
      );
      final ym = t.output('leaf_ymodes').value.toBigInt();
      final uvm = t.output('leaf_uv_modes').value.toBigInt();
      final cidx = t.output('leaf_cfl_alpha_idxs').value.toBigInt();
      final csg = t.output('leaf_cfl_signs_arr').value.toBigInt();
      final uc = t.output('leaf_u_coeffs_arr').value.toBigInt();
      final vc = t.output('leaf_v_coeffs_arr').value.toBigInt();
      // both leaves' y_mode (detects any mode-info desync).
      for (var l = 0; l < 2; l++) {
        final hwY = ((ym >> (l * 4)) & BigInt.from(0xf)).toInt();
        expect(
          hwY,
          yModes[iter][l],
          reason: '$label leaf $l y_mode iter=$iter',
        );
      }
      // chroma is decoded ONLY at the chromaRef leaf, other leaf stays 0.
      for (var l = 0; l < 2; l++) {
        final hwUv = ((uvm >> (l * 4)) & BigInt.from(0xf)).toInt();
        final u = unpackS(uc, chromaN, l * chromaN);
        final v = unpackS(vc, chromaN, l * chromaN);
        if (l == chromaLeaf[iter]) {
          expect(
            hwUv,
            uvMode[iter],
            reason: '$label leaf $l uv_mode iter=$iter',
          );
          if (uvMode[iter] == 13) {
            final hwIdx = ((cidx >> (l * 8)) & BigInt.from(0xff)).toInt();
            final hwSg = ((csg >> (l * 3)) & BigInt.from(0x7)).toInt();
            expect(
              hwIdx,
              cflAlphaIdx[iter],
              reason: '$label leaf $l cfl_idx iter=$iter',
            );
            expect(
              hwSg,
              cflSigns[iter],
              reason: '$label leaf $l cfl_signs iter=$iter',
            );
          }
          expect(
            u,
            uCoeffs[iter],
            reason: '$label leaf $l U coeffs iter=$iter',
          );
          expect(
            v,
            vCoeffs[iter],
            reason: '$label leaf $l V coeffs iter=$iter',
          );
        } else {
          expect(
            hwUv,
            0,
            reason: '$label leaf $l uv_mode (non-ref) iter=$iter',
          );
          expect(
            u,
            List<int>.filled(chromaN, 0),
            reason: '$label leaf $l U (non-ref) iter=$iter',
          );
          expect(
            v,
            List<int>.filled(chromaN, 0),
            reason: '$label leaf $l V (non-ref) iter=$iter',
          );
        }
      }
      await clk.nextPosedge;
    }
    await Simulator.endSimulation();
  }

