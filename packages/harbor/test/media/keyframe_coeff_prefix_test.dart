void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const rootBsize = 3; // 8x8 SB

  for (final qband in [0, 3]) {
    test(
      'HarborKeyframeModeWalk coeffPrefix (8x8 SB) qband=$qband matches libaom',
      timeout: const Timeout(Duration(minutes: 20)),
      () async {
        final t = HarborKeyframeModeWalk(
          rootBsize: rootBsize,
          maxBytes: maxBytes,
          coeffPrefix: true,
          qband: qband,
        );
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final bytes = Logic(name: 'bytes', width: maxBytes * 8);
        final dcQ = Logic(name: 'dc_q', width: 16);
        final acQ = Logic(name: 'ac_q', width: 16);
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('bytes').srcConnection! <= bytes;
        t.input('dc_q').srcConnection! <= dcQ;
        t.input('ac_q').srcConnection! <= acQ;
        await t.build();
        reset.inject(1);
        start.inject(0);
        bytes.inject(0);
        dcQ.inject(0);
        acQ.inject(0);
        Simulator.setMaxSimTime(60000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        BigInt packBytes(List<int> b) {
          var v = BigInt.zero;
          for (var i = 0; i < b.length; i++) {
            v |= BigInt.from(b[i] & 0xff) << (i * 8);
          }
          return v;
        }

        final bList = qband == 0 ? _bytesQ0 : _bytesQ3;
        final dcvList = qband == 0 ? _dcvQ0 : _dcvQ3;
        final acvList = qband == 0 ? _acvQ0 : _acvQ3;
        final leafList = qband == 0 ? _leafQ0 : _leafQ3;
        final chkList = qband == 0 ? _chkQ0 : _chkQ3;
        final seen = <int>{};
        for (var iter = 0; iter < 12; iter++) {
          final b = bList[iter];
          final dcv = dcvList[iter], acv = acvList[iter];

          bytes.inject(packBytes(b));
          dcQ.inject(dcv);
          acQ.inject(acv);
          start.inject(1);
          await clk.nextPosedge;
          start.inject(0);
          var guard = 0;
          while (t.output('done').value.toInt() != 1) {
            await clk.nextPosedge;
            if (++guard > 3000) fail('timeout iter=$iter');
          }
          expect(
            t.output('leaf_count').value.toInt(),
            leafList[iter],
            reason: 'leaf_count iter=$iter',
          );
          expect(
            t.output('chk').value.toInt(),
            chkList[iter],
            reason: 'chk iter=$iter',
          );
          seen.add(leafList[iter]);
          await clk.nextPosedge;
        }
        expect(seen.length > 1, isTrue, reason: 'no leaf-count variety');
        await Simulator.endSimulation();
      },
    );
  }
}
