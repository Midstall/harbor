void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 512, f = 16;
  test(
    'HarborKeyframeDecode2Sb16Seq: 2 SBs bit-exact vs golden',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      final t = HarborKeyframeDecode2Sb16Seq(maxBytes: maxBytes);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(800000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      const dcv = _dcv, acv = _acv;
      for (var nCases = 0; nCases < _bytes.length; nCases++) {
        final b = _bytes[nCases];
        bytes.inject(packBytes(b));
        dcQ.inject(dcv);
        acQ.inject(acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 100000) fail('timeout case=$nCases');
        }
        final fv0 = t.output('frame0').value.toBigInt();
        final fv1 = t.output('frame1').value.toBigInt();
        final got0 = [
          for (var p = 0; p < f * f; p++)
            ((fv0 >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        final got1 = [
          for (var p = 0; p < f * f; p++)
            ((fv1 >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(got0, equals(_f0[nCases]), reason: 'frame0 case=$nCases');
        expect(got1, equals(_f1[nCases]), reason: 'frame1 case=$nCases');
        print('CASE ${nCases + 1} matched (iter=${_iters[nCases]})');
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(
        _bytes.length,
        2,
        reason: 'too few qualifying cases (${_bytes.length})',
      );
      await Simulator.endSimulation();
    },
  );
}
