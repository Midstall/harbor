void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const f = 8;

  BigInt packBytes(List<int> b) {
    var v = BigInt.zero;
    for (var i = 0; i < b.length; i++) {
      v |= BigInt.from(b[i] & 0xff) << (i * 8);
    }
    return v;
  }

  Future<void> runHorzVert(
    List<List<int>> streams,
    List<List<int>> goldens,
    String label,
  ) async {
    final t = HarborKeyframeDecodeHorzVert(maxBytes: maxBytes, qband: 0);
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    final dcQ = Logic(name: 'dc_q', width: 16);
    final acQ = Logic(name: 'ac_q', width: 16);
    final haveA = Logic(name: 'have_above');
    final haveL = Logic(name: 'have_left');
    final above = Logic(name: 'above', width: f * 8);
    final left = Logic(name: 'left', width: f * 8);
    final aboveLeft = Logic(name: 'above_left', width: 8);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    t.input('dc_q').srcConnection! <= dcQ;
    t.input('ac_q').srcConnection! <= acQ;
    t.input('have_above').srcConnection! <= haveA;
    t.input('have_left').srcConnection! <= haveL;
    t.input('above').srcConnection! <= above;
    t.input('left').srcConnection! <= left;
    t.input('above_left').srcConnection! <= aboveLeft;
    await t.build();

    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    dcQ.inject(0);
    acQ.inject(0);
    haveA.inject(0);
    haveL.inject(0);
    above.inject(0);
    left.inject(0);
    aboveLeft.inject(0);
    Simulator.setMaxSimTime(400000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    const dcv = _dcv, acv = _acv;

    var nDone = 0, nNonZero = 0;
    const want = 4;
    for (var iter = 0; iter < streams.length; iter++) {
      final b = streams[iter];
      final golden = goldens[iter];
      nNonZero++;

      bytes.inject(packBytes(b));
      dcQ.inject(dcv);
      acQ.inject(acv);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 8000) fail('$label timeout iter=$iter');
      }
      final fv = t.output('frame').value.toBigInt();
      final got = [
        for (var p = 0; p < f * f; p++)
          ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
      ];
      expect(got, equals(golden), reason: '$label iter=$iter bytes=$b');
      nDone++;
      await clk.nextPosedge;
      await clk.nextPosedge;
    }
    expect(nDone, want, reason: '$label too few cases ($nDone)');
    expect(nNonZero, greaterThan(0), reason: '$label all-zero coeffs only');
    // ignore: avoid_print
    print('$label cases=$nDone nonZeroLeafSets=$nNonZero');
    await Simulator.endSimulation();
  }

  test(
    'HarborKeyframeDecodeHorzVert HORZ 8x8 -> luma pixels bit-exact',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      await runHorzVert(_horzInputs, _horzFrames, 'HORZ');
    },
  );

  test(
    'HarborKeyframeDecodeHorzVert VERT 8x8 -> luma pixels bit-exact',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      await runHorzVert(_vertInputs, _vertFrames, 'VERT');
    },
  );
}
