void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const f = 8;

  test(
    '2-SB vertical pair: bytes -> stacked 16x8 luma pixels (bit-exact)',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      final t = HarborKeyframeDecodeMultiSbVert(maxBytes: maxBytes, qband: 0);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(400000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      List<int> unpackFrame(BigInt v) => [
        for (var p = 0; p < f * f; p++)
          ((v >> (p * 8)) & BigInt.from(0xff)).toInt(),
      ];

      // RED evidence (captured from the golden self-check): SB1 reconstructed
      // with its ABOVE row UNAVAILABLE mismatches the real golden.
      // ignore: avoid_print
      print(_redMsg);

      var found = 0;
      for (final (b, dcv, acv, want) in _cases) {
        bytes.inject(packBytes(b));
        dcQ.inject(dcv);
        acQ.inject(acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 20000) fail('decode timeout case=$found');
        }
        final got0 = unpackFrame(t.output('frame0').value.toBigInt());
        final got1 = unpackFrame(t.output('frame1').value.toBigInt());
        final gotStacked = [...got0, ...got1];
        expect(gotStacked, equals(want), reason: 'case=$found');
        found++;
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(
        found >= 1,
        isTrue,
        reason: 'no qualifying 2-SB SPLIT pair ($found)',
      );
      await Simulator.endSimulation();
    },
  );
}
