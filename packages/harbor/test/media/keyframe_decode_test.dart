void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const f = 8;

  test(
    'HarborKeyframeDecode: bytes -> 8x8 luma pixels, bit-exact',
    timeout: const Timeout(Duration(minutes: 20)),
    () async {
      final t = HarborKeyframeDecode(maxBytes: maxBytes);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(120000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      var done = 0;
      for (var idx = 0; idx < _inputs.length; idx++) {
        final b = _inputs[idx];
        final dcv = _dcvs[idx], acv = _acvs[idx];
        final wantFrame = _frames[idx];

        bytes.inject(packBytes(b));
        dcQ.inject(dcv);
        acQ.inject(acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 4000) fail('decode timeout idx=$idx');
        }
        final fv = t.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < f * f; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(got, equals(wantFrame), reason: 'idx=$idx');
        done++;
        // re-arm: hold start low so the FSM returns to idle.
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(done >= 8, isTrue, reason: 'too few SPLIT cases found ($done)');
      await Simulator.endSimulation();
    },
  );
}
