void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 1024, tileW = 32;
  test(
    'HarborKeyframeDecodeTile16Seq 2x2 bit-exact vs golden',
    timeout: const Timeout(Duration(minutes: 40)),
    () async {
      final t = HarborKeyframeDecodeTile16Seq(
        sbRows: 2,
        sbCols: 2,
        maxBytes: maxBytes,
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(1600000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      var nCases = 0;
      const wantCases = 2;
      for (var ci = 0; ci < wantCases; ci++) {
        final b = _bytes[ci];
        bytes.inject(packBytes(b));
        dcQ.inject(_dcv);
        acQ.inject(_acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 200000) fail('timeout case=$ci');
        }
        final fv = t.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < tileW * tileW; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        final want = _wants[ci];
        expect(got, equals(want), reason: 'case=$ci');
        nCases++;
        print('CASE $nCases matched');
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(nCases, wantCases, reason: 'too few qualifying cases ($nCases)');
      await Simulator.endSimulation();
    },
  );
}
