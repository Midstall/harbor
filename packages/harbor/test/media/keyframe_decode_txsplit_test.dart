void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const f = 8;

  test(
    'HarborKeyframeDecodeVar: bytes -> 8x8 luma pixels (NONE depth-1 tx-split)',
    timeout: const Timeout(Duration(minutes: 30)),
    () async {
      const qband = 0;
      final t = HarborKeyframeDecodeVar(maxBytes: maxBytes, qband: qband);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      var nGood = 0;
      const want = 6;
      for (final cs in _cases) {
        bytes.inject(packBytes(cs.bytes));
        dcQ.inject(_dcv);
        acQ.inject(_acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 8000) fail('decode timeout case=$nGood');
        }
        final fv = t.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < f * f; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(got, equals(cs.frame), reason: 'depth1 case=$nGood');
        nGood++;
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(nGood, want, reason: 'too few depth-1 cases ($nGood)');
      expect(
        _nNonUniform,
        greaterThan(0),
        reason: 'sweep hit no non-uniform-tx_type streams ($_nNonUniform)',
      );
      await Simulator.endSimulation();
    },
  );
}
