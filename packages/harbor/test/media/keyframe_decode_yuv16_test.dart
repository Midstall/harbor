List<int> _unpackPix(BigInt v, int n) => [
  for (var i = 0; i < n; i++) ((v >> (i * 8)) & BigInt.from(0xff)).toInt(),
];

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 320;
  const q = 0, dcv = 200, acv = 220;

  test(
    'HarborKeyframeDecodeYuv16: 16x16 NONE SB -> YUV pixels bit-exact',
    timeout: const Timeout(Duration(minutes: 40)),
    () async {
      final t = HarborKeyframeDecodeYuv16(maxBytes: maxBytes, qband: q);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();

      final streams = _cases;
      expect(streams.length, greaterThan(0), reason: 'no qualifying streams');

      reset.inject(1);
      start.inject(0);
      dcQ.inject(dcv);
      acQ.inject(acv);
      Simulator.setMaxSimTime(4000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      for (var s = 0; s < streams.length; s++) {
        final cs = streams[s];
        var bv = BigInt.zero;
        for (var i = 0; i < maxBytes; i++) {
          bv |= BigInt.from(cs.bytes[i]) << (i * 8);
        }
        bytes.inject(bv);
        reset.inject(1);
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var iter = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++iter > 400000) fail('CASE $s: did not reach done');
        }
        final luma = _unpackPix(t.output('luma').value.toBigInt(), 256);
