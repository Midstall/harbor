        expect(gotL, equals(c.luma), reason: 'luma iter=$iter');

        final uv = t.output('u').value.toBigInt();
        final gotU = [
          for (var p = 0; p < 16; p++)
            ((uv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
