        final gotV = [
          for (var p = 0; p < 16; p++)
            ((vv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(gotV, equals(c.v), reason: 'V iter=$iter');

        iter++;
        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(iter > 0, isTrue, reason: 'no iterations ran');
      await Simulator.endSimulation();
    },
  );

