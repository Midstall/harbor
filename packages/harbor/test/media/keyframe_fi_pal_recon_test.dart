// Drive HarborIntraReconWalkSeq from an embedded per-leaf golden and diff the
// reconstructed luma plane against the SW pre-filter planeY.
Future<void> _reconAndCheck({
  required int n,
  required int sbSize,
  required int maxLog2,
  required bool filterIntra,
  required bool palette,
  required String label,
  required List<int> sides,
  required List<int> rs,
  required List<int> cs,
  required List<int> yModes,
  required List<int> txTypes,
  required List<List<int>> coeffsArr,
  required List<int> fiUseArr,
  required List<int> fiModeArr,
  required List<int> palSizeArr,
  required List<List<int>> palColArr,
  required List<List<int>> palMapArr,
  required List<List<int>> swY,
}) async {
  final mw = sbSize ~/ 4;
  final miBits = mw.bitLength;
  final maxSide = 4 << maxLog2;
  final coeffN = maxSide * maxSide;
  final log2W = maxLog2 >= 4 ? 3 : 2;

  final recon = HarborIntraReconWalkSeq(
    sbSize: sbSize,
    maxLeaves: n,
    maxLog2: maxLog2,
    filterIntra: filterIntra,
    palette: palette,
    name: 'recon_$label',
  );

  var positions = BigInt.zero,
      log2v = BigInt.zero,
      ymv = BigInt.zero,
      txv = BigInt.zero,
      coeffs = BigInt.zero,
      fiUse = BigInt.zero,
      fiMode = BigInt.zero,
      hasPal = BigInt.zero,
      palCol = BigInt.zero,
      palMap = BigInt.zero;

  for (var l = 0; l < n; l++) {
    final side = sides[l];
    final recLog2 = side.bitLength - 1 - 2; // log2(side/4)
    positions |= BigInt.from(rs[l] | (cs[l] << miBits)) << (l * 2 * miBits);
    log2v |= BigInt.from(recLog2) << (l * log2W);
    ymv |= BigInt.from(yModes[l]) << (l * 4);
    txv |= BigInt.from(txTypes[l]) << (l * 4);
    // coeffs: one whole-block tx per leaf (row-major, signed 16b). Palette
    // leaves carry all-zero residual (captured as an empty list). Feed 0.
    final blk = coeffsArr[l];
    if (blk.length == side * side) {
      for (var i = 0; i < blk.length; i++) {
        coeffs |= BigInt.from(blk[i] & 0xffff) << ((l * coeffN + i) * 16);
      }
    }
    if (filterIntra) {
      fiUse |= BigInt.from(fiUseArr[l] & 1) << l;
      fiMode |= BigInt.from(fiModeArr[l] & 7) << (l * 3);
    }
    if (palette) {
      hasPal |= BigInt.from(palSizeArr[l] > 0 ? 1 : 0) << l;
      for (var k = 0; k < 8; k++) {
        palCol |= BigInt.from(palColArr[l][k] & 0xff) << ((l * 8 + k) * 8);
      }
      // color-index map, leaf-local raster (stride = palYW = side).
      final slot = l * maxSide * maxSide;
      final map = palMapArr[l];
      for (var i = 0; i < map.length; i++) {
        palMap |= BigInt.from(map[i] & 7) << ((slot + i) * 3);
      }
    }
  }

  final clk = SimpleClockGenerator(10).clk;
  final reset = Logic(name: 'reset');
  final start = Logic(name: 'start');
  final leafCount = Logic(
    name: 'leafcount',
    width: recon.input('leaf_count').width,
  );
  final positionsL = Logic(name: 'positions', width: n * 2 * miBits);
  final log2L = Logic(name: 'log2', width: n * log2W);
  final ymL = Logic(name: 'ymodes', width: n * 4);
  final txL = Logic(name: 'txtypes', width: n * 4);
  final coeffsL = Logic(name: 'coeffs', width: n * coeffN * 16);
  recon.input('clk').srcConnection! <= clk;
  recon.input('reset').srcConnection! <= reset;
  recon.input('start').srcConnection! <= start;
  recon.input('leaf_count').srcConnection! <= leafCount;
  recon.input('positions').srcConnection! <= positionsL;
  recon.input('log2sizes').srcConnection! <= log2L;
  recon.input('y_modes').srcConnection! <= ymL;
  recon.input('tx_types').srcConnection! <= txL;
  recon.input('coeffs').srcConnection! <= coeffsL;
  final fiUseL = filterIntra ? Logic(name: 'fiuse', width: n) : null;
  final fiModeL = filterIntra ? Logic(name: 'fimode', width: n * 3) : null;
  if (filterIntra) {
    recon.input('leaf_use_filter_intra').srcConnection! <= fiUseL!;
    recon.input('leaf_filter_intra_modes').srcConnection! <= fiModeL!;
  }
  final hasPalL = palette ? Logic(name: 'haspal', width: n) : null;
  final palColL = palette ? Logic(name: 'palcol', width: n * 64) : null;
  final palMapL = palette
      ? Logic(name: 'palmap', width: n * maxSide * maxSide * 3)
      : null;
  if (palette) {
    recon.input('leaf_has_pal_y').srcConnection! <= hasPalL!;
    recon.input('leaf_pal_y_colors').srcConnection! <= palColL!;
    recon.input('leaf_pal_y_map').srcConnection! <= palMapL!;
  }
  await recon.build();

  reset.inject(1);
  start.inject(0);
  leafCount.inject(n);
  positionsL.inject(positions);
  log2L.inject(log2v);
  ymL.inject(ymv);
  txL.inject(txv);
  coeffsL.inject(coeffs);
  if (filterIntra) {
    fiUseL!.inject(fiUse);
    fiModeL!.inject(fiMode);
  }
  if (palette) {
    hasPalL!.inject(hasPal);
    palColL!.inject(palCol);
    palMapL!.inject(palMap);
  }
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await clk.nextPosedge;
  reset.inject(0);
  await clk.nextPosedge;
  start.inject(1);
  await clk.nextPosedge;
  start.inject(0);
  var guard = 0;
  while (recon.output('done').value.toInt() != 1) {
    await clk.nextPosedge;
    if (++guard > 2000000) fail('$label: recon timeout');
  }
  final frame = recon.output('frame').value.toBigInt();
  int px(int r, int c) =>
      ((frame >> ((r * sbSize + c) * 8)) & BigInt.from(0xff)).toInt();

  // Compare against the PRE-loop-filter reconstruction: the recon walk is a
  // filter-less HW recon (no deblock/CDEF), so its golden is preFilterY.
  var diffs = 0;
  var firstDiff = '';
  for (var r = 0; r < sbSize; r++) {
    for (var c = 0; c < sbSize; c++) {
      if (px(r, c) != swY[r][c]) {
        diffs++;
        firstDiff = firstDiff.isEmpty
            ? 'first diff @($r,$c): HW=${px(r, c)} SW=${swY[r][c]}'
            : firstDiff;
      }
    }
  }
  await Simulator.endSimulation();
  expect(
    diffs,
    equals(0),
    reason: '$label: $diffs/${sbSize * sbSize} luma pixels differ; $firstDiff',
  );
}

