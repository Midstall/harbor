// libaom intra_mode_to_tx_type (chroma tx_type derives from uv_mode, no flips).
const _intraModeToTxType = [0, 1, 2, 0, 3, 1, 2, 2, 1, 3, 1, 2, 3];

List<int> _leafMi(int leaf) {
  final q = leaf >> 2, s = leaf & 3;
  return [(q >> 1) * 8 + (s >> 1) * 4, (q & 1) * 8 + (s & 1) * 4];
}

BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

// All per-leaf walk outputs captured from one mode-walk run.
class _Walk {
  final int leafCount;
  final BigInt ym, log2, lumaTx, lumaCoeffs, uvm, uc, vc;
  _Walk(
    this.leafCount,
    this.ym,
    this.log2,
    this.lumaTx,
    this.lumaCoeffs,
    this.uvm,
    this.uc,
    this.vc,
  );
}

Future<_Walk> _walk(
  List<int> tileBytes,
  int dcQv,
  int acQv,
  int qband,
  int txMode,
  int bd,
  int maxBytes,
) async {
  const maxLeaves = 16;
  final walk = HarborKeyframeModeWalk(
    rootBsize: 12,
    maxBytes: maxBytes,
    coeffPrefix: true,
    txLeaf: true,
    maxTxN: 256,
    chroma: true,
    chromaLeaf16: true,
    maxLeafOut: maxLeaves,
    qband: qband,
    txModeSelect: txMode == 2,
    bitDepth: bd,
    name: 'walk',
  );
  final clk = SimpleClockGenerator(10).clk;
  final reset = Logic(name: 'wreset');
  final start = Logic(name: 'wstart');
  final bytes = Logic(name: 'wbytes', width: maxBytes * 8);
  final dcQ = Logic(name: 'wdcq', width: 16);
  final acQ = Logic(name: 'wacq', width: 16);
  walk.input('clk').srcConnection! <= clk;
  walk.input('reset').srcConnection! <= reset;
  walk.input('start').srcConnection! <= start;
  walk.input('bytes').srcConnection! <= bytes;
  walk.input('dc_q').srcConnection! <= dcQ;
  walk.input('ac_q').srcConnection! <= acQ;
  await walk.build();
  reset.inject(1);
  start.inject(0);
  bytes.inject(_pack(tileBytes));
  dcQ.inject(dcQv);
  acQ.inject(acQv);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await clk.nextPosedge;
  reset.inject(0);
  await clk.nextPosedge;
  start.inject(1);
  await clk.nextPosedge;
  start.inject(0);
  var guard = 0;
  while (walk.output('done').value.toInt() != 1) {
    await clk.nextPosedge;
    if (++guard > 500000) fail('walk timeout');
  }
  final w = _Walk(
    walk.output('leaf_count').value.toInt(),
    walk.output('leaf_ymodes').value.toBigInt(),
    walk.output('leaf_log2size').value.toBigInt(),
    walk.output('leaf_luma_txtypes').value.toBigInt(),
    walk.output('leaf_coeffs').value.toBigInt(),
    walk.output('leaf_uv_modes').value.toBigInt(),
    walk.output('leaf_u_coeffs_arr').value.toBigInt(),
    walk.output('leaf_v_coeffs_arr').value.toBigInt(),
  );
  await Simulator.endSimulation();
  await Simulator.reset();
  return w;
}

Future<void> _runBd(
  int bd,
  List<int> tileBytes,
  int dcQv,
  int acQv,
  int qband,
  int txMode,
  List<List<int>> swY,
  List<List<int>> swU,
  List<List<int>> swV,
) async {
  const sbSize = 64, maxLeaves = 16, miBits = 5, coeffN = 256;
  final cw = bd + 8;
  // od_ec byte buffer must exceed the tile length (proven chroma config = 256).
  const maxBytes = 256;
  expect(tileBytes.length, lessThan(maxBytes));

  final w = await _walk(tileBytes, dcQv, acQv, qband, txMode, bd, maxBytes);
  expect(w.leafCount, equals(maxLeaves));

  // Leaf ownership of chroma block (br, bc). br = miRow/4, bc = miCol/4.
  final leafOf = List.generate(4, (_) => List<int>.filled(4, 0));
  for (var l = 0; l < maxLeaves; l++) {
    final p = _leafMi(l);
    leafOf[p[0] ~/ 4][p[1] ~/ 4] = l;
  }

  final recon = HarborIntraReconWalkSeq(
    sbSize: sbSize,
    maxLeaves: maxLeaves,
    maxLog2: 2,
    bitDepth: bd,
    name: 'recon',
  );
  final rClk = SimpleClockGenerator(10).clk;
  final rReset = Logic(name: 'rreset');
  final rStart = Logic(name: 'rstart');
  final rLeafCount = Logic(name: 'rlc', width: recon.input('leaf_count').width);
  final rPositions = Logic(name: 'rpos', width: maxLeaves * 2 * miBits);
  final rLog2 = Logic(name: 'rlog2', width: maxLeaves * 2);
  final rYModes = Logic(name: 'rym', width: maxLeaves * 4);
  final rTxTypes = Logic(name: 'rtx', width: maxLeaves * 4);
  final rCoeffs = Logic(name: 'rco', width: maxLeaves * coeffN * cw);
  recon.input('clk').srcConnection! <= rClk;
  recon.input('reset').srcConnection! <= rReset;
  recon.input('start').srcConnection! <= rStart;
  recon.input('leaf_count').srcConnection! <= rLeafCount;
  recon.input('positions').srcConnection! <= rPositions;
  recon.input('log2sizes').srcConnection! <= rLog2;
  recon.input('y_modes').srcConnection! <= rYModes;
  recon.input('tx_types').srcConnection! <= rTxTypes;
  recon.input('coeffs').srcConnection! <= rCoeffs;
  await recon.build();

  var positions = BigInt.zero, log2v = BigInt.zero, txv = BigInt.zero;
  for (var l = 0; l < maxLeaves; l++) {
    final p = _leafMi(l);
    positions |= BigInt.from(p[0] | (p[1] << miBits)) << (l * 2 * miBits);
    final walkLog2 = ((w.log2 >> (l * 3)) & BigInt.from(0x7)).toInt();
    log2v |= BigInt.from(walkLog2 - 2) << (l * 2);
    txv |= ((w.lumaTx >> (l * 4)) & BigInt.from(0xf)) << (l * 4);
  }

  rReset.inject(1);
  rStart.inject(0);
  rLeafCount.inject(maxLeaves);
  rPositions.inject(positions);
  rLog2.inject(log2v);
  rYModes.inject(w.ym);
  rTxTypes.inject(txv);
  rCoeffs.inject(w.lumaCoeffs);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await rClk.nextPosedge;
  rReset.inject(0);
  await rClk.nextPosedge;
  rStart.inject(1);
  await rClk.nextPosedge;
  rStart.inject(0);
  var guard = 0;
  while (recon.output('done').value.toInt() != 1) {
    await rClk.nextPosedge;
    if (++guard > 2000000) fail('luma recon timeout');
  }
  final frame = recon.output('frame').value.toBigInt();
  final ymask = BigInt.from((1 << bd) - 1);
  int ypx(int r, int c) => ((frame >> ((r * sbSize + c) * bd)) & ymask).toInt();

  var yDiffs = 0;
  var yFirst = '';
  for (var r = 0; r < 64; r++) {
    for (var c = 0; c < 64; c++) {
      if (ypx(r, c) != swY[r][c]) {
        yDiffs++;
        yFirst = yFirst.isEmpty
            ? 'Y($r,$c) HW=${ypx(r, c)} SW=${swY[r][c]}'
            : yFirst;
      }
    }
  }
  await Simulator.endSimulation();
  await Simulator.reset();
  expect(yDiffs, equals(0), reason: 'bd=$bd $yDiffs/4096 luma differ; $yFirst');

  final cflAcBits = bd + 4;
  final cr = HarborChromaReconBlock(
    bs: 8,
    bitDepth: bd,
    cflAcBits: cflAcBits,
    name: 'cr',
  );
  final cClk = SimpleClockGenerator(10).clk;
  final cReset = Logic(name: 'cr_r');
  final cStart = Logic(name: 'cr_s');
  final cUvMode = Logic(name: 'cuv', width: 4);
  final cUseCfl = Logic(name: 'ccfl');
  final cHaveA = Logic(name: 'cha');
  final cHaveL = Logic(name: 'chl');
  final cAbove = Logic(name: 'cab', width: 8 * bd);
  final cLeft = Logic(name: 'clf', width: 8 * bd);
  final cAL = Logic(name: 'cal', width: bd);
  final cAc = Logic(name: 'cac', width: 64 * cflAcBits);
  final cIdx = Logic(name: 'cix', width: 8);
  final cSg = Logic(name: 'csg', width: 3);
  final cPlane = Logic(name: 'cpl');
  final cTx = Logic(name: 'ctx', width: 4);
  final cCoeffs = Logic(name: 'cco', width: 64 * cw);
  final cSkip = Logic(name: 'csk');
  final cEobZero = Logic(name: 'cez');
  cr.input('clk').srcConnection! <= cClk;
  cr.input('reset').srcConnection! <= cReset;
  cr.input('start').srcConnection! <= cStart;
  cr.input('uv_mode').srcConnection! <= cUvMode;
  cr.input('use_cfl').srcConnection! <= cUseCfl;
  cr.input('have_above').srcConnection! <= cHaveA;
  cr.input('have_left').srcConnection! <= cHaveL;
  cr.input('above').srcConnection! <= cAbove;
  cr.input('left').srcConnection! <= cLeft;
  cr.input('above_left').srcConnection! <= cAL;
  cr.input('cfl_luma_ac').srcConnection! <= cAc;
  cr.input('cfl_alpha_idx').srcConnection! <= cIdx;
  cr.input('cfl_signs').srcConnection! <= cSg;
  cr.input('plane').srcConnection! <= cPlane;
  cr.input('tx_type').srcConnection! <= cTx;
  cr.input('coeffs').srcConnection! <= cCoeffs;
  cr.input('skip').srcConnection! <= cSkip;
  cr.input('eob_zero').srcConnection! <= cEobZero;
  await cr.build();

  cReset.inject(1);
  cStart.inject(0);
  for (final l in [
    cUvMode,
    cUseCfl,
    cHaveA,
    cHaveL,
    cAbove,
    cLeft,
    cAL,
    cAc,
    cIdx,
    cSg,
    cPlane,
    cTx,
    cCoeffs,
    cSkip,
    cEobZero,
  ]) {
    l.inject(0);
  }
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await cClk.nextPosedge;
  cReset.inject(0);
  await cClk.nextPosedge;

  BigInt packPx(List<int> px) {
    var v = BigInt.zero;
    final mask = (BigInt.one << bd) - BigInt.one;
    for (var i = 0; i < px.length; i++) {
      v |= (BigInt.from(px[i]) & mask) << (i * bd);
    }
    return v;
  }

  Future<List<List<int>>> reconPlane(int planeNum, BigInt coeffArr) async {
    final plane = List.generate(32, (_) => List<int>.filled(32, 0));
    for (var br = 0; br < 4; br++) {
      for (var bc = 0; bc < 4; bc++) {
        final l = leafOf[br][bc];
        final r0 = br * 8, c0 = bc * 8;
        final haveA = br > 0, haveL = bc > 0;
        final above = [
          for (var i = 0; i < 8; i++) haveA ? plane[r0 - 1][c0 + i] : 0,
        ];
        final left = [
          for (var i = 0; i < 8; i++) haveL ? plane[r0 + i][c0 - 1] : 0,
        ];
        final al = (haveA && haveL) ? plane[r0 - 1][c0 - 1] : 0;
        final uvMode = ((w.uvm >> (l * 4)) & BigInt.from(0xf)).toInt();
        // These streams contain no CfL (uv_mode 13) leaves.
        expect(uvMode, lessThan(13), reason: 'bd=$bd unexpected CfL leaf $l');
        final txType = _intraModeToTxType[uvMode];
        var coeffs = BigInt.zero;
        for (var i = 0; i < 64; i++) {
          final cf =
              (coeffArr >> ((l * 64 + i) * cw)) &
              ((BigInt.one << cw) - BigInt.one);
          coeffs |= cf << (i * cw);
        }
        cUvMode.inject(uvMode);
        cUseCfl.inject(0);
        cHaveA.inject(haveA ? 1 : 0);
        cHaveL.inject(haveL ? 1 : 0);
        cAbove.inject(packPx(above));
        cLeft.inject(packPx(left));
        cAL.inject(al);
        cAc.inject(0);
        cIdx.inject(0);
        cSg.inject(0);
        cPlane.inject(planeNum);
        cTx.inject(txType);
        cCoeffs.inject(coeffs);
        cSkip.inject(0);
        cEobZero.inject(0);
        cStart.inject(1);
        await cClk.nextPosedge;
        cStart.inject(0);
        var g = 0;
        while (cr.output('done').value.toInt() != 1) {
          await cClk.nextPosedge;
          if (++g > 200) fail('chroma recon timeout');
        }
        final out = cr.output('recon').value.toBigInt();
        final mask = (BigInt.one << bd) - BigInt.one;
        for (var r = 0; r < 8; r++) {
          for (var c = 0; c < 8; c++) {
            plane[r0 + r][c0 + c] = ((out >> ((r * 8 + c) * bd)) & mask)
                .toInt();
          }
        }
        await cClk.nextPosedge;
      }
    }
    return plane;
  }

  final hwU = await reconPlane(0, w.uc);
  final hwV = await reconPlane(1, w.vc);
  await Simulator.endSimulation();

  var diffs = 0;
  var first = '';
  for (var r = 0; r < 32; r++) {
    for (var c = 0; c < 32; c++) {
      if (hwU[r][c] != swU[r][c]) {
        diffs++;
        first = first.isEmpty
            ? 'U($r,$c) HW=${hwU[r][c]} SW=${swU[r][c]}'
            : first;
      }
      if (hwV[r][c] != swV[r][c]) {
        diffs++;
        first = first.isEmpty
            ? 'V($r,$c) HW=${hwV[r][c]} SW=${swV[r][c]}'
            : first;
      }
    }
  }
  expect(diffs, equals(0), reason: 'bd=$bd $diffs/2048 chroma differ; $first');
}

