Future<void> runPart(
  int wantPart,
  String label,
  int dcv,
  int acv,
  List<List<int>> streams,
  List<int> chks,
  List<int> parts,
  List<List<int>> yModes,
  List<List<int>> txTypes,
  List<List<int>> txDepths,
  List<List<int>> log2sizes,
  List<List<List<int>>> coeffs,
) async {
  const maxBytes = 48;
  final t = HarborKeyframeModeWalk(
    rootBsize: 3,
    maxBytes: maxBytes,
    coeffPrefix: true,
    txLeaf: true,
    qband: 0,
  );
  final clk = SimpleClockGenerator(10).clk;
  final reset = Logic(name: 'reset');
  final start = Logic(name: 'start');
  final bytes = Logic(name: 'bytes', width: maxBytes * 8);
  final dcQ = Logic(name: 'dc_q', width: 16);
  final acQ = Logic(name: 'ac_q', width: 16);
  t.input('clk').srcConnection! <= clk;
  t.input('reset').srcConnection! <= reset;
  t.input('start').srcConnection! <= start;
  t.input('bytes').srcConnection! <= bytes;
  t.input('dc_q').srcConnection! <= dcQ;
  t.input('ac_q').srcConnection! <= acQ;
  await t.build();
  reset.inject(1);
  start.inject(0);
  bytes.inject(0);
  dcQ.inject(0);
  acQ.inject(0);
  Simulator.setMaxSimTime(200000000);
  unawaited(Simulator.run());
  await clk.nextPosedge;
  reset.inject(0);
  await clk.nextPosedge;

  BigInt packBytes(List<int> b) {
    var v = BigInt.zero;
    for (var i = 0; i < b.length; i++) {
      v |= BigInt.from(b[i] & 0xff) << (i * 8);
    }
    return v;
  }

  List<int> unpack(BigInt v, int n, int w) => [
    for (var i = 0; i < n; i++)
      ((v >> (i * w)) & BigInt.from((1 << w) - 1)).toInt(),
  ];

  expect(streams.isNotEmpty, isTrue, reason: 'no $label depth-0 streams found');
  var nonZeroCoeff = 0, iter = 0;
  for (final b in streams) {
    expect(parts[iter], wantPart, reason: '$label partition iter=$iter');
    for (final d in txDepths[iter]) {
      expect(d, 0, reason: '$label depth-0 coverage iter=$iter');
    }
    for (final cc in coeffs[iter]) {
      if (cc.any((x) => x != 0)) nonZeroCoeff++;
    }

    bytes.inject(packBytes(b));
    dcQ.inject(dcv);
    acQ.inject(acv);
    start.inject(1);
    await clk.nextPosedge;
    start.inject(0);
    var guard = 0;
    while (t.output('done').value.toInt() != 1) {
      await clk.nextPosedge;
      if (++guard > 8000) fail('timeout $label iter=$iter');
    }
    expect(
      t.output('leaf_count').value.toInt(),
      2,
      reason: '$label leaf_count iter=$iter',
    );
    expect(
      t.output('chk').value.toInt(),
      chks[iter],
      reason: '$label chk iter=$iter (bytes=$b)',
    );
    final txt = unpack(t.output('leaf_txtypes').value.toBigInt(), 4, 4);
    final l2 = unpack(t.output('leaf_log2size').value.toBigInt(), 4, 3);
    final td = unpack(t.output('leaf_tx_depth').value.toBigInt(), 4, 2);
    final ym = unpack(t.output('leaf_ymodes').value.toBigInt(), 4, 4);
    final co = unpack(t.output('leaf_coeffs').value.toBigInt(), 4 * 64, 16);
    for (var li = 0; li < 2; li++) {
      expect(ym[li], yModes[iter][li], reason: '$label ymode l=$li iter=$iter');
      expect(
        txt[li],
        txTypes[iter][li],
        reason: '$label txtype l=$li iter=$iter',
      );
      expect(
        l2[li],
        log2sizes[iter][li],
        reason: '$label log2 l=$li iter=$iter',
      );
      expect(
        td[li],
        txDepths[iter][li],
        reason: '$label txdepth l=$li iter=$iter',
      );
      expect(
        co.sublist(li * 64, li * 64 + 64),
        coeffs[iter][li],
        reason: '$label coeffs l=$li iter=$iter',
      );
    }
    iter++;
    await clk.nextPosedge;
  }
  expect(
    nonZeroCoeff,
    greaterThan(0),
    reason: '$label no non-zero rect coeff block decoded',
  );
  await Simulator.endSimulation();
}

