void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const qband = 0;

  BigInt packBytes(List<int> b) {
    var v = BigInt.zero;
    for (var i = 0; i < b.length; i++) {
      v |= BigInt.from(b[i] & 0xff) << (i * 8);
    }
    return v;
  }

  List<int> unpack(BigInt v, int n, int w) => [
    for (var i = 0; i < n; i++)
      ((v >> (i * w)) & BigInt.from((1 << w) - 1)).toInt(),
  ];

  Future<void> runPart(
    int wantPart,
    String label,
    List<List<int>> streams,
    List<
      ({
        int leafCount,
        int chk,
        int partition,
        List<int> yModes,
        List<int> log2sizes,
        List<int> txDepths,
        List<List<int>> coeffs64,
        int uvMode,
        int cflAlphaIdx,
        int cflSigns,
        List<int> uCoeffs,
        List<int> vCoeffs,
      })
    >
    goldens,
  ) async {
    final t = HarborKeyframeModeWalk(
      rootBsize: 3,
      maxBytes: maxBytes,
      coeffPrefix: true,
      txLeaf: true,
      chroma: true,
      qband: qband,
    );
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    final dcQ = Logic(name: 'dc_q', width: 16);
    final acQ = Logic(name: 'ac_q', width: 16);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    t.input('dc_q').srcConnection! <= dcQ;
    t.input('ac_q').srcConnection! <= acQ;
    await t.build();
    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    dcQ.inject(0);
    acQ.inject(0);
    Simulator.setMaxSimTime(2000000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    const dcv = _dcv, acv = _acv;
    expect(
      streams.isNotEmpty,
      isTrue,
      reason: 'no $label depth-0 chromaRef-nonskip streams found',
    );

    var nonZeroChroma = 0, iter = 0;
    for (final b in streams) {
      final want = goldens[iter];
      expect(want.partition, wantPart, reason: '$label partition iter=$iter');
      if (want.uCoeffs.any((x) => x != 0) || want.vCoeffs.any((x) => x != 0)) {
        nonZeroChroma++;
      }

      bytes.inject(packBytes(b));
      dcQ.inject(dcv);
      acQ.inject(acv);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 12000) fail('timeout $label iter=$iter');
      }
      // luma side (== monochrome HORZ/VERT).
      expect(
        t.output('leaf_count').value.toInt(),
        want.leafCount,
        reason: '$label leaf_count iter=$iter',
      );
      expect(
        t.output('chk').value.toInt(),
        want.chk,
        reason: '$label chk iter=$iter (bytes=$b)',
      );
      final l2 = unpack(t.output('leaf_log2size').value.toBigInt(), 4, 3);
      final td = unpack(t.output('leaf_tx_depth').value.toBigInt(), 4, 2);
      final ym = unpack(t.output('leaf_ymodes').value.toBigInt(), 4, 4);
      final coeffs = unpack(
        t.output('leaf_coeffs').value.toBigInt(),
        4 * 64,
        16,
      );
      for (var lidx = 0; lidx < 2; lidx++) {
        expect(
          ym[lidx],
          want.yModes[lidx],
          reason: '$label ymode l=$lidx iter=$iter',
        );
        expect(
          l2[lidx],
          want.log2sizes[lidx],
          reason: '$label log2 l=$lidx iter=$iter',
        );
        expect(
          td[lidx],
          want.txDepths[lidx],
          reason: '$label txdepth l=$lidx iter=$iter',
        );
        expect(
          coeffs.sublist(lidx * 64, lidx * 64 + 64),
          want.coeffs64[lidx],
          reason: '$label coeffs l=$lidx iter=$iter',
        );
      }
      // chroma side (the new outputs).
      expect(
        t.output('leaf_uv_mode').value.toInt(),
        want.uvMode,
        reason: '$label uv_mode iter=$iter (bytes=$b)',
      );
      expect(
        t.output('leaf_cfl_alpha_idx').value.toInt(),
        want.cflAlphaIdx,
        reason: '$label cfl_alpha_idx iter=$iter',
      );
      expect(
        t.output('leaf_cfl_signs').value.toInt(),
        want.cflSigns,
        reason: '$label cfl_signs iter=$iter',
      );
      final uc = unpack(t.output('leaf_u_coeffs').value.toBigInt(), 16, 16);
      final vc = unpack(t.output('leaf_v_coeffs').value.toBigInt(), 16, 16);
      expect(uc, want.uCoeffs, reason: '$label u_coeffs iter=$iter (bytes=$b)');
      expect(vc, want.vCoeffs, reason: '$label v_coeffs iter=$iter (bytes=$b)');
      iter++;
      await clk.nextPosedge;
    }
    expect(
      nonZeroChroma,
      greaterThan(0),
      reason: '$label no non-zero chroma coeff block decoded',
    );
    // ignore: avoid_print
    print('$label streams=${streams.length} nonZeroChroma=$nonZeroChroma');
    await Simulator.endSimulation();
  }

  test(
    'HarborKeyframeModeWalk HORZ 8x8 YUV (two TX_8X4 + U/V) entropy bit-exact',
    timeout: const Timeout(Duration(minutes: 40)),
    () async {
      await runPart(1, 'HORZ', _horzStreams, _horzGoldens);
    },
  );

  test(
    'HarborKeyframeModeWalk VERT 8x8 YUV (two TX_4X8 + U/V) entropy bit-exact',
    timeout: const Timeout(Duration(minutes: 40)),
    () async {
      await runPart(2, 'VERT', _vertStreams, _vertGoldens);
    },
  );
}
