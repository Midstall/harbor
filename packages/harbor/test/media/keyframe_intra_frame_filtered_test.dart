    timeout: const Timeout(Duration(minutes: 90)),
    () async {
      expect([_w, _h], equals([64, 64]));
      expect(_txMode, equals(1), reason: 'TX_MODE_LARGEST (uniform TX_16X16)');
      // The encoder picked a non-zero LUMA deblock (chroma slots 0): the point
      // under test is a real, active deblock pass.
      expect(
        [_lfYv, _lfYh, _lfU, _lfV],
        equals([9, 9, 0, 0]),
        reason: 'adj(8)=9 luma, chroma gated off',
      );
      expect(_tileBytes.length, lessThanOrEqualTo(256));

      final sbCols = _w ~/ 64;
      final sbRows = _h ~/ 64;

      // SW final (post-_applyLoopFilters) reconstruction = the deblocked frame.
      final swY = _goldenY; // [64][64]
      final swU = _goldenU; // [32][32]
      final swV = _goldenV; // [32][32]

      const maxBytes = 256;
      final dut = HarborKeyframeIntraFrame(
        sbRows: sbRows,
        sbCols: sbCols,
        maxBytes: maxBytes,
        qband: _qband,
        txMode: _txMode,
        applyLoopFilters: true,
        name: 'frame',
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      final lfYv = Logic(name: 'lf_level_yv', width: 6);
      final lfYh = Logic(name: 'lf_level_yh', width: 6);
      final lfU = Logic(name: 'lf_level_u', width: 6);
      final lfV = Logic(name: 'lf_level_v', width: 6);
      final sharp = Logic(name: 'lf_sharpness', width: 3);
      dut.input('clk').srcConnection! <= clk;
      dut.input('reset').srcConnection! <= reset;
      dut.input('start').srcConnection! <= start;
      dut.input('bytes').srcConnection! <= bytes;
      dut.input('dc_q').srcConnection! <= dcQ;
      dut.input('ac_q').srcConnection! <= acQ;
      dut.input('lf_level_yv').srcConnection! <= lfYv;
      dut.input('lf_level_yh').srcConnection! <= lfYh;
      dut.input('lf_level_u').srcConnection! <= lfU;
      dut.input('lf_level_v').srcConnection! <= lfV;
      dut.input('lf_sharpness').srcConnection! <= sharp;
      await dut.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(_pack(_tileBytes));
      dcQ.inject(_dcQ);
      acQ.inject(_acQ);
      lfYv.inject(_lfYv);
      lfYh.inject(_lfYh);
      lfU.inject(_lfU);
      lfV.inject(_lfV);
      sharp.inject(_sharpness);
      Simulator.setMaxSimTime(20000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (dut.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 20000000) fail('frame decode timeout');
      }

      final frameW = _w, frameH = _h;
      final chW = frameW ~/ 2, chH = frameH ~/ 2;
      final yv = dut.output('frame_y').value.toBigInt();
      final uv = dut.output('frame_u').value.toBigInt();
      final vv = dut.output('frame_v').value.toBigInt();
      int yPx(int r, int c) =>
          ((yv >> ((r * frameW + c) * 8)) & BigInt.from(0xff)).toInt();
      int uPx(int r, int c) =>
          ((uv >> ((r * chW + c) * 8)) & BigInt.from(0xff)).toInt();
      int vPx(int r, int c) =>
          ((vv >> ((r * chW + c) * 8)) & BigInt.from(0xff)).toInt();

      var diffs = 0;
      var first = '';
      for (var r = 0; r < frameH; r++) {
        for (var c = 0; c < frameW; c++) {
          if (yPx(r, c) != swY[r][c]) {
            diffs++;
            first = first.isEmpty
                ? 'Y($r,$c) HW=${yPx(r, c)} SW=${swY[r][c]}'
                : first;
          }
        }
      }
      for (var r = 0; r < chH; r++) {
        for (var c = 0; c < chW; c++) {
          if (uPx(r, c) != swU[r][c]) {
            diffs++;
            first = first.isEmpty
                ? 'U($r,$c) HW=${uPx(r, c)} SW=${swU[r][c]}'
                : first;
          }
          if (vPx(r, c) != swV[r][c]) {
            diffs++;
            first = first.isEmpty
                ? 'V($r,$c) HW=${vPx(r, c)} SW=${swV[r][c]}'
                : first;
          }
        }
      }
      await Simulator.endSimulation();
      expect(
        diffs,
        equals(0),
        reason:
            '$diffs pixels differ (Y=${frameW * frameH} '
            'U=V=${chW * chH}); first $first',
      );
    },
  );
}
