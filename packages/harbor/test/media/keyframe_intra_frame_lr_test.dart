      dut.input('lf_level_yh').srcConnection! <= lfYh;
      dut.input('lf_level_u').srcConnection! <= lfU;
      dut.input('lf_level_v').srcConnection! <= lfV;
      dut.input('lf_sharpness').srcConnection! <= sharp;
