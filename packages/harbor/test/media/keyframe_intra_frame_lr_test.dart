      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (dut.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 20000000) fail('frame decode timeout');
      }

      final frameW = _w, frameH = _h;
      final chW = frameW ~/ 2, chH = frameH ~/ 2;
      final yv = dut.output('frame_y').value.toBigInt();
      final uv = dut.output('frame_u').value.toBigInt();
      final vv = dut.output('frame_v').value.toBigInt();
      int yPx(int r, int c) =>
          ((yv >> ((r * frameW + c) * 8)) & BigInt.from(0xff)).toInt();
      int uPx(int r, int c) =>
          ((uv >> ((r * chW + c) * 8)) & BigInt.from(0xff)).toInt();
      int vPx(int r, int c) =>
          ((vv >> ((r * chW + c) * 8)) & BigInt.from(0xff)).toInt();

      var diffs = 0;
      var firstS = '';
      for (var r = 0; r < frameH; r++) {
        for (var c = 0; c < frameW; c++) {
          if (yPx(r, c) != swY[r][c]) {
