            diffs++;
            firstS = firstS.isEmpty
                ? 'U($r,$c) HW=${uPx(r, c)} SW=${swU[r][c]}'
                : firstS;
          }
          if (vPx(r, c) != swV[r][c]) {
            diffs++;
            firstS = firstS.isEmpty
                ? 'V($r,$c) HW=${vPx(r, c)} SW=${swV[r][c]}'
                : firstS;
          }
        }
      }
      await Simulator.endSimulation();
      expect(diffs, equals(0), reason: '$diffs pixels differ; first $firstS');
    },
