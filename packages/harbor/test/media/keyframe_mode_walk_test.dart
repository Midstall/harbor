void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const rootBsize = 6; // 16x16

  test(
    'HarborKeyframeModeWalk 16x16 SB matches libaom partition+mode-info',
    () async {
      final t = HarborKeyframeModeWalk(
        rootBsize: rootBsize,
        maxBytes: maxBytes,
      );
      final sbMi = _miWide[rootBsize];
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      Simulator.setMaxSimTime(60000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      List<int> unpack(BigInt v, int n, int w) => [
        for (var i = 0; i < n; i++)
          ((v >> (i * w)) & BigInt.from((1 << w) - 1)).toInt(),
      ];

      final rng = Random(0x4ED7);
      final seen = <int>{};
      for (var iter = 0; iter < 200; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        final want = _goldens[iter];

        bytes.inject(packBytes(b));
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 3000) fail('timeout iter=$iter');
        }
        expect(
          t.output('leaf_count').value.toInt(),
          want.leafCount,
          reason: 'leaf_count iter=$iter',
        );
        expect(
          t.output('sym_count').value.toInt(),
          want.symCount,
          reason: 'sym_count iter=$iter',
        );
        expect(
          t.output('chk').value.toInt(),
          want.chk,
          reason: 'chk iter=$iter',
        );
        expect(
          unpack(t.output('above_ctx').value.toBigInt(), sbMi, 5),
          want.above,
          reason: 'above_ctx iter=$iter',
        );
        expect(
          unpack(t.output('left_ctx').value.toBigInt(), sbMi, 5),
          want.left,
          reason: 'left_ctx iter=$iter',
        );
        expect(
          unpack(t.output('above_skip').value.toBigInt(), sbMi, 1),
          want.aboveSkip,
          reason: 'above_skip iter=$iter',
        );
        expect(
          unpack(t.output('above_ymode').value.toBigInt(), sbMi, 4),
          want.aboveYm,
          reason: 'above_ymode iter=$iter',
        );
        seen.add(want.symCount);
        await clk.nextPosedge;
      }
      expect(seen.length > 1, isTrue, reason: 'no decode-depth variety');
      await Simulator.endSimulation();
    },
  );
}
