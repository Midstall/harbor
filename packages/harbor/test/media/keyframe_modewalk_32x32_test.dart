      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      const dcv = 200, acv = 220;
      var tested = 0, matched = 0;
      for (var iter = 0; iter < _streams.length; iter++) {
        final b = _streams[iter];
        final wantChk = _chks[iter];
        tested++;
        bytes.inject(packBytes(b));
        dcQ.inject(dcv);
        acQ.inject(acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 400000) fail('timeout iter=$iter');
        }
        if (t.output('leaf_count').value.toInt() != 1) continue;
        final hwChk = t.output('chk').value.toInt();
        if (hwChk == wantChk) matched++;
        await clk.nextPosedge;
      }
      expect(
        matched,
        tested,
        reason: 'all qualifying 32x32 leaves must be bit-exact',
      );
      expect(tested, greaterThan(0));
      await Simulator.endSimulation();
    },
  );
}
