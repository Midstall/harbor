BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'real 64x64 monochrome palette keyframe: HW palette-Y leaves == SW',
    timeout: const Timeout(Duration(minutes: 40)),
    () async {
      // SW golden: per-leaf palette-Y in DFS (= HW leaf-emit) order.
      const swHas = _monoHas;
      const swSize = _monoSize;
      const swColors = _monoColors;
      const swMapChk = _monoMapChk;
      const swYm = _monoYm;
      // sanity: this stream really exercises palette.
      expect(
        swHas.where((v) => v == 1).length,
        greaterThan(40),
        reason: 'stream must contain many palette-Y leaves',
      );

      const maxBytes = 288;
      const nLeaf = 64;
      final dut = HarborKeyframeModeWalk(
        rootBsize: 12,
        maxBytes: maxBytes,
        coeffPrefix: true,
        txLeaf: true,
        maxTxN: 64,
        chroma: false,
        maxLeafOut: nLeaf,
        qband: _monoQband,
        txModeSelect: true,
        enablePalette: true,
        name: 'pal_mono_walk',
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      dut.input('clk').srcConnection! <= clk;
      dut.input('reset').srcConnection! <= reset;
      dut.input('start').srcConnection! <= start;
      dut.input('bytes').srcConnection! <= bytes;
      dut.input('dc_q').srcConnection! <= dcQ;
      dut.input('ac_q').srcConnection! <= acQ;
      await dut.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(_pack(_monoTileBytes));
      dcQ.inject(_monoDcQ);
      acQ.inject(_monoAcQ);
      Simulator.setMaxSimTime(200000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (dut.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 20000000) fail('mode-walk timeout');
      }

      expect(
        dut.output('leaf_count').value.toInt(),
        equals(nLeaf),
        reason: 'leaf_count',
      );
      final hasP = dut.output('leaf_has_pal_y').value.toBigInt();
      final sizeP = dut.output('leaf_pal_y_size').value.toBigInt();
      final colP = dut.output('leaf_pal_y_colors').value.toBigInt();
      final chkP = dut.output('leaf_pal_y_mapchk').value.toBigInt();
      final ymP = dut.output('leaf_ymodes').value.toBigInt();
      final hwHas = [
        for (var i = 0; i < nLeaf; i++) ((hasP >> i) & BigInt.one).toInt(),
      ];
      final hwSize = [
        for (var i = 0; i < nLeaf; i++)
          ((sizeP >> (i * 4)) & BigInt.from(15)).toInt(),
      ];
      final hwColors = [
        for (var i = 0; i < nLeaf; i++)
          [
            for (var k = 0; k < 8; k++)
              ((colP >> ((i * 8 + k) * 8)) & BigInt.from(255)).toInt(),
          ],
      ];
      final hwMapChk = [
        for (var i = 0; i < nLeaf; i++)
          ((chkP >> (i * 32)) & BigInt.from((1 << 32) - 1)).toInt(),
      ];
      final hwYm = [
        for (var i = 0; i < nLeaf; i++)
          ((ymP >> (i * 4)) & BigInt.from(15)).toInt(),
      ];
      await Simulator.endSimulation();

      // Colours / map only meaningful where a palette is present.
      final swColMasked = [
        for (var i = 0; i < nLeaf; i++)
          swHas[i] == 1 ? swColors[i] : List.filled(8, 0),
      ];
      final hwColMasked = [
        for (var i = 0; i < nLeaf; i++)
          hwHas[i] == 1 ? hwColors[i] : List.filled(8, 0),
      ];
      final swChkMasked = [
        for (var i = 0; i < nLeaf; i++) swHas[i] == 1 ? swMapChk[i] : 0,
      ];
      final hwChkMasked = [
        for (var i = 0; i < nLeaf; i++) hwHas[i] == 1 ? hwMapChk[i] : 0,
      ];
      expect(hwYm, equals(swYm), reason: 'leaf y_modes (window alignment)');
      expect(hwHas, equals(swHas), reason: 'leaf has_palette_y');
      expect(hwSize, equals(swSize), reason: 'leaf palette_size_y');
      expect(
        hwColMasked,
        equals(swColMasked),
        reason: 'leaf palette Y colours',
      );
      expect(
        hwChkMasked,
        equals(swChkMasked),
        reason: 'leaf palette Y color-index-map checksum',
      );
      // ignore: avoid_print
      print(
        'mono64 palette-Y matched on $nLeaf leaves '
        '(${swHas.where((v) => v == 1).length} with palette)',
      );
    },
  );

  test(
    'real 4:2:0 8x8 palette leaf: HW palette Y+UV == SW (single SB)',
    timeout: const Timeout(Duration(minutes: 20)),
    () async {
      // The stream's superblock is 64x64 (--sb-size=64), so the walk must use a
      // 64x64 root. We decode the whole SB but only verify its FIRST 8x8 leaf's
      // palette: leaf 0 has no chroma neighbour, so its base TX_4X4 chroma decode
      // is exact. Later leaves desync (base chroma uses the no-neighbour ctx) but
      // are not checked, and leaf 0's palette is fully decoded before any coeffs.
      const maxBytes = 700;
      final dut = HarborKeyframeModeWalk(
        rootBsize: 12,
        maxBytes: maxBytes,
        coeffPrefix: true,
        txLeaf: true,
        chroma: true,
        maxLeafOut: 4,
        qband: _c420Qband,
        txModeSelect: true,
        enablePalette: true,
        name: 'pal_420_walk',
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      dut.input('clk').srcConnection! <= clk;
      dut.input('reset').srcConnection! <= reset;
      dut.input('start').srcConnection! <= start;
      dut.input('bytes').srcConnection! <= bytes;
      dut.input('dc_q').srcConnection! <= dcQ;
      dut.input('ac_q').srcConnection! <= acQ;
      await dut.build();

      reset.inject(1);
      start.inject(0);
      final tb = _c420TileBytes.length >= maxBytes
          ? _c420TileBytes.sublist(0, maxBytes)
          : _c420TileBytes;
      bytes.inject(_pack(tb));
      dcQ.inject(_c420DcQ);
      acQ.inject(_c420AcQ);
      Simulator.setMaxSimTime(200000000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (dut.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 5000000) fail('mode-walk timeout');
      }

      expect(
        dut.output('leaf_count').value.toInt(),
        greaterThanOrEqualTo(1),
        reason: 'at least the first leaf decoded',
      );
      int lo(String p, int w, int i) =>
          ((dut.output(p).value.toBigInt() >> (i * w)) &
                  BigInt.from((BigInt.one << w).toInt() - 1))
              .toInt();
      final hwHasY = lo('leaf_has_pal_y', 1, 0);
      final hwSizeY = lo('leaf_pal_y_size', 4, 0);
      final hwColY = [
        for (var k = 0; k < 8; k++) lo('leaf_pal_y_colors', 8, k),
      ];
      final hwChkY = lo('leaf_pal_y_mapchk', 32, 0);
      final hwHasUV = lo('leaf_has_pal_uv', 1, 0);
      final hwSizeUV = lo('leaf_pal_uv_size', 4, 0);
      final hwColU = [
        for (var k = 0; k < 8; k++) lo('leaf_pal_u_colors', 8, k),
      ];
      final hwColV = [
        for (var k = 0; k < 8; k++) lo('leaf_pal_v_colors', 8, k),
      ];
      final hwChkUV = lo('leaf_pal_uv_mapchk', 32, 0);
      await Simulator.endSimulation();

      List<int> pad8(List<int> c) => [
        for (var k = 0; k < 8; k++) k < c.length ? c[k] : 0,
      ];
      expect(hwHasY, equals(1), reason: 'has_palette_y');
      expect(hwSizeY, equals(_c420PalYSize), reason: 'palette_size_y');
      expect(hwColY, equals(pad8(_c420PalY)), reason: 'palette Y colours');
      expect(hwChkY, equals(_c420PalYMapChk), reason: 'palette Y map');
      expect(hwHasUV, equals(1), reason: 'has_palette_uv');
      expect(hwSizeUV, equals(_c420PalUVSize), reason: 'palette_size_uv');
      expect(hwColU, equals(pad8(_c420PalU)), reason: 'palette U colours');
      expect(hwColV, equals(pad8(_c420PalV)), reason: 'palette V colours');
      expect(hwChkUV, equals(_c420PalUVMapChk), reason: 'palette UV map');
      // ignore: avoid_print
      print(
        'c8_5 8x8 leaf palette matched: Y=$_c420PalY U=$_c420PalU '
        'V=$_c420PalV',
      );
    },
  );
}
