BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

int _s16(BigInt v, int j) {
  final u = ((v >> (j * 16)) & BigInt.from(0xffff)).toInt();
  return u >= 0x8000 ? u - 0x10000 : u;
}

// Drive the HW mode-walk on the captured tile and assert all 16 leaves match SW.
Future<void> _runQbandLeafDiff({
  required List<int> tileBytes,
  required int dcQ,
  required int acQ,
  required int qband,
  required int txMode,
  required bool mono,
  required int frameW,
  required int frameH,
  required int leafCountSw,
  required List<int> yModeG,
  required List<int> uvModeG,
  required List<int> cflIdxG,
  required List<int> cflSignsG,
  required List<List<int>> yCoeffG,
  required List<List<int>> uCoeffG,
  required List<List<int>> vCoeffG,
  required int expectQband,
}) async {
  const chromaN = 64; // TX_8X8 chroma
  const maxLeaves = 16;
  const maxBytes = 256;
  expect(
    tileBytes.length,
    lessThanOrEqualTo(maxBytes),
    reason: 'tile must fit the od_ec byte buffer',
  );
  expect(mono, isFalse);
  expect([frameW, frameH], equals([64, 64]));
  expect(qband, equals(expectQband), reason: 'qband');
  expect(txMode, equals(1), reason: 'TX_MODE_LARGEST');
  expect(
    leafCountSw,
    equals(maxLeaves),
    reason: 'uniform-16x16 64x64 SB must produce 16 leaves',
  );

  final walk = HarborKeyframeModeWalk(
    rootBsize: 12,
    maxBytes: maxBytes,
    coeffPrefix: true,
    txLeaf: true,
    maxTxN: 256,
    chroma: true,
    chromaLeaf16: true,
    maxLeafOut: maxLeaves,
    qband: qband,
    txModeSelect: txMode == 2,
    name: 'walk',
  );
  final wClk = SimpleClockGenerator(10).clk;
  final wReset = Logic(name: 'wreset');
  final wStart = Logic(name: 'wstart');
  final wBytes = Logic(name: 'wbytes', width: maxBytes * 8);
  final wDcQ = Logic(name: 'wdcq', width: 16);
  final wAcQ = Logic(name: 'wacq', width: 16);
  walk.input('clk').srcConnection! <= wClk;
  walk.input('reset').srcConnection! <= wReset;
  walk.input('start').srcConnection! <= wStart;
  walk.input('bytes').srcConnection! <= wBytes;
  walk.input('dc_q').srcConnection! <= wDcQ;
  walk.input('ac_q').srcConnection! <= wAcQ;
  await walk.build();

  wReset.inject(1);
  wStart.inject(0);
  wBytes.inject(_pack(tileBytes));
  wDcQ.inject(dcQ);
  wAcQ.inject(acQ);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await wClk.nextPosedge;
  wReset.inject(0);
  await wClk.nextPosedge;
  wStart.inject(1);
  await wClk.nextPosedge;
  wStart.inject(0);
  var guard = 0;
  while (walk.output('done').value.toInt() != 1) {
    await wClk.nextPosedge;
    if (++guard > 500000) fail('mode-walk decode timeout');
  }

  final leafCount = walk.output('leaf_count').value.toInt();
  final ym = walk.output('leaf_ymodes').value.toBigInt();
  final uvm = walk.output('leaf_uv_modes').value.toBigInt();
  final cidx = walk.output('leaf_cfl_alpha_idxs').value.toBigInt();
  final csg = walk.output('leaf_cfl_signs_arr').value.toBigInt();
  final uc = walk.output('leaf_u_coeffs_arr').value.toBigInt();
  final vc = walk.output('leaf_v_coeffs_arr').value.toBigInt();
  final yc = walk.output('leaf_coeffs').value.toBigInt();
  await Simulator.endSimulation();

  expect(leafCount, equals(maxLeaves), reason: 'leaf_count');

  for (var l = 0; l < maxLeaves; l++) {
    final hwY = ((ym >> (l * 4)) & BigInt.from(0xf)).toInt();
    final hwUv = ((uvm >> (l * 4)) & BigInt.from(0xf)).toInt();
    final hwIdx = ((cidx >> (l * 8)) & BigInt.from(0xff)).toInt();
    final hwSg = ((csg >> (l * 3)) & BigInt.from(0x7)).toInt();
    expect(hwY, equals(yModeG[l]), reason: 'leaf $l y_mode');
    expect(hwUv, equals(uvModeG[l]), reason: 'leaf $l uv_mode');
    if (uvModeG[l] == 13) {
      expect(hwIdx, equals(cflIdxG[l]), reason: 'leaf $l cfl_alpha_idx');
      expect(hwSg, equals(cflSignsG[l]), reason: 'leaf $l cfl_signs');
    }
    final swY = yCoeffG[l], swU = uCoeffG[l], swV = vCoeffG[l];
    for (var i = 0; i < 256; i++) {
      expect(
        _s16(yc, l * 256 + i),
        equals(swY[i]),
        reason: 'leaf $l Y coeff $i',
      );
    }
    for (var i = 0; i < chromaN; i++) {
      expect(
        _s16(uc, l * chromaN + i),
        equals(swU[i]),
        reason: 'leaf $l U coeff $i',
      );
      expect(
        _s16(vc, l * chromaN + i),
        equals(swV[i]),
