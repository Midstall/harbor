      for (var iter = 0; iter < 40; iter++) {
        final ym = [for (var b = 0; b < nBlk; b++) rng.nextInt(13)];
        final tt = [for (var b = 0; b < nBlk; b++) _intraSet[rng.nextInt(7)]];
        final co = [
          for (var b = 0; b < nBlk; b++)
            [for (var i = 0; i < 16; i++) rng.nextInt(4096) - 2048],
        ];

        // golden: captured raster recon into an f x f frame.
        final frame = goldens[iter];

        BigInt packN(List<int> vals, int w) {
          var v = BigInt.zero;
          for (var i = 0; i < vals.length; i++) {
            v |= BigInt.from(vals[i] & ((1 << w) - 1)) << (i * w);
          }
          return v;
        }

        // pack coeffs: block b at [b*256 +: 256], 16 signed 16-bit.
        var cv = BigInt.zero;
        for (var b = 0; b < nBlk; b++) {
          for (var i = 0; i < 16; i++) {
            cv |= BigInt.from(co[b][i] & 0xffff) << (b * 256 + i * 16);
          }
        }
        yModes.inject(packN(ym, 4));
        txTypes.inject(packN(tt, 4));
        coeffs.inject(cv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 400) fail('timeout iter=$iter');
        }
        final fv = t.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < f * f; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(got, equals(frame), reason: 'iter=$iter ym=$ym tt=$tt');
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    },
  );
}
