BigInt _pack(List<int> b) {
  var v = BigInt.zero;
  for (var i = 0; i < b.length; i++) {
    v |= BigInt.from(b[i] & 0xff) << (i * 8);
  }
  return v;
}

Future<void> _runOne(
  String label, {
  required List<int> tile,
  required int dcQ,
  required int acQ,
  required int qband,
  required int txMode,
  required int leafCountSw,
  required List<int> bw,
  required List<int> bh,
  required List<int> rectKind,
  required List<int> miWideLog2,
  required List<int> yModeG,
  required List<int> yTxTypeG,
  required List<int> rPos,
  required List<int> cPos,
  required List<int> yCoeffLen,
  required List<bool> skip,
  required List<List<int>> yCoeffG,
  required List<List<int>> preY,
}) async {
  expect(txMode, equals(1), reason: '$label: expect TX_MODE_LARGEST stream');
  // sanity: at least one rect leaf, and every leaf a single depth-0 tx block.
  var rectN = 0;
  for (var l = 0; l < leafCountSw; l++) {
    if (bw[l] != bh[l]) rectN++;
  }
  expect(rectN, greaterThan(0), reason: '$label: expect rect leaves');
  for (var l = 0; l < leafCountSw; l++) {
    if (!skip[l]) {
      expect(
        yCoeffLen[l],
        equals(1),
        reason: '$label: leaf (${rPos[l]},${cPos[l]}) must be depth-0',
      );
    }
  }

  const maxBytes = 96;
  const sbSize = 64;
  const maxLeaves = 24;
  const coeffN = 256;
  const miBits = 5; // bitLength(64/4)

  final walk = HarborKeyframeModeWalk(
    rootBsize: 12,
    maxBytes: maxBytes,
    coeffPrefix: true,
    txLeaf: true,
    maxTxN: 256,
    chroma: false,
    maxLeafOut: maxLeaves,
    qband: qband,
    txModeSelect: txMode == 2,
    name: 'walk_$label',
  );
  final wClk = SimpleClockGenerator(10).clk;
  final wReset = Logic(name: 'wreset');
  final wStart = Logic(name: 'wstart');
  final wBytes = Logic(name: 'wbytes', width: maxBytes * 8);
  final wDcQ = Logic(name: 'wdcq', width: 16);
  final wAcQ = Logic(name: 'wacq', width: 16);
  walk.input('clk').srcConnection! <= wClk;
  walk.input('reset').srcConnection! <= wReset;
  walk.input('start').srcConnection! <= wStart;
  walk.input('bytes').srcConnection! <= wBytes;
  walk.input('dc_q').srcConnection! <= wDcQ;
  walk.input('ac_q').srcConnection! <= wAcQ;
  await walk.build();

  wReset.inject(1);
  wStart.inject(0);
  wBytes.inject(_pack(tile));
  wDcQ.inject(dcQ);
  wAcQ.inject(acQ);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await wClk.nextPosedge;
  wReset.inject(0);
  await wClk.nextPosedge;
  wStart.inject(1);
  await wClk.nextPosedge;
  wStart.inject(0);
  var guard = 0;
  while (walk.output('done').value.toInt() != 1) {
    await wClk.nextPosedge;
    if (++guard > 500000) fail('$label: mode-walk decode timeout');
  }

  final leafCount = walk.output('leaf_count').value.toInt();
  final ym = walk.output('leaf_ymodes').value.toBigInt();
  final l2 = walk.output('leaf_log2size').value.toBigInt();
  final rk = walk.output('leaf_rect_kinds').value.toBigInt();
  final tt = walk.output('leaf_txtypes').value.toBigInt();
  final cf = walk.output('leaf_coeffs').value.toBigInt();

  expect(
    leafCount,
    equals(leafCountSw),
    reason: '$label: leaf count desync (HW $leafCount vs SW $leafCountSw)',
  );

  int leafRectKind(int l) => ((rk >> (l * 3)) & BigInt.from(0x7)).toInt();
  int leafWidthLog2(int l) => ((l2 >> (l * 3)) & BigInt.from(0x7)).toInt();
  int leafYMode(int l) => ((ym >> (l * 4)) & BigInt.from(0xf)).toInt();
  int leafTxType(int l) => ((tt >> (l * 4)) & BigInt.from(0xf)).toInt();
  int leafCoeff(int l, int idx) {
    final raw = ((cf >> ((l * coeffN + idx) * 16)) & BigInt.from(0xffff))
        .toInt();
    return raw >= 0x8000 ? raw - 0x10000 : raw;
  }

  // Per-leaf entropy check vs SW blocks (both DFS order).
  for (var l = 0; l < leafCountSw; l++) {
    final bwl = bw[l], bhl = bh[l];
    expect(
      leafRectKind(l),
      equals(rectKind[l]),
      reason: '$label: leaf $l rect kind (SW ${bwl}x$bhl)',
    );
    expect(
      leafWidthLog2(l),
      equals(miWideLog2[l] + 2),
      reason: '$label: leaf $l width log2',
    );
    expect(leafYMode(l), equals(yModeG[l]), reason: '$label: leaf $l y_mode');
    if (!skip[l]) {
      expect(
        leafTxType(l),
        equals(yTxTypeG[l]),
        reason: '$label: leaf $l tx_type (SW ${bwl}x$bhl)',
      );
      // dequant coeffs: SW yCoeff[0] is row-major bh*bw. The HW leaf coeff slot
      // is the same row-major raster in [0, bw*bh).
      final sw = yCoeffG[l];
      for (var i = 0; i < bwl * bhl; i++) {
        expect(
          leafCoeff(l, i),
          equals(sw[i]),
          reason: '$label: leaf $l coeff $i (${bwl}x$bhl)',
        );
      }
    }
  }

  await Simulator.endSimulation();
  await Simulator.reset();

  final recon = HarborIntraReconWalkSeq(
    sbSize: sbSize,
    maxLeaves: maxLeaves,
    maxLog2: 2,
    rect: true,
    name: 'recon_$label',
  );
  final rClk = SimpleClockGenerator(10).clk;
  final rReset = Logic(name: 'rreset');
  final rStart = Logic(name: 'rstart');
  final rLeafCount = Logic(
    name: 'rleafcount',
    width: recon.input('leaf_count').width,
  );
  final rPositions = Logic(name: 'rpositions', width: maxLeaves * 2 * miBits);
  final rLog2 = Logic(name: 'rlog2', width: maxLeaves * 2);
  final rRectKinds = Logic(name: 'rrectkinds', width: maxLeaves * 3);
  final rYModes = Logic(name: 'rymodes', width: maxLeaves * 4);
  final rTxTypes = Logic(name: 'rtxtypes', width: maxLeaves * 4);
  final rCoeffs = Logic(name: 'rcoeffs', width: maxLeaves * coeffN * 16);
  recon.input('clk').srcConnection! <= rClk;
  recon.input('reset').srcConnection! <= rReset;
  recon.input('start').srcConnection! <= rStart;
  recon.input('leaf_count').srcConnection! <= rLeafCount;
  recon.input('positions').srcConnection! <= rPositions;
  recon.input('log2sizes').srcConnection! <= rLog2;
  recon.input('rect_kinds').srcConnection! <= rRectKinds;
  recon.input('y_modes').srcConnection! <= rYModes;
  recon.input('tx_types').srcConnection! <= rTxTypes;
  recon.input('coeffs').srcConnection! <= rCoeffs;
  await recon.build();

  // Positions come from the SW block list (same DFS order the mode-walk emits),
  // everything else from the HW mode-walk outputs (so recon consumes the HW
  // entropy result, validating the whole HW path end to end).
  var positions = BigInt.zero, log2v = BigInt.zero;
  for (var l = 0; l < leafCountSw; l++) {
    positions |= BigInt.from(rPos[l] | (cPos[l] << miBits)) << (l * 2 * miBits);
    // recon square log2 (width/4) - only used for square leaves.
    log2v |= BigInt.from(miWideLog2[l]) << (l * 2); // 16 -> 2, 8 -> 1
  }

  rReset.inject(1);
  rStart.inject(0);
  rLeafCount.inject(leafCountSw);
  rPositions.inject(positions);
  rLog2.inject(log2v);
  rRectKinds.inject(rk);
  rYModes.inject(ym);
  rTxTypes.inject(tt);
  rCoeffs.inject(cf);
  Simulator.setMaxSimTime(2000000000);
  unawaited(Simulator.run());
  await rClk.nextPosedge;
  rReset.inject(0);
  await rClk.nextPosedge;
  rStart.inject(1);
  await rClk.nextPosedge;
  rStart.inject(0);
  guard = 0;
  while (recon.output('done').value.toInt() != 1) {
    await rClk.nextPosedge;
    if (++guard > 4000000) fail('$label: recon timeout');
  }
  final frame = recon.output('frame').value.toBigInt();
  int px(int r, int c) =>
      ((frame >> ((r * sbSize + c) * 8)) & BigInt.from(0xff)).toInt();

  final swY = preY;
  var diffs = 0;
  var firstDiff = '';
  for (var r = 0; r < 64; r++) {
    for (var c = 0; c < 64; c++) {
      if (px(r, c) != swY[r][c]) {
        diffs++;
        firstDiff = firstDiff.isEmpty
            ? 'first diff @($r,$c): HW=${px(r, c)} SW=${swY[r][c]}'
            : firstDiff;
      }
    }
  }
  expect(
    diffs,
    equals(0),
    reason: '$label: $diffs/4096 luma pixels differ; $firstDiff',
  );
  await Simulator.endSimulation();
}

