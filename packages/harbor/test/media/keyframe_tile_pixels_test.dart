void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;
  const f = 8;

  test(
    '8x8 keyframe SB (split to 2x2) decodes to pixels',
    timeout: const Timeout(Duration(minutes: 20)),
    () async {
      final w = HarborKeyframeModeWalk(
        rootBsize: 3,
        maxBytes: maxBytes,
        coeffPrefix: true,
      );
      final g = HarborKeyframeReconGrid(gridN: 2);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final wStart = Logic(name: 'w_start');
      final gStart = Logic(name: 'g_start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);

      w.input('clk').srcConnection! <= clk;
      w.input('reset').srcConnection! <= reset;
      w.input('start').srcConnection! <= wStart;
      w.input('bytes').srcConnection! <= bytes;
      w.input('dc_q').srcConnection! <= dcQ;
      w.input('ac_q').srcConnection! <= acQ;

      g.input('clk').srcConnection! <= clk;
      g.input('reset').srcConnection! <= reset;
      g.input('start').srcConnection! <= gStart;
      g.input('y_modes').srcConnection! <= w.output('leaf_ymodes');
      g.input('tx_types').srcConnection! <= w.output('leaf_txtypes');
      g.input('coeffs').srcConnection! <= w.output('leaf_coeffs');
      await g.build();

      reset.inject(1);
      wStart.inject(0);
      gStart.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(80000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      var done = 0;
      for (var iter = 0; iter < _streams.length; iter++) {
        final s = _streams[iter];
        final wantFrame = s.frame;

        bytes.inject(packBytes(s.b));
        dcQ.inject(s.dcv);
        acQ.inject(s.acv);
        wStart.inject(1);
        await clk.nextPosedge;
        wStart.inject(0);
        var guard = 0;
        while (w.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 3000) fail('walk timeout iter=$iter');
        }
        // run recon on the decoded leaves.
        gStart.inject(1);
        await clk.nextPosedge;
        gStart.inject(0);
        guard = 0;
        while (g.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 400) fail('recon timeout iter=$iter');
        }
        final fv = g.output('frame').value.toBigInt();
        final got = [
          for (var p = 0; p < f * f; p++)
            ((fv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];
        expect(got, equals(wantFrame), reason: 'iter=$iter');
        done++;
        await clk.nextPosedge;
        // re-arm: walk back to idle.
        await clk.nextPosedge;
      }
      expect(done >= 4, isTrue, reason: 'too few SPLIT cases found ($done)');
      await Simulator.endSimulation();
    },
  );
}
