        width: maxLeaves * 2 * miBits,
      );
      final rLog2 = Logic(name: 'rlog2', width: recon.input('log2sizes').width);
      final rYModes = Logic(name: 'rymodes', width: maxLeaves * 4);
      final rTxTypes = Logic(name: 'rtxtypes', width: maxLeaves * 4);
      final rCoeffs = Logic(
        name: 'rcoeffs',
        width: maxLeaves * reconCoeffN * 16,
      );
      recon.input('clk').srcConnection! <= rClk;
      recon.input('reset').srcConnection! <= rReset;
      recon.input('start').srcConnection! <= rStart;
      recon.input('leaf_count').srcConnection! <= rLeafCount;
      recon.input('positions').srcConnection! <= rPositions;
      recon.input('log2sizes').srcConnection! <= rLog2;
      recon.input('y_modes').srcConnection! <= rYModes;
      recon.input('tx_types').srcConnection! <= rTxTypes;
      recon.input('coeffs').srcConnection! <= rCoeffs;
      await recon.build();

      // Map the walk's 32x32 coeff region (row-major 32-wide) into the top-left
      // 32x32 of the recon's 64x64 coeff slot, the DCT-64 core reads only that
      // region (the high-frequency quadrants are zero).
      var reconCoeffs = BigInt.zero;
      final mask16 = BigInt.from(0xFFFF);
      for (var r = 0; r < 32; r++) {
        for (var c = 0; c < 32; c++) {
          final v = (cf >> ((r * 32 + c) * 16)) & mask16;
          reconCoeffs |= v << ((r * 64 + c) * 16);
        }
      }
      final walkLog2 = ((l2) & BigInt.from(0x7)).toInt();
      final positions = BigInt.zero; // leaf 0 at mi (0,0)
      final log2v = BigInt.from(walkLog2 - 2); // 64x64: 6 -> 4
      final txv = (tt) & BigInt.from(0xf);

      rReset.inject(1);
      rStart.inject(0);
      rLeafCount.inject(1);
      rPositions.inject(positions);
      rLog2.inject(log2v);
      rYModes.inject(ym & BigInt.from(0xf));
      rTxTypes.inject(txv);
      rCoeffs.inject(reconCoeffs);
      Simulator.setMaxSimTime(2000000000);
      unawaited(Simulator.run());
      await rClk.nextPosedge;
      rReset.inject(0);
      await rClk.nextPosedge;
      rStart.inject(1);
      await rClk.nextPosedge;
      rStart.inject(0);
      guard = 0;
      while (recon.output('done').value.toInt() != 1) {
        await rClk.nextPosedge;
        if (++guard > 4000000) fail('recon timeout');
      }
      final frame = recon.output('frame').value.toBigInt();
      int px(int r, int c) =>
          ((frame >> ((r * sbSize + c) * 8)) & BigInt.from(0xff)).toInt();

      var firstDiff = '';
      var diffs = 0;
      for (var r = 0; r < 64; r++) {
        for (var c = 0; c < 64; c++) {
          if (px(r, c) != swY[r][c]) {
            diffs++;
            firstDiff = firstDiff.isEmpty
                ? 'first diff @($r,$c): HW=${px(r, c)} SW=${swY[r][c]}'
                : firstDiff;
          }
        }
      }
      expect(
        diffs,
        equals(0),
        reason: '$diffs/4096 luma pixels differ; $firstDiff',
      );
      await Simulator.endSimulation();
    },
  );
}
