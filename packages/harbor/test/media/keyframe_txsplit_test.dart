void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 48;

  test(
    'HarborKeyframeModeWalk txLeaf 8x8 NONE depth-1 (four TX_4X4) tx-split',
    timeout: const Timeout(Duration(minutes: 20)),
    () async {
      const qband = 0;
      final t = HarborKeyframeModeWalk(
        rootBsize: 3,
        maxBytes: maxBytes,
        coeffPrefix: true,
        txLeaf: true,
        qband: qband,
      );
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('dc_q').srcConnection! <= dcQ;
      t.input('ac_q').srcConnection! <= acQ;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
      acQ.inject(0);
      Simulator.setMaxSimTime(120000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      List<int> unpack(BigInt v, int n, int w) => [
        for (var i = 0; i < n; i++)
          ((v >> (i * w)) & BigInt.from((1 << w) - 1)).toInt(),
      ];

      final dcv = _dcv, acv = _acv;
      final streams = _streams;
      expect(
        streams.isNotEmpty,
        isTrue,
        reason: 'no depth-1 NONE streams found',
      );
      for (var iter = 0; iter < streams.length; iter++) {
        final b = streams[iter];
        expect(
          _goldTxDepth[iter],
          1,
          reason: 'filtered to depth-1, iter=$iter',
        );

        bytes.inject(packBytes(b));
        dcQ.inject(dcv);
        acQ.inject(acv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 6000) fail('timeout iter=$iter');
        }
        expect(
          t.output('leaf_count').value.toInt(),
          _goldLeafCount[iter],
          reason: 'leaf_count iter=$iter',
        );
        expect(
          t.output('chk').value.toInt(),
          _goldChk[iter],
          reason: 'chk iter=$iter',
        );
        final l2 = unpack(t.output('leaf_log2size').value.toBigInt(), 4, 3);
        expect(l2[0], _goldLog2size[iter], reason: 'leaf_log2size iter=$iter');
        // leaf_tx_depth: leaf 0 holds the 8x8 leaf at depth 1.
        final td = unpack(t.output('leaf_tx_depth').value.toBigInt(), 4, 2);
        expect(td[0], _goldTxDepth[iter], reason: 'leaf_tx_depth iter=$iter');
        // 64 coeffs of leaf 0, raster order across the four TX_4X4 sub-blocks.
        final coeffs = unpack(
          t.output('leaf_coeffs').value.toBigInt(),
          4 * 64,
          16,
        );
        expect(
          coeffs.sublist(0, 64),
          _goldCoeffs64[iter],
          reason: 'leaf_coeffs iter=$iter',
        );
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    },
  );
}
