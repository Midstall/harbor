      zero8.inject(0);
      zero1.inject(0);
      Simulator.setMaxSimTime(80000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packB(List<int> b, int w) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & ((1 << w) - 1)) << (i * w);
        }
        return v;
      }

      final rng = Random(0xF1A7);
      var sawSkip = false, sawCoeffs = false, sawDir = false;
      for (var iter = 0; iter < 80; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        rng.nextInt(256); // qi: advances rng, dc/ac quant captured in goldens
        final yMode = _yMode[iter];
        final txType = _txType[iter];
        final wantRecon = _recon[iter];
        if (_allZero[iter]) sawSkip = true;
        if (!_allZero[iter]) sawCoeffs = true;
        if (yMode >= 3 && yMode <= 8) sawDir = true;

        bytes.inject(packB(b, 8));
        dcQ.inject(_dcQ[iter]);
        acQ.inject(_acQ[iter]);
        clStart.inject(1);
        await clk.nextPosedge;
        clStart.inject(0);
        var guard = 0;
        while (cl.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 4000) fail('coeff timeout iter=$iter');
        }
        txStart.inject(1);
        await clk.nextPosedge;
        txStart.inject(0);
        guard = 0;
        while (tx.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 64) fail('tx timeout iter=$iter');
        }

        final rvv = ra.output('recon').value.toBigInt();
        final got = [
          for (var p = 0; p < n; p++)
            ((rvv >> (p * 8)) & BigInt.from(0xff)).toInt(),
        ];

        expect(
          got,
          equals(wantRecon),
          reason: 'iter=$iter yMode=$yMode txType=$txType',
        );

        await clk.nextPosedge;
        await clk.nextPosedge;
      }
      expect(sawSkip, isTrue, reason: 'no skipped block seen');
      expect(sawCoeffs, isTrue, reason: 'no coded block seen');
      expect(sawDir, isTrue, reason: 'no directional mode seen');
      await Simulator.endSimulation();
    },
  );
}
