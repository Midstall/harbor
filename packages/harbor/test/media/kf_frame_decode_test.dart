  const bs = 4, n = 16, maxBytes = 32;

  test(
    'top-left 4x4 keyframe block decodes to pixels (no neighbours)',
    () async {
      final cl = HarborCoeffLevels(
        maxBytes: maxBytes,
        readTxType: true,
        kfIntra: true,
      );
      final tx = HarborInvTxfm(txSize: 0, txType: 0, runtimeTxType: true);
      final pred = HarborIntraPredAvail(bs: bs);
      final ra = HarborReconAdd(n: n);

      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final clStart = Logic(name: 'cl_start');
      final txStart = Logic(name: 'tx_start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final dcQ = Logic(name: 'dc_q', width: 16);
      final acQ = Logic(name: 'ac_q', width: 16);
      final zero2 = Logic(name: 'z2', width: 2);
      final zero4 = Logic(name: 'z4', width: 4);
      final zeroBs = Logic(name: 'zbs', width: bs * 8);
      final zero8 = Logic(name: 'z8', width: 8);
      final zero1 = Logic(name: 'z1');

      cl.input('clk').srcConnection! <= clk;
      cl.input('reset').srcConnection! <= reset;
      cl.input('start').srcConnection! <= clStart;
      cl.input('bytes').srcConnection! <= bytes;
      cl.input('dc_q').srcConnection! <= dcQ;
      cl.input('ac_q').srcConnection! <= acQ;
      cl.input('skip_ctx').srcConnection! <= zero2; // top-left: skip_ctx 0
      cl.input('above_ymode').srcConnection! <= zero4; // DC neighbours
      cl.input('left_ymode').srcConnection! <= zero4;

      tx.input('clk').srcConnection! <= clk;
      tx.input('reset').srcConnection! <= reset;
      tx.input('start').srcConnection! <= txStart;
      tx.input('coeffs').srcConnection! <= cl.output('coeffs');
      tx.input('tx_type').srcConnection! <= cl.output('tx_type');

      pred.input('mode').srcConnection! <= cl.output('y_mode');
      pred.input('have_above').srcConnection! <= zero1; // no neighbours
      pred.input('have_left').srcConnection! <= zero1;
      pred.input('above').srcConnection! <= zeroBs;
      pred.input('left').srcConnection! <= zeroBs;
      pred.input('above_left').srcConnection! <= zero8;

      ra.input('pred').srcConnection! <= pred.output('pred');
      ra.input('residual').srcConnection! <= tx.output('residual');

      await ra.build();

      reset.inject(1);
      clStart.inject(0);
      txStart.inject(0);
      bytes.inject(0);
      dcQ.inject(0);
