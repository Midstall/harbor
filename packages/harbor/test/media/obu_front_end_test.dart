// End-to-end front-end: a hand-assembled OBU stream (temporal delimiter +
// sequence header OBU + frame header OBU) is walked by HarborObuFrontEnd, which
// runs the full seq + frame parsers on the OBU payloads (seq outputs feeding
// frame inputs). The seq/frame OBU payload bytes (hand-written bits) and their
// golden parsed fields were captured from the SW reference
// parseSequenceHeader -> parseFrameHeader for the same 80 seeded streams.
// _golds row layout (per iteration): [seqProfile, frameType, showFrame,
// frameWidth, frameHeight, baseQIdx, tileCols, tileRows, codedLossless,
// cdefBits, txMode, allowScreenContentTools].

List<int> _leb128(int v) {
  final out = <int>[];
  do {
    var b = v & 0x7f;
    v >>= 7;
    if (v != 0) b |= 0x80;
    out.add(b);
  } while (v != 0);
  return out;
}

