void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const bufBytes = 128;

  test(
    'HarborObuFrontEnd: walk TD+seq+frame OBU stream, parse bit-exact',
    () async {
      final fe = HarborObuFrontEnd(bufBytes: bufBytes);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: bufBytes * 8);
      final streamLen = Logic(name: 'stream_len', width: 12);

      fe.input('clk').srcConnection! <= clk;
      fe.input('reset').srcConnection! <= reset;
      fe.input('start').srcConnection! <= start;
      fe.input('bytes').srcConnection! <= bytes;
      fe.input('stream_len').srcConnection! <= streamLen;
      await fe.build();

      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      streamLen.inject(0);
      Simulator.setMaxSimTime(200000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;

      BigInt pack(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xFF) << (i * 8);
        }
        return v;
      }

      int fo(String name) => fe.output(name).value.toInt();

      var sawCdef = false, sawScreen = false;
      for (var iter = 0; iter < 80; iter++) {
        final seqPay = _seqPays[iter];
        final framePay = _framePays[iter];
        final g = _golds[iter];

        if (g[9] > 0) sawCdef = true;
        if (g[11] != 0) sawScreen = true;

        // assemble: TD (type 2) + seq header OBU (type 1) + frame header OBU (3).
        final stream = <int>[];
        stream.addAll([0x12, 0x00]); // TD: header (type2,has_size), size 0
        stream.add(0x0A); // seq header OBU header (type1, has_size)
        stream.addAll(_leb128(seqPay.length));
        stream.addAll(seqPay);
        stream.add(0x1A); // frame header OBU header (type3, has_size)
        stream.addAll(_leb128(framePay.length));
        stream.addAll(framePay);
        // tile_group OBU (type 4): single tile (whole payload is the tile data).
        final tileData = _tileDatas[iter];
        stream.add(0x22); // tile_group OBU header (type4, has_size)
        stream.addAll(_leb128(tileData.length));
        final tgBase = stream.length; // absolute payload offset
        stream.addAll(tileData);
        expect(
          stream.length <= bufBytes,
          isTrue,
          reason: 'stream too big iter=$iter',
        );

        reset.inject(1);
        bytes.inject(pack(stream));
        streamLen.inject(stream.length);
        await clk.nextPosedge;
        reset.inject(0);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (fe.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 5000) fail('walk timeout iter=$iter');
        }
        expect(
          fo('frame_unsupported'),
          equals(0),
          reason: 'iter=$iter frame unsupported',
        );
        expect(fo('obu_count'), equals(4), reason: 'iter=$iter obu_count');
        expect(fo('seq_profile'), equals(g[0]), reason: 'iter=$iter profile');
        // single-tile keyframe: one slice covering the whole tile-group payload.
        expect(fo('tile_count'), equals(1), reason: 'iter=$iter tile_count');
        int slot(String name, int i) =>
            ((fe.output(name).value.toBigInt() >> (i * 12)) &
                    BigInt.from(0xfff))
                .toInt();
        expect(
          slot('tile_offsets', 0),
          equals(0),
          reason: 'iter=$iter tile_off',
        );
        expect(
          slot('tile_sizes', 0),
          equals(tileData.length),
          reason: 'iter=$iter tile_size',
        );
        expect(
          fo('tile_group_base'),
          equals(tgBase),
          reason: 'iter=$iter tg_base',
        );

        void chk(String name, int want, String label) =>
            expect(fo(name), equals(want), reason: 'iter=$iter $label');

        chk('frame_type', g[1], 'frame_type');
        chk('show_frame', g[2], 'show_frame');
        chk('frame_width', g[3], 'frame_width');
        chk('frame_height', g[4], 'frame_height');
        chk('base_q_idx', g[5], 'base_q');
        chk('tile_cols', g[6], 'tile_cols');
        chk('tile_rows', g[7], 'tile_rows');
        chk('coded_lossless', g[8], 'coded_lossless');
        chk('cdef_bits', g[9], 'cdef_bits');
        chk('tx_mode', g[10], 'tx_mode');
      }
      expect(sawCdef, isTrue, reason: 'no cdef frame seen');
      expect(sawScreen, isTrue, reason: 'no screen-content frame seen');
      await Simulator.endSimulation();
    },
  );
}
