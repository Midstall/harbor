void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test(
    'HW palette recon (index->color) bit-exact vs SW, real blocks',
    () async {
      expect(
        _planes.length,
        greaterThan(4),
        reason: 'stream must contain palette-Y blocks',
      );

      const bd = 8;
      var checked = 0;
      for (final p in _planes) {
        final r = p[0] as int;
        final c = p[1] as int;
        final colors = p[2] as List<int>;
        final map = p[3] as List<int>;
        final n = map.length;
        final dut = HarborPaletteRecon(n: n, bitDepth: bd, name: 'pr_$checked');
        final colorsL = Logic(name: 'colors', width: 8 * bd);
        final indices = Logic(name: 'indices', width: n * 3);
        dut.input('colors').srcConnection! <= colorsL;
        dut.input('indices').srcConnection! <= indices;
        await dut.build();

        var cAcc = BigInt.zero;
        for (var k = 0; k < 8; k++) {
          final v = k < colors.length ? colors[k] : 0;
          cAcc |= BigInt.from(v & 0xff) << (k * bd);
        }
        var iAcc = BigInt.zero;
        for (var i = 0; i < n; i++) {
          iAcc |= BigInt.from(map[i] & 7) << (i * 3);
        }
        colorsL.put(cAcc);
        indices.put(iAcc);

        final packed = dut.output('pixels').value.toBigInt();
        for (var i = 0; i < n; i++) {
          final hw = ((packed >> (i * bd)) & BigInt.from((1 << bd) - 1))
              .toInt();
          final sw = colors[map[i]];
          expect(
            hw,
            equals(sw),
            reason: 'block ($r,$c) plane pixel $i idx=${map[i]}',
          );
        }
        await Simulator.reset();
        checked++;
      }
      expect(checked, greaterThanOrEqualTo(4));
      // ignore: avoid_print
      print('palette recon verified on $checked (block,plane) maps');
    },
  );
}
