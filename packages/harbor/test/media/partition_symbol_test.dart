void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 16;
  const names = ['128x128', '64x64', '32x32', '16x16', '8x8'];

  for (var partIdx = 0; partIdx < 5; partIdx++) {
    test('HarborPartitionSymbol ${names[partIdx]} matches libaom', () async {
      final t = HarborPartitionSymbol(partIdx: partIdx, maxBytes: maxBytes);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final ctx = Logic(name: 'ctx', width: 2);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('ctx').srcConnection! <= ctx;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      ctx.inject(0);
      Simulator.setMaxSimTime(20000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;

      BigInt packBytes(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      final rng = Random(0x9A1 + partIdx);
      for (var iter = 0; iter < 120; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        final cv = rng.nextInt(4);
        final want = _wants[partIdx][iter];

        bytes.inject(packBytes(b));
        ctx.inject(cv);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var guard = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++guard > 100) fail('timeout iter=$iter');
        }
        expect(
          t.output('partition').value.toInt(),
          want,
          reason: 'iter=$iter ctx=$cv',
        );
        await clk.nextPosedge;
      }
      await Simulator.endSimulation();
    });
  }
}
