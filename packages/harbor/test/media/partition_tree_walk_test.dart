({int leafCount, int symCount, int chk, List<int> above, List<int> left}) _g64(
  int iter,
) => (
  leafCount: _leaf64[iter],
  symCount: _sym64[iter],
  chk: _chk64[iter],
  above: _above64[iter],
  left: _left64[iter],
);

void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 32;
  const rootBsize = 6; // BLOCK_16X16

  test('HarborPartitionTreeWalk 16x16 SB matches libaom recursion', () async {
    final t = HarborPartitionTreeWalk(rootBsize: rootBsize, maxBytes: maxBytes);
    final sbMi = _miWide[rootBsize];
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    await t.build();
    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    Simulator.setMaxSimTime(40000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;

    BigInt packBytes(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    List<int> unpackCtx(BigInt v, int n) => [
      for (var i = 0; i < n; i++) ((v >> (i * 5)) & BigInt.from(0x1f)).toInt(),
    ];

    final rng = Random(0x9117);
    final seen = <int>{};
    for (var iter = 0; iter < 200; iter++) {
      final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
      final want = _g16(iter);

      bytes.inject(packBytes(b));
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var guard = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++guard > 2000) fail('timeout iter=$iter');
      }
      expect(
        t.output('leaf_count').value.toInt(),
        want.leafCount,
        reason: 'leaf_count iter=$iter',
      );
      expect(
        t.output('sym_count').value.toInt(),
        want.symCount,
        reason: 'sym_count iter=$iter',
      );
      expect(t.output('chk').value.toInt(), want.chk, reason: 'chk iter=$iter');
      expect(
        unpackCtx(t.output('above_ctx').value.toBigInt(), sbMi),
        want.above,
        reason: 'above_ctx iter=$iter',
      );
      expect(
        unpackCtx(t.output('left_ctx').value.toBigInt(), sbMi),
        want.left,
        reason: 'left_ctx iter=$iter',
      );
      seen.add(want.symCount);
      await clk.nextPosedge;
    }
    // Sanity: the random streams should exercise both shallow (1 symbol) and
    // deeper (split -> more symbols) partition trees.
    expect(seen.length > 1, isTrue, reason: 'no partition-depth variety');
    await Simulator.endSimulation();
  });

