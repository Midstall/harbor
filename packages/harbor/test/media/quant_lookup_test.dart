void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  for (final bd in [8, 10, 12]) {
    test('HarborQuantLookup($bd): dc/ac vs SW over qindex + deltas', () async {
      await _runBd(bd);
    });
  }
}

Future<void> _runBd(int bd) async {
  final golden = bd == 8 ? _golden8 : (bd == 10 ? _golden10 : _golden12);
  final p = HarborQuantLookup(bitDepth: bd);
  final clk = SimpleClockGenerator(10).clk;
  final qindex = Logic(name: 'qindex', width: 8);
  final deltaDc = Logic(name: 'delta_dc', width: 8);
  final deltaAc = Logic(name: 'delta_ac', width: 8);
  p.input('qindex').srcConnection! <= qindex;
  p.input('delta_dc').srcConnection! <= deltaDc;
  p.input('delta_ac').srcConnection! <= deltaAc;
  await p.build();
  qindex.inject(0);
  deltaDc.inject(0);
  deltaAc.inject(0);
  Simulator.setMaxSimTime(20000000);
  unawaited(Simulator.run());
  await clk.nextPosedge;

  int u8(int v) => v & 0xff; // signed -> 8-bit two's complement

  var ci = 0;
  Future<void> chk(int qi, int dDc, int dAc) async {
    qindex.inject(qi);
    deltaDc.inject(u8(dDc));
    deltaAc.inject(u8(dAc));
    await clk.nextPosedge;
    final want = golden[ci++];
    expect(
      p.output('dc_q').value.toInt(),
      equals(want[0]),
      reason: 'bd=$bd dc qi=$qi dDc=$dDc',
    );
    expect(
      p.output('ac_q').value.toInt(),
      equals(want[1]),
      reason: 'bd=$bd ac qi=$qi dAc=$dAc',
    );
  }

  // boundaries + clamping
  for (final qi in [0, 1, 80, 127, 200, 254, 255]) {
    await chk(qi, 0, 0);
  }
  await chk(0, -64, -64); // clamps low
  await chk(255, 63, 63); // clamps high
  await chk(250, 63, 10);
  await chk(5, -64, 20);

  final rng = Random(0x9112);
  for (var i = 0; i < 400; i++) {
    await chk(rng.nextInt(256), rng.nextInt(129) - 64, rng.nextInt(129) - 64);
  }
  await Simulator.endSimulation();
}
