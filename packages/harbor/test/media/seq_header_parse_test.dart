  const maxBytes = 64;

  test('HarborSeqHeaderParse: bit-exact vs SW parseSequenceHeader', () async {
    final p = HarborSeqHeaderParse(maxBytes: maxBytes);
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);

    p.input('clk').srcConnection! <= clk;
    p.input('reset').srcConnection! <= reset;
    p.input('start').srcConnection! <= start;
    p.input('bytes').srcConnection! <= bytes;
    await p.build();

    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    Simulator.setMaxSimTime(200000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;

    BigInt pack(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xFF) << (i * 8);
      }
      return v;
    }

    int o(String name) => p.output(name).value.toInt();
    int bo(String name) => p.output(name).value.toInt();

    final rng = Random(0xA1B2);
    var sawReduced = false, sawFull = false, sawTiming = false, sawMono = false;
    var sawCl709 = false, sawSubX0 = false;
    for (var iter = 0; iter < 200; iter++) {
      final buf = _buildHeader(rng, maxBytes);
