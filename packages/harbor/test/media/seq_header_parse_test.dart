// MSB-first bit writer mirroring sw.BitReader.f / uvlc.
class _W {
  final bits = <int>[];
  void f(int value, int n) {
    for (var k = n - 1; k >= 0; k--) {
      bits.add((value >> k) & 1);
    }
  }

  void uvlc(int val) {
    var l = 0;
    while ((1 << (l + 1)) - 1 <= val) {
      l++;
    }
    final field = val - ((1 << l) - 1);
    for (var k = 0; k < l; k++) {
      f(0, 1);
    }
    f(1, 1);
    if (l > 0) f(field, l);
  }

  List<int> toBytes(int len) {
    final out = List.filled(len, 0);
    for (var i = 0; i < bits.length && i < len * 8; i++) {
      if (bits[i] != 0) out[i >> 3] |= 1 << (7 - (i & 7));
    }
    return out;
  }
}

// Build a random well-formed sequence header. Mirrors parseSequenceHeader so
// the SW parser reads back exactly what we wrote. Avoids the
// decoder_model_present_for_this_op path (the one SW rejects).
List<int> _buildHeader(Random rng, int maxBytes) {
  final w = _W();
  bool b() => rng.nextBool();
  final profile = rng.nextInt(3); // 0..2
  w.f(profile, 3);
  w.f(b() ? 1 : 0, 1); // still_picture
  final reduced = b();
  w.f(reduced ? 1 : 0, 1);

  var decoderModelPresent = false;
  var initDispPresent = false;
  if (reduced) {
    w.f(rng.nextInt(32), 5); // seq_level_idx[0]
  } else {
    final timingPresent = rng.nextInt(4) == 0; // keep rare
    w.f(timingPresent ? 1 : 0, 1);
    if (timingPresent) {
      w.f(rng.nextInt(1 << 16), 32); // num_units_in_display_tick
      w.f(rng.nextInt(1 << 16), 32); // time_scale
      final equalPi = b();
      w.f(equalPi ? 1 : 0, 1);
      if (equalPi) w.uvlc(rng.nextInt(64)); // num_ticks_per_picture_minus_1
      decoderModelPresent = b();
      w.f(decoderModelPresent ? 1 : 0, 1);
      if (decoderModelPresent) {
        w.f(rng.nextInt(32), 5); // buffer_delay_length_minus_1
        w.f(rng.nextInt(1 << 16), 32); // num_units_in_decoding_tick
        w.f(rng.nextInt(32), 5); // buffer_removal_time_length_minus_1
        w.f(rng.nextInt(32), 5); // frame_presentation_time_length_minus_1
      }
    }
    initDispPresent = b();
    w.f(initDispPresent ? 1 : 0, 1);
    final opCntM1 = rng.nextInt(3); // 0..2 operating points
    w.f(opCntM1, 5);
    for (var i = 0; i <= opCntM1; i++) {
      w.f(rng.nextInt(1 << 12), 12); // operating_point_idc[i]
      final levelIdx = rng.nextInt(24);
      w.f(levelIdx, 5);
      if (levelIdx > 7) w.f(b() ? 1 : 0, 1); // seq_tier
      if (decoderModelPresent) w.f(0, 1); // decoder_model_present_for_this_op
      if (initDispPresent) {
        final present = b();
        w.f(present ? 1 : 0, 1);
        if (present) w.f(rng.nextInt(16), 4); // initial_display_delay_minus_1
      }
    }
  }

  // frame size
  final wBitsM1 = rng.nextInt(8); // 0..7
  final hBitsM1 = rng.nextInt(8);
  w.f(wBitsM1, 4);
  w.f(hBitsM1, 4);
  w.f(rng.nextInt(1 << (wBitsM1 + 1)), wBitsM1 + 1); // max_frame_width_minus_1
  w.f(rng.nextInt(1 << (hBitsM1 + 1)), hBitsM1 + 1);

  if (!reduced) {
    final frameId = b();
    w.f(frameId ? 1 : 0, 1);
    if (frameId) {
      w.f(rng.nextInt(16), 4); // delta_frame_id_length_minus_2
      w.f(rng.nextInt(8), 3); // additional_frame_id_length_minus_1
    }
  }
  w.f(b() ? 1 : 0, 1); // use_128x128_superblock
  w.f(b() ? 1 : 0, 1); // enable_filter_intra
  w.f(b() ? 1 : 0, 1); // enable_intra_edge_filter

  var orderHint = false;
  if (!reduced) {
    w.f(b() ? 1 : 0, 1); // enable_interintra_compound
    w.f(b() ? 1 : 0, 1); // enable_masked_compound
    w.f(b() ? 1 : 0, 1); // enable_warped_motion
    w.f(b() ? 1 : 0, 1); // enable_dual_filter
    orderHint = b();
    w.f(orderHint ? 1 : 0, 1); // enable_order_hint
    if (orderHint) {
      w.f(b() ? 1 : 0, 1); // enable_jnt_comp
      w.f(b() ? 1 : 0, 1); // enable_ref_frame_mvs
    }
    final chooseScreen = b();
    w.f(chooseScreen ? 1 : 0, 1);
    var forceScreen = 2;
    if (!chooseScreen) {
      forceScreen = rng.nextInt(2);
      w.f(forceScreen, 1);
    }
    if (forceScreen > 0) {
      final chooseIntMv = b();
      w.f(chooseIntMv ? 1 : 0, 1);
      if (!chooseIntMv) w.f(rng.nextInt(2), 1);
    }
    if (orderHint) w.f(rng.nextInt(8), 3); // order_hint_bits_minus_1
  }
  w.f(b() ? 1 : 0, 1); // enable_superres
  w.f(b() ? 1 : 0, 1); // enable_cdef
  w.f(b() ? 1 : 0, 1); // enable_restoration

  // color_config
  final highBd = b();
  w.f(highBd ? 1 : 0, 1);
  var bitDepth = 8;
  if (profile == 2 && highBd) {
    final twelve = b();
    w.f(twelve ? 1 : 0, 1);
    bitDepth = twelve ? 12 : 10;
  } else {
    bitDepth = highBd ? 10 : 8;
  }
  var mono = false;
  if (profile == 1) {
    mono = false;
  } else {
    mono = b();
    w.f(mono ? 1 : 0, 1);
  }
  // Occasionally exercise the BT.709-identity (CL709) color branch.
  final cl709 = !mono && rng.nextInt(4) == 0;
  final colorDescPresent = cl709 || b();
  w.f(colorDescPresent ? 1 : 0, 1);
  var prim = 2, transfer = 2, matrix = 2;
  if (colorDescPresent) {
    if (cl709) {
      prim = 1;
      transfer = 13;
      matrix = 0;
    } else {
      prim = rng.nextInt(256);
      transfer = rng.nextInt(256);
      matrix = rng.nextInt(256);
    }
    w.f(prim, 8);
    w.f(transfer, 8);
    w.f(matrix, 8);
  }
  if (mono) {
    w.f(b() ? 1 : 0, 1); // color_range
  } else if (prim == 1 && transfer == 13 && matrix == 0) {
    // CL709: no color_range read, subX=subY=0, no chroma_sample_position
  } else {
    w.f(b() ? 1 : 0, 1); // color_range
    var subX = 1, subY = 1;
    if (profile == 0) {
      subX = 1;
      subY = 1;
    } else if (profile == 1) {
      subX = 0;
      subY = 0;
    } else {
      if (bitDepth == 12) {
        subX = rng.nextInt(2);
        w.f(subX, 1);
        if (subX != 0) {
          subY = rng.nextInt(2);
          w.f(subY, 1);
        } else {
          subY = 0;
        }
      } else {
        subX = 1;
        subY = 0;
      }
    }
    if (subX != 0 && subY != 0)
      w.f(rng.nextInt(4), 2); // chroma_sample_position
  }
  if (!mono) w.f(b() ? 1 : 0, 1); // separate_uv_delta_q

  w.f(b() ? 1 : 0, 1); // film_grain_params_present
  return w.toBytes(maxBytes);
}

void main() {
