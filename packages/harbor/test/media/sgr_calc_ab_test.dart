void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // Confirm the in-module LUT matches the SW source of truth.
  test('xByXPlus1 / oneByX LUTs match the SW tables', () {
    expect(HarborSgrCalcAb.xByXPlus1, equals(_xByXPlus1));
    expect(HarborSgrCalcAb.oneByX, equals(_oneByX));
  });

  for (final radius in [1, 2]) {
    test('HarborSgrCalcAb matches libaom _calcAb (r=$radius)', () async {
      final n = (2 * radius + 1) * (2 * radius + 1);
      final golden = radius == 1 ? _goldenR1 : _goldenR2;
      final cab = HarborSgrCalcAb(radius: radius);
      final clk = SimpleClockGenerator(10).clk;
      final av = Logic(name: 'av', width: 24);
      final bv = Logic(name: 'bv', width: 16);
      final s = Logic(name: 's', width: 12);
      cab.input('av').srcConnection! <= av;
      cab.input('bv').srcConnection! <= bv;
      cab.input('s').srcConnection! <= s;
      await cab.build();
      Simulator.setMaxSimTime(40000000);
      unawaited(Simulator.run());

      final rng = Random(0x5A6B + radius);
      for (var iter = 0; iter < 1500; iter++) {
        // Draw a plausible box: pixels in [0,255], so bv in [0, n*255] and
        // av in [0, n*255^2], with the realistic av >= mean^2 relation kept by
        // sampling n pixels.
        final px = [for (var t = 0; t < n; t++) rng.nextInt(256)];
        final bvV = px.reduce((a, b) => a + b);
        final avV = px.map((p) => p * p).reduce((a, b) => a + b);
        // s drawn from the real param table plus some random spread.
        final sV = iter % 2 == 0
            ? _sgrParams[rng.nextInt(16)][1][rng.nextInt(2)].clamp(0, 4095)
            : rng.nextInt(4096);
        av.put(avV);
        bv.put(bvV);
        s.put(sV);
        await clk.nextPosedge;
        final want = golden[iter];
        expect(
          cab.output('a').value.toInt(),
          equals(want[0]),
          reason: 'iter=$iter av=$avV bv=$bvV s=$sV a',
        );
        expect(
          cab.output('b').value.toInt(),
          equals(want[1]),
          reason: 'iter=$iter av=$avV bv=$bvV s=$sV b',
        );
      }
      await Simulator.endSimulation();
    });
  }
}
