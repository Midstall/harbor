void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  // Runs the HW module on a `height` x `downW` plane and returns the
  // `height` x `upW` upscaled plane.
  Future<List<List<int>>> runHw(
    HarborSuperresUpscale mod,
    Logic clk,
    Logic planeIn,
    List<List<int>> src,
    int downW,
    int upW,
    int height,
    int bd,
  ) async {
    final mask = (BigInt.one << bd) - BigInt.one;
    var pv = BigInt.zero;
    for (var y = 0; y < height; y++) {
      for (var x = 0; x < downW; x++) {
        pv |= (BigInt.from(src[y][x]) & mask) << ((y * downW + x) * bd);
      }
    }
    planeIn.inject(pv);
    await clk.nextPosedge;
    final v = mod.output('out').value.toBigInt();
    return [
      for (var y = 0; y < height; y++)
        [
          for (var x = 0; x < upW; x++)
            ((v >> ((y * upW + x) * bd)) & mask).toInt(),
        ],
    ];
  }

  // Full elaborate+build+drive+compare for one geometry over several random
  // planes plus deterministic edge-stress planes.
  Future<void> checkGeometry(
    int downW,
    int upW,
    int height,
    int bd,
    int seed, {
    int iters = 6,
  }) async {
    final mod = HarborSuperresUpscale(
      downW: downW,
      upW: upW,
      height: height,
      bd: bd,
      name: 'sr_$seed',
    );
    final clk = SimpleClockGenerator(10).clk;
    final planeIn = Logic(name: 'plane', width: downW * height * bd);
    mod.input('plane').srcConnection! <= planeIn;
    await mod.build();
    Simulator.setMaxSimTime(60000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;

    final rng = Random(seed);
    final pixMax = (1 << bd) - 1;
    for (var iter = 0; iter < iters; iter++) {
      List<List<int>> src;
      if (iter == 0) {
        // Hard left/right edge stress: extreme values at the borders so
        // replicated (out-of-range) taps carry weight.
        src = [
          for (var y = 0; y < height; y++)
            [
              for (var x = 0; x < downW; x++)
                x == 0
                    ? pixMax
                    : (x == downW - 1 ? 0 : (x.isEven ? pixMax : 0)),
            ],
        ];
      } else if (iter == 1) {
        // A ramp (exercises interior filtering monotonically).
        src = [
          for (var y = 0; y < height; y++)
            [for (var x = 0; x < downW; x++) (x * 7 + y * 13) & pixMax],
        ];
      } else {
        src = [
          for (var y = 0; y < height; y++)
            [for (var x = 0; x < downW; x++) rng.nextInt(pixMax + 1)],
        ];
      }

      final got = await runHw(mod, clk, planeIn, src, downW, upW, height, bd);
      final exp = _srGold[seed]![iter];
      expect(
        got,
        equals(exp),
        reason: 'downW=$downW upW=$upW height=$height bd=$bd iter=$iter',
      );
    }
    await Simulator.endSimulation();
  }

  // One geometry per test() so the global Simulator is reset (tearDown)
  // between builds/runs.
  group('HarborSuperresUpscale bit-exact vs SW upscalePlane', () {
    // upW=64 with downW covering superres denominators 9..16
    // (AV1: downW = (upW*8 + denom/2)/denom, SUPERRES_NUM=8): denom 16->32,
    // 14->37, 12->43, 10->51, 9->57, plus the mid case 48.
    for (final downW in [32, 37, 43, 48, 51, 57]) {
      test('upW=64 downW=$downW single row (denominator sweep)', () async {
        await checkGeometry(downW, 64, 1, 8, 0x5150 ^ downW);
      });
    }

    test('multiple rows (48->64, 3 rows)', () async {
      await checkGeometry(48, 64, 3, 8, 0xABCD);
    });

    test('multiple rows (40->64, 4 rows)', () async {
      await checkGeometry(40, 64, 4, 8, 0x1234);
    });

    test('tiny plane strong edges (6->16, 2 rows)', () async {
      await checkGeometry(6, 16, 2, 8, 0x0EDE);
    });

    test('small plane (10->24, 1 row)', () async {
      await checkGeometry(10, 24, 1, 8, 0x7777);
    });

    test('wider upscale (90->120, 2 rows)', () async {
      await checkGeometry(90, 120, 2, 8, 0xBEEF);
    });

    test('wider upscale (100->128, 1 row)', () async {
      await checkGeometry(100, 128, 1, 8, 0xFACE);
    });
  });

  // High-bit-depth (10/12): the module is bd-parameterizable, verify bit-exact
  // vs the same SW upscalePlane at 10 and 12 bits over the denominator sweep and
  // a few multi-row / tiny-edge geometries.
  group('HarborSuperresUpscale hbd (10/12-bit) bit-exact vs SW', () {
    for (final bd in [10, 12]) {
      for (final downW in [32, 43, 48, 57]) {
        test('bd=$bd upW=64 downW=$downW single row', () async {
          await checkGeometry(downW, 64, 1, bd, 0x5150 ^ downW ^ (bd << 8));
        });
      }
      test('bd=$bd multiple rows (48->64, 3 rows)', () async {
        await checkGeometry(48, 64, 3, bd, 0xABCD ^ (bd << 8));
      });
      test('bd=$bd tiny plane strong edges (6->16, 2 rows)', () async {
        await checkGeometry(6, 16, 2, bd, 0x0EDE ^ (bd << 8));
      });
      test('bd=$bd wider upscale (90->120, 2 rows)', () async {
        await checkGeometry(90, 120, 2, bd, 0xBEEF ^ (bd << 8));
      });
    }
  });
}
