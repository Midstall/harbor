void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  const maxBytes = 16;

  for (final txSize in [0, 1]) {
    final syms = txSize == 0 ? _syms0 : _syms1;
    test(
      'HarborTxTypeRead TX_${txSize == 0 ? '4X4' : '8X8'} intra DC matches libaom',
      () async {
        final t = HarborTxTypeRead(maxBytes: maxBytes, txSize: txSize);
        final clk = SimpleClockGenerator(10).clk;
        final reset = Logic(name: 'reset');
        final start = Logic(name: 'start');
        final bytes = Logic(name: 'bytes', width: maxBytes * 8);
        t.input('clk').srcConnection! <= clk;
        t.input('reset').srcConnection! <= reset;
        t.input('start').srcConnection! <= start;
        t.input('bytes').srcConnection! <= bytes;
        await t.build();
        reset.inject(1);
        start.inject(0);
        bytes.inject(0);
        Simulator.setMaxSimTime(20000000);
        unawaited(Simulator.run());
        await clk.nextPosedge;
        reset.inject(0);
        await clk.nextPosedge;

        BigInt packBytes(List<int> b) {
          var v = BigInt.zero;
          for (var i = 0; i < b.length; i++) {
            v |= BigInt.from(b[i] & 0xff) << (i * 8);
          }
          return v;
        }

        final rng = Random(0x7787);
        for (var iter = 0; iter < 300; iter++) {
          final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
          final wantSym = syms[iter];
          final wantType = _extTxInv[wantSym];

          bytes.inject(packBytes(b));
          start.inject(1);
          await clk.nextPosedge;
          start.inject(0);
          var guard = 0;
          while (t.output('done').value.toInt() != 1) {
            await clk.nextPosedge;
            if (++guard > 100) fail('timeout iter=$iter');
          }
          expect(
            t.output('ext_tx_sym').value.toInt(),
            wantSym,
            reason: 'sym iter=$iter',
          );
          expect(
            t.output('tx_type').value.toInt(),
            wantType,
            reason: 'tx_type iter=$iter',
          );
          await clk.nextPosedge;
        }
        await Simulator.endSimulation();
      },
    );
  }
}
