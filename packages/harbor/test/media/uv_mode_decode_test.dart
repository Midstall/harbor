void main() {
  tearDown(() async {
    await Simulator.reset();
  });
  const maxBytes = 16;
  test('HarborUvModeDecode matches libaom uv_mode (cfl not allowed)', () async {
    final t = HarborUvModeDecode(maxBytes: maxBytes);
    final clk = SimpleClockGenerator(10).clk;
    final reset = Logic(name: 'reset');
    final start = Logic(name: 'start');
    final bytes = Logic(name: 'bytes', width: maxBytes * 8);
    final yMode = Logic(name: 'y_mode', width: 4);
    t.input('clk').srcConnection! <= clk;
    t.input('reset').srcConnection! <= reset;
    t.input('start').srcConnection! <= start;
    t.input('bytes').srcConnection! <= bytes;
    t.input('y_mode').srcConnection! <= yMode;
    await t.build();
    reset.inject(1);
    start.inject(0);
    bytes.inject(0);
    yMode.inject(0);
    Simulator.setMaxSimTime(20000000);
    unawaited(Simulator.run());
    await clk.nextPosedge;
    reset.inject(0);
    await clk.nextPosedge;
    BigInt pk(List<int> b) {
      var v = BigInt.zero;
      for (var i = 0; i < b.length; i++) {
        v |= BigInt.from(b[i] & 0xff) << (i * 8);
      }
      return v;
    }

    final rng = Random(0x5151);
    for (var iter = 0; iter < 300; iter++) {
      final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
      final ym = rng.nextInt(13);
      final want = _wantsNotAllowed[iter];
      bytes.inject(pk(b));
      yMode.inject(ym);
      start.inject(1);
      await clk.nextPosedge;
      start.inject(0);
      var g = 0;
      while (t.output('done').value.toInt() != 1) {
        await clk.nextPosedge;
        if (++g > 100) fail('to');
      }
      expect(
        t.output('uv_mode').value.toInt(),
        want,
        reason: 'iter=$iter ym=$ym',
      );
      await clk.nextPosedge;
    }
    await Simulator.endSimulation();
  });

  test(
    'HarborUvModeDecode matches libaom uv_mode (cfl allowed, 14-sym)',
    () async {
      final t = HarborUvModeDecode(maxBytes: maxBytes, cflAllowed: true);
      final clk = SimpleClockGenerator(10).clk;
      final reset = Logic(name: 'reset');
      final start = Logic(name: 'start');
      final bytes = Logic(name: 'bytes', width: maxBytes * 8);
      final yMode = Logic(name: 'y_mode', width: 4);
      t.input('clk').srcConnection! <= clk;
      t.input('reset').srcConnection! <= reset;
      t.input('start').srcConnection! <= start;
      t.input('bytes').srcConnection! <= bytes;
      t.input('y_mode').srcConnection! <= yMode;
      await t.build();
      reset.inject(1);
      start.inject(0);
      bytes.inject(0);
      yMode.inject(0);
      Simulator.setMaxSimTime(20000000);
      unawaited(Simulator.run());
      await clk.nextPosedge;
      reset.inject(0);
      await clk.nextPosedge;
      BigInt pk(List<int> b) {
        var v = BigInt.zero;
        for (var i = 0; i < b.length; i++) {
          v |= BigInt.from(b[i] & 0xff) << (i * 8);
        }
        return v;
      }

      final rng = Random(0x14ce);
      var sawCfl = false;
      for (var iter = 0; iter < 400; iter++) {
        final b = [for (var i = 0; i < maxBytes; i++) rng.nextInt(256)];
        final ym = rng.nextInt(13);
        final want = _wantsAllowed[iter];
        expect(want, inInclusiveRange(0, 13), reason: 'golden sym range');
        if (want == 13) sawCfl = true;
        bytes.inject(pk(b));
        yMode.inject(ym);
        start.inject(1);
        await clk.nextPosedge;
        start.inject(0);
        var g = 0;
        while (t.output('done').value.toInt() != 1) {
          await clk.nextPosedge;
          if (++g > 100) fail('to');
        }
        expect(
          t.output('uv_mode').value.toInt(),
          want,
          reason: 'iter=$iter ym=$ym',
        );
        await clk.nextPosedge;
      }
      expect(
        sawCfl,
        isTrue,
        reason: 'CfL sentinel uv_mode==13 must be reachable in the sweep',
      );
      await Simulator.endSimulation();
    },
  );
}
