void main() {
  tearDown(() async {
    await Simulator.reset();
  });

  test('HarborWarpAffine matches warpAffine inner 8x8 (single pred, bd8)', () async {
    final dut = HarborWarpAffine();
    final clk = SimpleClockGenerator(10).clk;
    final patch = Logic(name: 'patch', width: 15 * 15 * 8);
    final sx4 = Logic(name: 'sx4', width: 20);
    final sy4 = Logic(name: 'sy4', width: 20);
    final alpha = Logic(name: 'alpha', width: 16);
    final beta = Logic(name: 'beta', width: 16);
    final gamma = Logic(name: 'gamma', width: 16);
    final delta = Logic(name: 'delta', width: 16);
    dut.input('patch').srcConnection! <= patch;
    dut.input('sx4').srcConnection! <= sx4;
    dut.input('sy4').srcConnection! <= sy4;
    dut.input('alpha').srcConnection! <= alpha;
    dut.input('beta').srcConnection! <= beta;
    dut.input('gamma').srcConnection! <= gamma;
    dut.input('delta').srcConnection! <= delta;
    await dut.build();
    Simulator.setMaxSimTime(60000000);
    unawaited(Simulator.run());

    final rng = Random(0xA1);

    // Sample a param respecting the AV1 shear constraint and the reduce-bits
    // quantization (multiple of 64), so generated phases stay in 0..192.
    // Shear-allowed: 4|a|+7|b| < 65536, 4|g|+4|d| < 65536. We pick small params
    // (warp is a gentle local warp) that always satisfy this.
    int param() {
      // multiple of 64 in roughly [-2048, 2048] -> well inside shear bounds.
      final v = (rng.nextInt(65) - 32) * 64;
      return v;
    }

    int signedFit(int v, int width) =>
        v & ((1 << width) - 1); // two's complement low bits

    var iters = 0;
    for (var iter = 0; iter < 30; iter++) {
      final a = param();
      final b = param();
      final g = param();
      final d = param();

      // sx4/sy4: emulate a real masked sub-pixel base. The real value is
      // (x4 & 0xFFFF) + alpha*-4 + beta*-4, masked to ~63. Reproduce that.
      final baseX = rng.nextInt(1 << 16);
      final baseY = rng.nextInt(1 << 16);
      var sxv = (baseX + a * -4 + b * -4) & ~63;
      var syv = (baseY + g * -4 + d * -4) & ~63;

      // Guard: ensure all phases land in [0,192] for this golden (true for valid
      // streams). If any escapes, resample params (cheap, rare with our ranges).
      bool phasesOk() {
        for (var k = -7; k < 8; k++) {
          var sx = sxv + b * (k + 4);
          for (var l = -4; l < 4; l++) {
            final o = _rpo(sx, _warpedDiffPrecBits) + _warpedPixelPrecShifts;
            if (o < 0 || o > 192) return false;
            sx += a;
          }
        }
        for (var k = -4; k < 4; k++) {
          final sy = syv + d * (k + 4);
          final o = _rpo(sy, _warpedDiffPrecBits) + _warpedPixelPrecShifts;
          if (o < 0 || o > 192) return false;
        }
        return true;
      }

      var tries = 0;
      while (!phasesOk() && tries < 64) {
        // nudge bases toward centre window (offs centred at 64 => sx near 0).
        sxv = ((rng.nextInt(1 << 12) - 2048) & ~63);
        syv = ((rng.nextInt(1 << 12) - 2048) & ~63);
        tries++;
      }
      if (!phasesOk()) continue; // skip pathological draw

      final px = [for (var i = 0; i < 15 * 15; i++) rng.nextInt(256)];

      var packed = BigInt.zero;
      for (var i = 0; i < px.length; i++) {
        packed |= BigInt.from(px[i]) << (i * 8);
      }
      patch.put(packed);
      sx4.put(signedFit(sxv, 20));
      sy4.put(signedFit(syv, 20));
      alpha.put(signedFit(a, 16));
      beta.put(signedFit(b, 16));
      gamma.put(signedFit(g, 16));
      delta.put(signedFit(d, 16));

      await clk.nextPosedge;

      final gold = _warpGold[iter];
      final pv = dut.output('pred').value;
      for (var k = 0; k < 64; k++) {
        expect(
          pv.getRange(k * 8, k * 8 + 8).toInt(),
          equals(gold[k]),
          reason: 'iter=$iter k=$k a=$a b=$b g=$g d=$d sx=$sxv sy=$syv',
        );
      }
      iters++;
    }
    expect(
      iters,
      greaterThanOrEqualTo(20),
      reason: 'covered $iters iterations',
    );
    await Simulator.endSimulation();
  });
}
